"""Generated roadmap from the graph's milestones: ``research_graph roadmap [--write]``.

One table of every milestone (status, progress, trigger or reached date), then a section per milestone: trigger,
``reached`` evidence, progress and critical path, and the items that move it (``part_of``, open prerequisites
through ``depends_on``, items that name it). Pending milestones come first, then reached ones, newest first. The
output is deterministic, like the kanban, and ``kanban --write`` regenerates both views together.

It is a view: the source of truth stays the graph (``nodes/work.yaml``: a milestone's ``props.trigger`` and
``props.reached``). The default output is ``notes/roadmap_graph.md`` (``roadmap_graph.md`` in the folder ``--views``
names); a file without the GENERATED marker (a
hand-written roadmap) is never overwritten, and the marker written before the engine was its own package is still
recognised. ``graph check`` flags a stale view. Another store's node an edge names (``--foreign-store``) is shown by
its id and that store's label: an item that moves a milestone, a sub-milestone, a parent, a step of the critical path.
"""

from __future__ import annotations

import re
from pathlib import Path

import networkx as nx

from .kanban import VIEWS, view_path
from .query import roadmap

FILE = "roadmap_graph.md"
DEFAULT_OUT = f"{VIEWS}/{FILE}"
MARKER = "<!-- GENERATED by `research_graph roadmap --write`"
# also a generated view: the marker written by the engine under another module path (python -m <pkg>.research_graph)
GENERATED = re.compile(r"<!-- GENERATED by `(python -m [\w.]+\.)?research_graph roadmap --write`")


def _row_line(row: dict) -> str:
    box = "x" if row["status"] == "done" else " "
    name = f"{row['id']} ({row['store']})" if row.get("store") else row["id"]
    text = f"{name} — {row['title']}".rstrip(" —")
    if row["status"] == "dropped":
        text = f"~~{text}~~"
    notes = [] if row["status"] in ("done", "todo", "dropped") else [row["status"]]
    if row.get("priority"):
        notes.insert(0, row["priority"])
    return f"- [{box}] {text}" + (f" ({', '.join(notes)})" if notes else "")


def _names(m: dict, ids) -> list[str]:
    """Ids as the view shows them: another store's node with that store's label (``ms-x (parent:graph)``)."""
    stores = m.get("stores") or {}
    return [f"{n} ({stores[n]})" if n in stores else n for n in ids]


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render_roadmap(graph: nx.DiGraph) -> str:
    ms = roadmap(graph)
    counts: dict[str, int] = {}
    for m in ms:
        counts[m["status"]] = counts.get(m["status"], 0) + 1
    out = [
        f"{MARKER} from the graph's milestones (also written by `kanban --write`). Do not edit: change a "
        "milestone's trigger / reached props in the store's nodes, then regenerate. -->",
        "",
        "# Roadmap (generated from the graph's milestones)",
        "",
        f"{len(ms)} milestones: " + (", ".join(f"{k} {v}" for k, v in counts.items()) or "none") + ". "
        "A milestone is reached when its trigger is met (`props.reached`: date and evidence). Read it from the "
        "command line with `research_graph roadmap`.",
        "",
        "| Milestone | Status | Items done | Trigger, or reached on |",
        "|---|---|---|---|",
    ]
    for m in ms:
        done = m["by_status"].get("done", 0)
        when = m["reached_date"] if m["status"] == "reached" and m["reached_date"] else (m["trigger"] or "-")
        out.append(f"| {m['id']} — {_cell(m['title'])} | {m['status']} | {done}/{m['items']} | {_cell(when)} |")
    for m in ms:
        out += ["", f"## {m['id']}" + (f" — {m['title']}" if m["title"] else "") + f" [{m['status']}]", ""]
        if m["trigger"]:
            out.append(f"Trigger: {m['trigger']}")
        if m["reached"]:
            out.append(f"Reached: {m['reached']}")
        if m["note"]:
            out.append(f"Note: {m['note']}")
        progress = ", ".join(f"{k} {v}" for k, v in m["by_status"].items())
        line = f"Items: {m['items']}" + (f" ({progress})" if progress else "")
        if m["cycle"]:
            line += ". Critical path: dependency cycle among open items"
        elif m["critical_path"]:
            line += ". Critical path: " + " → ".join(_names(m, m["critical_path"]))
        out.append(line + ".")
        if m["parents"]:
            out.append("Part of: " + ", ".join(_names(m, m["parents"])) + ".")
        if m["sub_milestones"]:
            out.append("Sub-milestones: " + ", ".join(_names(m, m["sub_milestones"])) + ".")
        for key, heading in (("part_of", "Moved by its items (part_of)"),
                             ("depends_on", "Open prerequisites outside it (depends_on)"),
                             ("mentions", "Items that name it")):
            if m[key]:
                out += ["", f"{heading}:", ""] + [_row_line(r) for r in m[key]]
    return "\n".join(out) + "\n"


def write_roadmap(graph: nx.DiGraph, path: str | Path) -> Path:
    """Write the view to ``path``; refuse to overwrite a file that is not a generated view."""
    path = Path(path)
    if path.exists() and not GENERATED.match(path.read_text(encoding="utf-8")):
        raise FileExistsError(
            f"{path} exists and is not a generated view (no GENERATED marker): refusing to overwrite it"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_roadmap(graph), encoding="utf-8", newline="\n")
    return path


def roadmap_stale(graph: nx.DiGraph, repo_root: str | Path, views: str | Path | None = None) -> list[str]:
    """Advisory: the generated view (in the folder ``views``, default notes) exists but no longer matches the graph."""
    rel = view_path(FILE, views)
    path = Path(repo_root) / rel
    if not path.exists() or path.read_text(encoding="utf-8") == render_roadmap(graph):
        return []
    return [f"{rel} is stale: run `research_graph kanban --write`"]
