"""Generated kanban view of the work layer: ``research_graph kanban [--write]``.

Renders the graph's WorkItems as markdown. The work frontier (what can start now) comes first. Each milestone
follows, with its trigger, progress and remaining critical path, then its items by status with their blockers:
dependencies not yet satisfied, and external blockers from ``props.external_blocker``. Items attached to no
milestone come last. The output is deterministic (sorted, no timestamp), so a regenerated view diffs cleanly.

It is a view. The source of truth stays the store's ``nodes/*.yaml`` and ``edges/*.yaml``. The default output is
``notes/kanban_graph.md``, which starts with a GENERATED marker; a file without that marker (a hand-written board) is
never overwritten. A marker naming the engine under another module path (``python -m <pkg>.research_graph``, from
before it was its own package) is still recognised. ``graph check`` flags a stale view.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

import networkx as nx

from .model import WORK_OPEN, LayeredGraph

DEFAULT_OUT = "notes/kanban_graph.md"
MARKER = "<!-- GENERATED by `research_graph kanban --write`"
# also a generated view: the marker written by the engine under another module path (python -m <pkg>.research_graph)
GENERATED = re.compile(r"<!-- GENERATED by `(python -m [\w.]+\.)?research_graph kanban --write`")
STATUS_ORDER = ("doing", "todo", "blocked", "done", "dropped")
MILESTONE_ORDER = {"pending": 0, "reached": 1, "dropped": 2}


def _of_type(rg: LayeredGraph, nodes, node_type: str) -> list[str]:
    return sorted(n for n in nodes if rg.g.nodes[n].get("type") == node_type)


def _parts(rg: LayeredGraph, mid: str, node_type: str) -> list[str]:
    """Direct ``part_of`` members of a milestone of one type (WorkItem or sub-Milestone)."""
    return _of_type(
        rg,
        (s for s, _, e in rg.g.in_edges(mid, data=True) if e.get("type") == "part_of"),
        node_type,
    )


def _milestones_of(rg: LayeredGraph, nid: str) -> list[str]:
    targets = (d for _, d, e in rg.g.out_edges(nid, data=True) if e.get("type") == "part_of")
    return _of_type(rg, targets, "Milestone")


def _by_status(rg: LayeredGraph, items: list[str]) -> list[str]:
    rank = {s: i for i, s in enumerate(STATUS_ORDER)}
    return sorted(items, key=lambda n: (rank.get(rg.g.nodes[n].get("status"), len(rank)), n))


def _item(rg: LayeredGraph, nid: str, frontier: set[str], *, in_frontier: bool = False) -> str:
    """One checklist line: id and title, then what holds the item (dependencies, external) or that it can start.
    In the frontier section every item is startable, so the line names its milestones instead."""
    a = rg.g.nodes[nid]
    status = a.get("status")
    text = f"{nid} — {a.get('title') or ''}".rstrip(" —")
    if status == "dropped":
        text = f"~~{text}~~"
    if in_frontier and _milestones_of(rg, nid):
        text += f" ({', '.join(_milestones_of(rg, nid))})"
    notes = ["startable"] if nid in frontier and not in_frontier else []
    if status == "doing":
        notes.append("doing")
    if status in WORK_OPEN:
        blockers = rg.blockers(nid)
        if blockers:
            notes.append(
                "blocked by " + ", ".join(f"{b} [{rg.g.nodes[b].get('status')}]" for b in blockers)
            )
        if status == "blocked":
            reason = (a.get("props") or {}).get("external_blocker")
            notes.append(f"external: {reason}" if reason else "external blocker")
    box = "x" if status == "done" else " "
    return f"- [{box}] {text}" + (f"  ← {'; '.join(notes)}" if notes else "")


def render_kanban(graph: nx.DiGraph) -> str:
    rg = LayeredGraph(graph)
    items = _of_type(rg, graph.nodes, "WorkItem")
    frontier = set(rg.work_frontier())
    blocked = rg.blocked()
    counts = Counter(graph.nodes[n].get("status") for n in items)
    out = [
        f"{MARKER} from the graph's work layer. Do not edit: change the store's nodes/*.yaml and edges/*.yaml, "
        "then regenerate. -->",
        "",
        "# Work board (generated from the graph)",
        "",
        f"{len(items)} work items: "
        + ", ".join(f"{s} {counts[s]}" for s in STATUS_ORDER if counts[s])
        + f". Startable now: {len(frontier)}. Cannot proceed: {len(blocked)}.",
        "",
        "## Startable now",
        "",
    ]
    out += [_item(rg, n, frontier, in_frontier=True) for n in sorted(frontier)] or ["(none)"]

    milestones = _of_type(rg, graph.nodes, "Milestone")
    milestones.sort(key=lambda m: (MILESTONE_ORDER.get(graph.nodes[m].get("status"), 3), m))
    for m in milestones:
        info = rg.milestone(m)
        title = graph.nodes[m].get("title")
        out += ["", f"## {m}" + (f" — {title}" if title else "") + f" [{info['status']}]", ""]
        if info["trigger"]:
            out.append(f"Trigger: {info['trigger']}")
        progress = ", ".join(f"{k} {v}" for k, v in info["by_status"].items())
        line = f"Items: {info['items']}" + (f" ({progress})" if progress else "")
        if info["cycle"]:
            line += ". Critical path: dependency cycle among open items"
        elif info["critical_path"]:
            line += ". Critical path: " + " → ".join(info["critical_path"])
        out.append(line + ".")
        parents = _milestones_of(rg, m)
        subs = _parts(rg, m, "Milestone")
        if parents:
            out.append("Part of: " + ", ".join(parents) + ".")
        if subs:
            out.append(
                "Sub-milestones: "
                + ", ".join(f"{s} [{graph.nodes[s].get('status')}]" for s in subs)
                + "."
            )
        direct = _parts(rg, m, "WorkItem")
        if direct:
            out.append("")
            out += [_item(rg, n, frontier) for n in _by_status(rg, direct)]

    loose = [n for n in items if not _milestones_of(rg, n)]
    if loose:
        out += ["", "## No milestone", ""]
        out += [_item(rg, n, frontier) for n in _by_status(rg, loose)]
    return "\n".join(out) + "\n"


def write_kanban(graph: nx.DiGraph, path: str | Path) -> Path:
    """Write the view to ``path``; refuse to overwrite a file that is not a generated view."""
    path = Path(path)
    if path.exists() and not GENERATED.match(path.read_text(encoding="utf-8")):
        raise FileExistsError(
            f"{path} exists and is not a generated view (no GENERATED marker): refusing to overwrite it"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_kanban(graph), encoding="utf-8", newline="\n")
    return path


def kanban_stale(graph: nx.DiGraph, repo_root: str | Path) -> list[str]:
    """Advisory: the generated view exists but no longer matches the graph."""
    path = Path(repo_root) / DEFAULT_OUT
    if not path.exists() or path.read_text(encoding="utf-8") == render_kanban(graph):
        return []
    return [f"{DEFAULT_OUT} is stale: run `research_graph kanban --write`"]
