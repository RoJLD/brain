"""The generated views and their one writer (wi-brain-views-one-writer; docs/views.md).

A view is what the merge driver calls one (brain.mergedriver): a tracked file whose first lines say ``GENERATED by```
(the kanban, the roadmap, the plan and module maps, the decision queue, the audit, FEATURES.md) or whose name starts
with ``_generated_`` (the graph's derived nodes and edges). Every branch used to regenerate and commit them, so every
merge of the default branch into a branch met them; the merge driver then kept one side and marked it.

One writer instead: a branch need not commit its views, and the default branch gets them regenerated once after each
merge, by ``brain views --write`` run in a worktree at the default branch's tip (its sync, the audit view, then the
files it changed listed, committed with ``--commit``). Where it runs decides what ``brain check`` asks of the views:

- on the default branch (HEAD is origin/HEAD's target, else main, else master): a stale view is an error;
- on any other branch, or a detached HEAD: a stale view is said on one ``views:`` line, never required;
- outside a git checkout: the warnings as before.

On a branch, ``brain views --unstage`` keeps the views out of a commit after ``git add`` (the working tree keeps them
regenerated, for the branch's own checks), and ``brain views --reset`` puts them back at HEAD before a merge of the
default branch (a local change to a file the merge brings would stop it). A branch that still commits its views keeps
working: nothing refuses it, and the merge driver's view kind stays the fallback for its merges.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from . import actions, tidy
from .mergedriver import GENERATED, HEAD_LINES

PREFIX = "_generated_"
SUFFIXES = (".md", ".yaml", ".yml")
WRITER = "brain views --write"   # the one writer's command, named in the messages and the procedures


def is_view(path: str, head: str = "") -> bool:
    """Whether ``path`` is a generated view: a ``_generated_`` name, or ``GENERATED by``` in ``head`` (its first
    lines), as the merge driver's view kind (brain.mergedriver.kind_of)."""
    name = Path(path.replace("\\", "/")).name.lower()
    if name.startswith(PREFIX):
        return True
    return Path(name).suffix in SUFFIXES and bool(GENERATED.search(head))


def head_of(f: Path) -> str:
    try:
        with f.open(encoding="utf-8", errors="replace") as fh:
            return "".join(fh.readline() for _ in range(HEAD_LINES))
    except OSError:
        return ""


def _paths(text: str) -> list[str]:
    """The paths of a ``git ... -z`` listing."""
    return [p for p in text.split("\0") if p]


def _git(root: Path, *args: str) -> str:
    return actions.git(root, *args, timeout=30)


def _views_of(root: Path, paths: list[str]) -> list[str]:
    """Those of ``paths`` (relative to ``root``) that are views, read in the working tree."""
    return [p for p in paths if p.lower().endswith(SUFFIXES) and is_view(p, head_of(root / p))]


def tracked(root: Path) -> list[str]:
    """The views git tracks under ``root``, relative to it (posix)."""
    return _views_of(root, _paths(_git(root, "ls-files", "-z")))


def changed(root: Path) -> list[str]:
    """The tracked views that differ from HEAD, in the index or the working tree."""
    return _views_of(root, _paths(_git(root, "diff", "--name-only", "--relative", "-z", "HEAD", "--")))


def staged(root: Path) -> list[str]:
    """The views staged for the next commit (a new view included)."""
    return _views_of(root, _paths(_git(root, "diff", "--cached", "--name-only", "--relative", "-z", "--")))


@dataclass
class Place:
    """Where a checkout stands for its views: ``default`` (HEAD on the default branch), ``branch`` (any other branch,
    or a detached HEAD) or ``''`` (not a git checkout with a commit)."""
    where: str
    branch: str = ""    # HEAD's branch ('HEAD' when detached)
    default: str = ""   # the default branch's name ('' when none is found)

    def line(self) -> str:
        if self.where == "default":
            return f"on {self.branch}, the default branch: its views must be fresh ({WRITER} writes them)"
        if self.where == "branch":
            on = "a detached HEAD" if self.branch == "HEAD" else f"branch {self.branch}"
            return (f"on {on}: its views need not be fresh nor committed; {WRITER} writes them on "
                    f"{self.default or 'the default branch'} after the merge")
        return "not a git checkout: the views are checked as warnings"


def place(root: Path) -> Place:
    """Where ``root`` stands: on the default branch (origin/HEAD's target, else main, else master: brain.tidy), on
    another branch, or outside git."""
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if not branch:
        return Place("")
    default, _ = tidy.default_branch(root)
    return Place("default" if default and branch == default else "branch", branch, default)


@dataclass
class Stale:
    """The stale views a check found: (the path relative to the root, the command that rewrites it)."""
    views: list[tuple[str, str]] = field(default_factory=list)

    def add(self, path: str, fix: str = "brain sync") -> None:
        if path not in [p for p, _ in self.views]:
            self.views.append((path, fix))


def verdict(stale: Stale, where: Place, legacy: dict[str, str] | None = None) -> tuple[int, list[str]]:
    """(1 when the default branch holds a stale view, else 0; the lines brain check prints). ``legacy``: the label an
    earlier engine's warning gave a path, kept outside a git checkout."""
    if not stale.views:
        return 0, []
    if where.where == "default":
        return 1, [f"error: {p} is stale on {where.branch}, the default branch: {WRITER} (the one writer, from a "
                   f"worktree at {where.branch}'s tip; docs/views.md), or {fix}" for p, fix in stale.views]
    if where.where == "branch":
        names = ", ".join(p for p, _ in stale.views)
        return 0, [f"views: {len(stale.views)} stale here ({names}), not required on a branch: brain sync refreshes "
                   f"them for this branch's checks; {WRITER} writes them on {where.default or 'the default branch'} "
                   "after the merge"]
    legacy = legacy or {}
    return 0, [f"warning: {legacy.get(p, p)} is stale: {fix}" for p, fix in stale.views]


# --- the branch side: keep them out of a commit, put them back before a merge ---

def unstage(root: Path) -> list[str]:
    """The staged views taken out of the index (the working tree keeps them): the next commit leaves them as HEAD
    has them. A view new to the branch is unstaged too (it stays untracked)."""
    views = staged(root)
    if views:
        actions.git(root, "reset", "-q", "--", *views, timeout=60)
    left = staged(root)
    return [v for v in views if v not in left]


def reset(root: Path) -> list[str]:
    """The tracked views put back at HEAD, in the index and the working tree (before ``git merge`` of the default
    branch: a local change to a file it brings would stop the merge); ``brain sync`` writes them again after."""
    views = changed(root)
    old = set(_views_of(root, _paths(_git(root, "diff", "--name-only", "--relative", "-z", "--diff-filter=MDT",
                                          "HEAD", "--"))))
    if old:   # in HEAD: back as HEAD has them
        actions.git(root, "checkout", "-q", "HEAD", "--", *sorted(old), timeout=60)
    new = [v for v in views if v not in old]
    if new:   # a view new to the branch, staged: unstaged, its file left untracked
        actions.git(root, "reset", "-q", "--", *new, timeout=60)
    return [v for v in views if v not in changed(root)]


# --- the writer's side: what it changed, committed ---

def dirty(root: Path) -> set[str]:
    """Every path that differs from HEAD (index or working tree) or is untracked, relative to ``root``."""
    diff = _paths(_git(root, "diff", "--name-only", "--relative", "-z", "HEAD", "--"))
    new = _paths(_git(root, "ls-files", "--others", "--exclude-standard", "-z"))
    return set(diff) | set(new)


def commit(root: Path, paths: list[str], message: str) -> str:
    """``paths`` staged and committed alone (``git commit --only``: what else was staged stays staged); the new
    commit's short id, '' when git refused."""
    if not paths:
        return ""
    before = _git(root, "rev-parse", "HEAD")
    actions.git(root, "add", "--", *paths, timeout=60)
    actions.git(root, "commit", "-q", "-m", message, "--only", "--", *paths, timeout=120)
    after = _git(root, "rev-parse", "HEAD")
    return after[:7] if after and after != before else ""


def status(root: Path, as_json: bool = False, out=None) -> int:
    """``brain views``: the tracked views, where this checkout stands, those changed here and staged, and the ones the
    merge driver kept from one side."""
    from . import mergedriver
    where = place(root)
    data = {"place": where.where, "branch": where.branch, "default": where.default, "tracked": tracked(root),
            "changed": changed(root) if where.where else [], "staged": staged(root) if where.where else [],
            "merge_marks": mergedriver.marked(root)}
    if as_json:
        print(json.dumps(data, indent=2), file=out)
        return 0
    lines = [f"views: {len(data['tracked'])} tracked (a GENERATED marker in their first lines, or a {PREFIX} name)",
             f"place: {where.line()}"]
    lines += [f"  {p}" + ("  (changed here" + (", staged" if p in data["staged"] else "") + ")"
                          if p in data["changed"] else "") for p in data["tracked"]]
    if where.where == "branch" and data["staged"]:
        lines.append(f"staged: {len(data['staged'])} view(s); brain views --unstage keeps them out of the commit "
                     "(committing them is allowed too: the merge driver keeps one side)")
    if data["merge_marks"]:
        lines.append(f"merge driver: {len(data['merge_marks'])} kept from one side at the last merge "
                     f"({', '.join(data['merge_marks'])}): brain refresh, or {WRITER} on the default branch")
    print("\n".join(lines), file=out)
    return 0
