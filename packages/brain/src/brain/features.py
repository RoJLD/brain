"""``brain features``: the feature matrix (spec 2026-10-30 section 3.11; Q6, the owner 2026-10-30: the graph as
source, a generated table, a SQLite index for search, vectors later; ADR "La matrice des features : le graphe comme
source").

The source is the graph: one Feature node per capability, its status ``have``, ``partial``, ``planned`` or ``no``,
its props ``domain``, ``repo`` (the owner repo), ``value`` (strategic value: high, medium, low) and ``module`` (the
module of the owner's platform, a slot the module layer fills; nothing here depends on it), and its edges
``implemented_by`` (a CodeRef), ``specified_by`` (a Spec), ``tested_by`` (a Test), ``documented_in`` (a Doc),
``decided_by`` (an ADR) and ``part_of`` (a parent Feature); a WorkItem ``delivers`` a Feature. Three things come
from it and are never edited:

- ``FEATURES.md`` at the root of each repo, the matrix by domain (``brain features render --write``, run by
  ``brain sync``); ``brain audit`` checks it is the render of the committed graph (check ``features.md``);
- a SQLite index with full-text search (FTS5, standard library), a cache under ``<BRAIN_HOME>/features`` rebuilt when
  the store's files change: ``brain features list|search|show``;
- the status: ``brain sync`` reads the merged PRs that name a feature with a status (``feat-brain-x: have``) and sets
  it, with the PR as evidence (``status_pr``, ``status_merged``); never a hook.
"""

