"""Signed engine releases (wi-brain-release-signing, STD-3): a release tag is verified against the releasers'
public keys before it is installed, so that a tag pushed from a compromised account does not install.

- **The releasers** are the people with the ``releaser`` role on the whole brain in ``members.yaml`` (brain.identity),
  with their SSH ed25519 signing keys not revoked.
- **allowed_signers** (:data:`FILE`, beside config.json) is the file git reads (``gpg.ssh.allowedSignersFile``):
  one line per releaser key, valid for the namespace ``git`` only (a tag or commit signature; a ``brain-decision``
  signature verifies nothing here, nor the reverse). It is **generated** from members.yaml
  (``brain identity allowed-signers --write``), never edited by hand, and committed with the brain; the engine's
  installer reads it before the brain command exists. Publishing it elsewhere later is an export of that file, not a
  code change. Without the file, ``brain update`` generates the same text from members.yaml in a temporary folder.
- :func:`verify_remote` fetches the tag alone into a temporary repo (``git fetch --depth 1``), runs
  ``git verify-tag`` there with that file, and returns the commit the signed tag names. pip then installs the tag (a
  release is read by its tag, brain.skew), and :func:`installed_commit` checks that the commit pip recorded is that
  one: a tag moved between the check and the install is said, refused under the opt-in below.
- **Nothing is refused by default**: ``brain update`` and the installer report the verification either way; config.json
  ``engine.verify_tags: true`` (the owner's opt-in) turns a tag that is unsigned, signed by an unknown key, or that
  cannot be verified into a refusal.

The engine never signs and never reads a private key: the owner signs each tag in their own terminal
(``git tag -s``, ``gpg.format ssh``; docs/release.md).
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
from pathlib import Path

from . import config, sshsig

FILE = "allowed_signers"
RELEASER = "releaser"
NAMESPACE = "git"   # what git signs a tag or a commit for (ssh-keygen -Y sign -n git)
TIMEOUT_S = 60.0
HEADER = (f"# Generated by brain identity allowed-signers from members.yaml (role {RELEASER}, namespace {NAMESPACE}): "
          "do not edit; regenerate with --write\n")
GOOD_RE = re.compile(r'Good "git" signature for (\S+) with')
CANNOT_RUN_RE = re.compile(r"cannot run|No such file|not recognized", re.I)   # git found no ssh-keygen to run

VERIFIED, UNSIGNED, UNKNOWN_KEY, NO_SIGNERS, UNVERIFIABLE = (
    "verified", "unsigned", "unknown-key", "no-signers", "unverifiable")


# --- the allowed signers, generated from members.yaml ---

def releasers(data: dict) -> dict[str, list[str]]:
    """{person_id: [public key]} of the people with the releaser role on the whole brain (not a project's, an
    organization's or a tenant's), their signing keys not revoked."""
    from . import identity

    who = set()
    for m in identity._list(data, "memberships"):
        roles = m.get("roles")
        if isinstance(roles, list) and RELEASER in roles and not (m.get("project") or m.get("organization")
                                                                   or m.get("tenant")):
            who.add(identity._id(m))
    return {p["person_id"]: [_bare(k["key"]) for k in identity._signing(p)]
            for p in identity._list(data, "people") if identity._id(p) in who - {None} and identity._signing(p)}


def _bare(key: str) -> str:
    """A public key without its comment (type and base64 only): the comment often names a machine, and the file may
    be published one day."""
    return " ".join(key.split()[:2])


def _from_members(root: Path) -> str | None:
    """The allowed_signers text members.yaml gives ('' when no releaser has a key); None when there is no
    members.yaml or it has errors (nothing to compare with)."""
    from . import identity

    m = identity.load(root)
    if m is None or m.errors:
        return None
    keys = releasers(m.data)
    return HEADER + sshsig.allowed_signers(keys, NAMESPACE) if keys else ""


def generate(root: Path) -> str:
    """The allowed_signers text members.yaml gives (:data:`HEADER`, then one line per releaser key); '' when there is
    no members.yaml, it has errors, or no releaser has a key."""
    return _from_members(root) or ""


def signers_file(root: Path | None) -> Path | None:
    """allowed_signers beside the brain's config.json; None without a config.json."""
    cfg = config.load(root)
    return cfg.file.parent / FILE if cfg.file else None


def signers(root: Path | None) -> tuple[str, str]:
    """(the allowed-signers text, where it comes from) for brain update: the text members.yaml gives when it is there
    and valid, so that a key revoked or a role taken away stops verifying at once, even before the file is written
    again; else the file beside config.json (a brain without members.yaml: a published file); ('', '') when neither
    has a key. The installer, which runs before the brain command exists, reads the file only."""
    f = signers_file(root)
    if f is None:
        return "", ""
    text = _from_members(f.parent)
    if text is not None:
        return (text, f"members.yaml, role {RELEASER}") if text else ("", "")
    text = f.read_text(encoding="utf-8", errors="replace") if f.is_file() else ""
    return (text, str(f)) if _lines(text) else ("", "")


def _lines(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]


def write(root: Path, out: Path | None = None) -> Path:
    """Write the generated text to ``out`` (default: :func:`signers_file`); ValueError when there is nothing to
    write."""
    text = generate(root)
    if not text:
        raise ValueError(f"no person has the {RELEASER} role with a signing key in members.yaml "
                         "(docs/identity.md, « Signed releases »)")
    dest = out or signers_file(root)
    if dest is None:
        raise ValueError("no config.json: the brain's root is unknown (--write FILE)")
    from . import stateio

    stateio.write_atomic(dest, text)
    return dest


def required(root: Path | None) -> bool:
    """config.json engine.verify_tags: the owner's opt-in that refuses a tag not verified."""
    eng = config.load(root).data.get("engine")
    return isinstance(eng, dict) and eng.get("verify_tags") is True


def problems(root: Path) -> list[str]:
    """What brain check warns of: allowed_signers no longer what members.yaml gives (a key added, rotated or
    revoked since it was written), or engine.verify_tags on while no key can verify a tag."""
    f = signers_file(root)
    if f is None:
        return []
    want = _from_members(f.parent)
    out = []
    if f.is_file() and want is not None and f.read_text(encoding="utf-8", errors="replace") != want:
        fix = ("brain identity allowed-signers --write, then commit it" if want else
               f"no releaser key is left in members.yaml: delete {FILE}, or declare a releaser key and write it again")
        out.append(f"{FILE}: not what members.yaml's {RELEASER} keys give (the installer still trusts it): {fix}")
    if required(root) and not (f.is_file() and _lines(f.read_text(encoding="utf-8", errors="replace"))):
        out.append(f"config.json engine.verify_tags is on and no {FILE} is written beside it: the installer refuses "
                   "every tag (brain identity allowed-signers --write)")
    return out


# --- verifying a tag ---

def repo_url(repo: str) -> str:
    """The git URL of an engine repo, owner/name on GitHub."""
    return f"https://github.com/{repo}.git"


def _git(args: list[str], cwd: Path | None, runner) -> subprocess.CompletedProcess:
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0", "GCM_INTERACTIVE": "never"}
    cmd = ["git", "-c", "credential.helper=", *args]
    try:
        return runner(cmd, capture_output=True, text=True, timeout=TIMEOUT_S, stdin=subprocess.DEVNULL, env=env,
                      cwd=str(cwd) if cwd else None)
    except (OSError, subprocess.SubprocessError) as exc:   # git missing, a timeout: said, never raised
        return subprocess.CompletedProcess(cmd, 127, "", str(exc))


def verdict(status: str, tag: str, *, signer: str = "", commit: str = "", why: str = "", source: str = "") -> dict:
    return {"status": status, "tag": tag, "signer": signer, "commit": commit, "why": why, "source": source}


def verify_remote(url: str, tag: str, allowed: str, *, source: str = "", program: str = "",
                  runner=subprocess.run) -> dict:
    """The tag ``tag`` of the git repo ``url`` fetched alone into a temporary repo and checked with
    ``git verify-tag`` against the allowed-signers text ``allowed``: :func:`verdict` with ``status`` verified (and
    the releaser's principal and the commit the tag names), unsigned, unknown-key or unverifiable. git runs its own
    ssh-keygen, as the installer's does (``program``, tests, names another)."""
    if not _lines(allowed):
        return verdict(NO_SIGNERS, tag, why=f"no {FILE}: no releaser key to verify {tag} with", source=source)
    with tempfile.TemporaryDirectory(prefix="brain-tag-", ignore_cleanup_errors=True) as tmp:
        work = Path(tmp) / "repo"
        init = _git(["init", "--quiet", str(work)], None, runner)
        if init.returncode != 0:
            return verdict(UNVERIFIABLE, tag, why=f"git init failed: {_said(init)}", source=source)
        ref = f"refs/tags/{tag}"
        got = _git(["fetch", "--quiet", "--no-tags", "--depth", "1", "--filter=tree:0", url, f"+{ref}:{ref}"], work,
                   runner)
        if got.returncode != 0:
            return verdict(UNVERIFIABLE, tag, why=f"git fetch {tag} failed (offline?): {_said(got)}", source=source)
        kind = (_git(["cat-file", "-t", ref], work, runner).stdout or "").strip()
        commit = (_git(["rev-parse", "--verify", f"{ref}^{{commit}}"], work, runner).stdout or "").strip()
        if not kind or not commit:
            return verdict(UNVERIFIABLE, tag, why=f"git could not read the fetched {tag}", source=source)
        if kind != "tag":
            return verdict(UNSIGNED, tag, commit=commit, why=f"{tag} is a lightweight tag: no signature",
                           source=source)
        allowed_file = Path(tmp) / FILE
        allowed_file.write_text(allowed, encoding="utf-8", newline="\n")
        conf = ["-c", f"gpg.ssh.allowedSignersFile={allowed_file.as_posix()}"]
        # ssh-keygen, git's default, even when the owner's git config names a signing program (an agent's, which may
        # not verify)
        conf += ["-c", f"gpg.ssh.program={Path(program).as_posix() if program else 'ssh-keygen'}"]
        checked = _git([*conf, "verify-tag", "--raw", ref], work, runner)
    said = f"{checked.stdout or ''}\n{checked.stderr or ''}"
    good = GOOD_RE.search(said)
    if checked.returncode == 0 and good:
        return verdict(VERIFIED, tag, signer=good.group(1), commit=commit, source=source)
    if re.search(r"no signature found", said, re.I):
        return verdict(UNSIGNED, tag, commit=commit, why=f"{tag} carries no signature", source=source)
    if checked.returncode == 127 or CANNOT_RUN_RE.search(said):
        return verdict(UNVERIFIABLE, tag, commit=commit, why=f"git verify-tag could not run: {_said(checked)}",
                       source=source)
    return verdict(UNKNOWN_KEY, tag, commit=commit, why=f"{tag} is not signed by a key of {FILE}: {_said(checked)}",
                   source=source)


def _said(proc) -> str:
    lines = [ln.strip() for ln in f"{proc.stdout or ''}\n{proc.stderr or ''}".splitlines() if ln.strip()]
    return " / ".join(lines[-3:]) or f"exit {proc.returncode}"


def verify(root: Path | None, repo: str, tag: str, *, runner=subprocess.run) -> dict:
    """The release tag ``tag`` of the engine repo ``repo`` verified with this brain's allowed signers
    (:func:`signers`); no network when there is none (status no-signers)."""
    allowed, source = signers(root)
    if not allowed:
        return verdict(NO_SIGNERS, tag, why=f"no {RELEASER} key (members.yaml, else {FILE} beside config.json)")
    return verify_remote(repo_url(repo), tag, allowed, source=source, runner=runner)


def line(v: dict | None, required_: bool) -> str:
    """The verification in one line, as brain update's plan and the installer say it."""
    if not v:
        return ""
    if v["status"] == VERIFIED:
        return f"{v['tag']}: signed by {v['signer']} ({v['source'] or FILE}), commit {v['commit'][:12]}"
    then = ("refused: config.json engine.verify_tags is on" if required_
            else "not refused: config.json engine.verify_tags is off")
    return f"{v['tag']}: not verified, {v['why']} ({then})"


def installed_commit(site_packages: list[Path], dist: str, repo: str = "") -> str:
    """The commit pip recorded for a distribution installed from git (its dist-info's direct_url.json), when it came
    from ``repo`` (owner/name; any repo when empty); '' otherwise."""
    for sp in site_packages:
        for d in sorted(sp.glob(f"{dist}-*.dist-info")) if sp.is_dir() else []:
            try:
                data = json.loads((d / "direct_url.json").read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if not isinstance(data, dict) or (repo and f"/{repo.lower()}" not in str(data.get("url", "")).lower()):
                continue
            commit = (data.get("vcs_info") or {}).get("commit_id")
            if isinstance(commit, str):
                return commit
    return ""
