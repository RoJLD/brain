"""The module map (wi-brain-module-map): each open item's module, ``props.module`` (its primary, one) and
``props.modules_secondary`` (a list), against the registry of modules the store keeps, ``<store>/modules.yaml`` (or
the one config.json ``modules.store`` names, below); the generated view ``notes/modules_graph.md`` (brain sync;
``modules_graph.md`` beside the store's other views when they are not in notes/, brain.projects.views_dir) and brain
check's warnings. Zero token. A store that reads no registry is not concerned.

The registry is a YAML list, one entry per module:
``{id: P2, name: kettle-core, brick: P, phase: MVP, status: tree, lab: now, since: 2026-08-01, note: ...}``:
``phase`` the product's phase the platform's tree gives it (MVP, V1.5, V2, V3, P5...), ``status`` ``tree`` (in the
platform's tree) or ``proposed`` (proposed by the brain, waiting on the owner), ``lab`` the brain's own phase,
``since`` the day a proposed module was proposed. An open item's ``props.module`` is an id of the registry, or
``none`` with ``props.module_reason`` (outside the tree: the brain's own process).

The features (``Feature`` nodes) and the done items carry a module too, which the technical reference reads
(wi-brain-module-backfill): the view counts how many are placed, and brain check warns (never fails) about one with no
module, or one the registry does not know; ``brain modules --check`` lists them as warnings, its exit code being the
open items' only.

The view gives, per brick then per module: its phase and status, its state in the brain (items done and open with it
as primary, open items with it as secondary), its open items, and the gaps: a module with no item done or open, a
proposed one with none since 90 days (to put back to sleep), an item whose module the registry does not know. It
holds no date of its own: it changes only when the registry or the items do.

**A registry kept in another store** (wi-brain-module-registry-import): a store without its own ``modules.yaml`` reads
the one ``config.json`` ``modules.store`` names, a store of the projects registry (brain.crossstore) given as
``<project>:<store relative to its root>`` or by its project's name (that project's first store that keeps one). The
owner's opt-in: without the key a store reads only its own, as before. Its items are checked against that registry,
and its view names it.

**An imported registry** (wi-brain-module-registry-import): a session that reads the platform's documents writes the
entries' document fields (:data:`DRIVE`: name, brick, phase, status, placement, definition, the dependencies the
documents declare, their divergences) with ``source``, the documents read (``[{ref, date}]``), and ``imported``, the day of the
import; the engine never reads those documents. ``brain modules --check`` validates the imported entries only (an
entry with ``source`` or ``imported``): a hand entry is checked as before. The view then generates the counts (in the
tree, proposed, by brick), lists the documents read and the divergences the import reported (never settled by the
brain), and ``brain modules --diff [REF]`` says what changed since the registry's version at a git ref: the modules
added and removed, the document fields changed, and the hand fields changed (an import never touches them).
"""

from __future__ import annotations

import json
import re
import subprocess
from collections import Counter
from datetime import date, datetime, timedelta
from pathlib import Path

from . import graph

REGISTRY = "modules.yaml"
# The fields an import writes from the platform's documents (wi-brain-module-registry-import); every other field of an
# entry (lab, since, note, and the map's own) is written by hand and never touched by an import.
DRIVE = ("name", "brick", "phase", "status", "placement", "definition", "declared", "divergences", "source",
         "imported")
SOURCE, IMPORTED = "source", "imported"
STATUSES = ("tree", "proposed")
FILE = "modules_graph.md"
VIEW = f"notes/{FILE}"   # the view of a project's first store at a root it owns
NONE = "none"
DORMANT_DAYS = 90
OPEN = ("todo", "doing", "blocked")
HEAD = ("# Modules\n\nGENERATED by `brain sync` (brain.modules) from the items' `props.module` and the registry "
        "`{reg}`. Do not edit: set an item's module with `brain item set <id> props.module=<id>`, or change the "
        "registry.\n")


def named(root: Path | None, store: Path | None = None) -> str:
    """The store ``config.json`` ``modules.store`` names: '' without the key, with no root to read it from, or for a
    ``store`` outside the personal brain's root (config.json's folder): another project's store, at its own root,
    never reads that registry."""
    if root is None:
        return ""
    from . import config
    cfg = config.load(root)
    m = cfg.data.get("modules")
    s = m.get("store") if isinstance(m, dict) else None
    if not isinstance(s, str) or not s.strip():
        return ""
    if store is not None and not _under(store, cfg.root):
        return ""
    return s.strip()


def _under(store: Path, folder: Path) -> bool:
    """Whether ``store`` is under ``folder`` (config.json's), or under a worktree of the checkout ``folder`` is in:
    config.json found in the main checkout ($BRAIN_CONFIG, the machine's pointer) applies to its worktrees' stores."""
    store = store.resolve()
    if store.is_relative_to(folder):
        return True
    from . import paths
    main, mine, top = paths.main_checkout(folder), paths.main_checkout(store), _toplevel(store)
    if main is None or mine is None or top is None or main.resolve() != mine.resolve():
        return False
    folder, main = folder.resolve(), main.resolve()
    return folder.is_relative_to(main) and (top / folder.relative_to(main)) in (store, *store.parents)


def _toplevel(d: Path) -> Path | None:
    try:
        out = subprocess.run(["git", "-C", str(d), "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                             timeout=10, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None
    return Path(out.stdout.strip()).resolve() if out.returncode == 0 and out.stdout.strip() else None


def lookup(store: Path, root: Path | None) -> tuple[str, Path] | None:
    """(label, store) of the registry ``store`` reads when it keeps none: the store of the projects registry that
    ``config.json`` ``modules.store`` names (its label ``<project>:<store>``, or its project's name: that project's
    first store with a ``modules.yaml``), for a store under config.json's folder; None without the key, for another
    store, or when no such store keeps one."""
    want = named(root, store)
    if not want:
        return None
    from . import crossstore, projects
    try:
        found = crossstore.stores(list(projects.load(root).values()))
    except (OSError, ValueError, graph._yaml().YAMLError):   # an unreadable registry: brain check --all says why
        return None
    for label, s in found:
        if (label == want or label.split(":", 1)[0] == want) and (s / REGISTRY).is_file():
            return label, s
    return None


def registry_file(store: Path, root: Path | None = None) -> Path | None:
    """The registry ``store`` reads: its own ``modules.yaml``, else the one :func:`lookup` finds; None for neither."""
    if (store / REGISTRY).is_file():
        return store / REGISTRY
    found = lookup(store, root)
    return found[1] / REGISTRY if found else None


def registry_label(store: Path, store_label: str, root: Path | None = None) -> str:
    """How the view names the registry: ``<store label>/modules.yaml``, or ``<project>:<store>/modules.yaml`` for
    one read in another store."""
    if (store / REGISTRY).is_file():
        return f"{store_label}/{REGISTRY}"
    found = lookup(store, root)
    return f"{found[0]}/{REGISTRY}" if found else f"{store_label}/{REGISTRY}"


def registry(store: Path, root: Path | None = None) -> list[dict] | None:
    """The registry's entries (those with an id), None when the store reads none (:func:`registry_file`)."""
    f = registry_file(store, root)
    if f is None:
        return None
    return [m for m in graph.load_yaml_list(f) if isinstance(m, dict) and m.get("id")]


def applies(store: Path, root: Path | None = None) -> bool:
    return registry_file(store, root) is not None


def items(store: Path, node_type: str = "WorkItem") -> list[dict]:
    """The store's nodes of ``node_type`` (its WorkItem nodes by default) that have an id (one without is
    research_graph check's to report)."""
    out = []
    for f in sorted((store / "nodes").glob("*.yaml")):
        out += [n for n in graph.load_yaml_list(f) if isinstance(n, dict) and n.get("type") == node_type
                and n.get("id")]
    return out


def _props(n: dict) -> dict:
    return n.get("props") if isinstance(n.get("props"), dict) else {}


def _secondary(n: dict) -> list[str]:
    """props.modules_secondary: a list, or a string of ids separated by commas (as brain item set writes it)."""
    s = _props(n).get("modules_secondary") or []
    s = re.split(r"[,\s]+", s.strip("[] ")) if isinstance(s, str) else s if isinstance(s, list) else []
    return list(dict.fromkeys(str(x) for x in s if str(x)))   # an id given twice counts once


def problems(store: Path, root: Path | None = None) -> list[str]:
    """What brain check warns about: an open item with no module, ``none`` without its reason, a module or a
    secondary module the registry does not know, a secondary that repeats the primary."""
    reg = registry(store, root)
    if reg is None:
        return []
    known, out = {str(m["id"]) for m in reg}, []
    for n in items(store):
        if n.get("status") not in OPEN:
            continue
        nid, p = n["id"], _props(n)
        mod = str(p.get("module") or "")
        if not mod:
            out.append(f"{nid}: no props.module (a module of {REGISTRY}, or none with props.module_reason)")
        elif mod == NONE and not p.get("module_reason"):
            out.append(f"{nid}: props.module is none without props.module_reason")
        elif mod != NONE and mod not in known:
            out.append(f"{nid}: props.module {mod} is not in {REGISTRY}")
        for s in _secondary(n):
            if s not in known:
                out.append(f"{nid}: props.modules_secondary {s} is not in {REGISTRY}")
            elif s == mod:
                out.append(f"{nid}: props.modules_secondary repeats its module {s}")
    return out


FEATURE = "Feature"
SHOWN = 10   # the ids a warning names before « and N more »


def placed_nodes(store: Path) -> dict[str, list[dict]]:
    """The nodes beyond the open items that the reference reads by module (wi-brain-module-backfill): the features
    (``Feature`` nodes, any status) and the done items."""
    return {"features": items(store, FEATURE), "done": [n for n in items(store) if n.get("status") == "done"]}


def unplaced(store: Path, root: Path | None = None) -> dict[str, list[str]]:
    """The features and the done items with no ``props.module``, by kind (``features``, ``done``): the ids, sorted.
    A store without a registry is not concerned (empty lists)."""
    if not applies(store, root):
        return {"features": [], "done": []}
    return {kind: sorted(str(n["id"]) for n in nodes if not str(_props(n).get("module") or ""))
            for kind, nodes in placed_nodes(store).items()}


def _placed_line(store: Path, root: Path | None = None) -> list[str]:
    """The view's line on what the reference reads by module (wi-brain-module-backfill), then a blank line; none for
    a store with no feature and no done item."""
    more, missing = placed_nodes(store), unplaced(store, root)
    if not (more["features"] or more["done"]):
        return []
    return [f"Features placed: {len(more['features']) - len(missing['features'])} of {len(more['features'])}; "
            f"done items placed: {len(more['done']) - len(missing['done'])} of {len(more['done'])}.", ""]


def _named(ids: list[str]) -> str:
    more = len(ids) - SHOWN
    return ", ".join(ids[:SHOWN]) + (f" and {more} more" if more > 0 else "")


def warnings(store: Path, root: Path | None = None) -> list[str]:
    """What brain check warns about beyond :func:`problems`, never a failure (``brain modules --check`` does not
    count them either): the features and the done items with no module, one line per kind, and those whose module is
    not in the registry or is ``none`` without its reason, one line each. Once a brain has placed them all
    (wi-brain-module-backfill), a line here names a new one."""
    reg = registry(store, root)
    if reg is None:
        return []
    known, out = {str(m["id"]) for m in reg}, []
    missing = unplaced(store, root)
    how = {"features": ("feature(s)", "brain features set <id> module=<module>"),
           "done": ("done item(s)", "brain item set <id> props.module=<module>")}
    for kind, nodes in placed_nodes(store).items():
        if missing[kind]:
            what, cmd = how[kind]
            out.append(f"{len(missing[kind])} {what} with no props.module: {_named(missing[kind])} ({cmd})")
        for n in sorted(nodes, key=lambda n: str(n["id"])):
            mod, p = str(_props(n).get("module") or ""), _props(n)
            if mod == NONE and not p.get("module_reason"):
                out.append(f"{n['id']}: props.module is none without props.module_reason")
            elif mod and mod != NONE and mod not in known:
                out.append(f"{n['id']}: props.module {mod} is not in {REGISTRY}")
    return out


# --- an imported registry (wi-brain-module-registry-import) ---

def is_imported(m: dict) -> bool:
    """An entry an import wrote: it carries the import's shape, ``source`` a list of mappings or ``imported`` a day.
    A hand entry that happens to hold another ``source`` (a text, a note) or ``imported: false`` stays a hand entry,
    checked as before."""
    src = m.get(SOURCE)
    return (isinstance(src, list) and all(isinstance(s, dict) for s in src)) or _day(m.get(IMPORTED)) is not None


def _day(value) -> date | None:
    """A day as YAML gives it (a date, a timestamp: its day, or a YYYY-MM-DD string); None for anything else."""
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return date.fromisoformat(str(value or ""))
    except ValueError:
        return None


def _strings(value) -> bool:
    return isinstance(value, list) and all(isinstance(x, str) and x.strip() for x in value)


def _check_fields(mid: str, m: dict) -> list[str]:
    """An imported entry's required document fields and its status."""
    out = [f"{mid}: imported without {key}" for key in ("name", "brick", "phase") if not str(m.get(key) or "").strip()]
    if m.get("status") not in STATUSES:
        out.append(f"{mid}: imported with status {m.get('status')!r} (one of {', '.join(STATUSES)})")
    return out


def _check_source(mid: str, i: int, s, day: date | None) -> list[str]:
    """One document of an entry's ``source``: its ref, its date (not after the import), the fields it gave."""
    ref = str(s.get("ref") or "").strip() if isinstance(s, dict) else ""
    if not ref:
        return [f"{mid}: source {i} has no ref (the document read)"]
    out, when, fields = [], _day(s.get("date")), s.get("fields")
    if when is None:
        out.append(f"{mid}: source {ref} has no date (the document's, YYYY-MM-DD)")
    elif day is not None and when > day:
        out.append(f"{mid}: source {ref} is dated {when}, after the import of {day}")
    if fields is not None and not (_strings(fields) and set(fields) <= set(DRIVE[:-2])):
        out.append(f"{mid}: source {ref} fields must list document fields ({', '.join(DRIVE[:-2])})")
    return out


def _check_provenance(mid: str, m: dict) -> list[str]:
    """An imported entry's ``source`` (each document) and ``imported`` (the day)."""
    src, day = m.get(SOURCE), _day(m.get(IMPORTED))
    out = [] if isinstance(src, list) and src else \
        [f"{mid}: imported without source (the documents read: a list of {{ref, date}})"]
    for i, s in enumerate(src if isinstance(src, list) else [], 1):
        out += _check_source(mid, i, s, day)
    return out + ([] if day else [f"{mid}: imported without imported (the day of the import, YYYY-MM-DD)"])


def _check_lists(mid: str, m: dict, known: set[str]) -> list[str]:
    """An imported entry's ``declared`` (module ids the registry knows), texts and ``divergences``."""
    declared, out = m.get("declared"), []
    if declared is not None and not _strings(declared):
        out.append(f"{mid}: declared must be a list of module ids")
    elif declared is not None:
        out += [f"{mid}: declared {d} is not in {REGISTRY}" for d in declared if d not in known]
    out += [f"{mid}: {key} must be a text" for key in ("placement", "definition")
            if m.get(key) is not None and not isinstance(m[key], str)]
    if m.get("divergences") is not None and not _strings(m["divergences"]):
        out.append(f"{mid}: divergences must be a list of texts")
    return out


def _check_entry(m: dict, known: set[str]) -> list[str]:
    mid = str(m["id"])
    return _check_fields(mid, m) + _check_provenance(mid, m) + _check_lists(mid, m, known)


def registry_problems(store: Path, root: Path | None = None) -> list[str]:
    """What ``brain modules --check`` refuses in the registry's imported entries (:func:`is_imported`): a document
    field missing (name, brick, phase), a status other than tree or proposed, no source (the documents read, each a
    ref and its date, none after the import, its ``fields`` document fields), no day of import, a ``placement`` or
    ``definition`` that is not a text, a ``declared`` that is not a list of ids the registry knows, ``divergences``
    that are not texts, an id given twice (:func:`_check_entry`). A hand entry is checked as before: never here."""
    reg = registry(store, root) or []
    known, twice = {str(m["id"]) for m in reg}, Counter(str(m["id"]) for m in reg)
    out = []
    for m in reg:
        if not is_imported(m):
            continue
        if twice[str(m["id"])] > 1:
            out.append(f"{m['id']}: imported, and its id is given {twice[str(m['id'])]} times in {REGISTRY}")
        out += _check_entry(m, known)
    return list(dict.fromkeys(out))


def tally(reg: list[dict]) -> dict:
    """The registry's counts, generated (never written by hand): in the tree, proposed, in all, and by brick."""
    bricks: dict[str, dict[str, int]] = {}
    for m in reg:
        b = bricks.setdefault(str(m.get("brick") or "?"), {"tree": 0, "proposed": 0})
        b["proposed" if m.get("status") == "proposed" else "tree"] += 1
    tree = sum(b["tree"] for b in bricks.values())
    proposed = sum(b["proposed"] for b in bricks.values())
    return {"tree": tree, "proposed": proposed, "all": tree + proposed, "bricks": dict(sorted(bricks.items()))}


def _id_key(mid: str) -> tuple:
    return len(mid), mid


def _show(value) -> str:
    return json.dumps(value, ensure_ascii=False, default=str)


def diff(old: list[dict] | None, new: list[dict]) -> dict:
    """What changed from ``old`` (a registry's earlier entries; None: there was none) to ``new``: the modules added
    and removed, each document field changed (:data:`DRIVE`) and each hand field changed, as ``<id>.<field>: <old> ->
    <new>`` lines, the modules whose provenance only (``source``, ``imported``) changed, by id, and the counts on both
    sides."""
    before = {str(m["id"]): m for m in old or []}
    after = {str(m["id"]): m for m in new}
    drive, hand, provenance = [], [], []
    for mid in sorted(set(before) & set(after), key=_id_key):
        a, b = before[mid], after[mid]
        for key in sorted((set(a) | set(b)) - {"id"}):
            if a.get(key) == b.get(key):
                continue
            if key in (SOURCE, IMPORTED):   # the documents read and the day: one id each, not a line per field
                provenance += [] if mid in provenance else [mid]
                continue
            line = f"{mid}.{key}: {_show(a.get(key))} -> {_show(b.get(key))}"
            (drive if key in DRIVE else hand).append(line)
    return {"added": sorted(set(after) - set(before), key=_id_key),
            "removed": sorted(set(before) - set(after), key=_id_key),
            "drive": drive, "hand": hand, "provenance": provenance,
            "before": tally(old or []) if old is not None else None, "after": tally(new)}


def _git(d: Path, *args: str) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(["git", "-C", str(d), *args], capture_output=True, text=True, encoding="utf-8",
                              errors="replace", timeout=60, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None


def at_ref(f: Path, ref: str) -> list[dict] | None:
    """The registry file ``f`` as it was at the git ref ``ref`` (its entries with an id); None when that commit does
    not hold it (a registry not committed yet: every module is new). Raises ValueError when ``ref`` is no commit of
    the repo ``f`` is in (a typo, another repo's ref, no repository: never read as « all new »), or when the file at
    ``ref`` does not parse."""
    if not ref or ref.startswith("-"):
        raise ValueError(f"{ref!r} is not a git ref")
    found = _git(f.parent, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    if found is None or found.returncode:
        raise ValueError(f"{ref} is no commit of the git repository at {f.parent}")
    out = _git(f.parent, "show", f"{ref}:./{f.name}")
    if out is None or out.returncode:
        return None
    try:
        data = graph.load_yaml(out.stdout)
    except graph._yaml().YAMLError as exc:
        raise ValueError(f"{f.name} at {ref} does not parse ({exc})") from exc
    return [m for m in data if isinstance(m, dict) and m.get("id")] if isinstance(data, list) else []


def diff_lines(d: dict, label: str, ref: str) -> list[str]:
    """``brain modules --diff``'s report of :func:`diff`."""
    def total(c):
        return f"{c['all']} modules ({c['proposed']} proposed)" if c else "none"
    out = [f"registry: {label}, against {ref}",
           f"counts: {total(d['before'])} -> {total(d['after'])}" + ("" if d["before"] is not None else
                                                                      f" ({ref} has no {REGISTRY}: all are new)")]
    for key, what in (("added", "added"), ("removed", "removed")):
        out.append(f"{what} ({len(d[key])}): " + (", ".join(d[key]) or "none"))
    out.append(f"document fields changed ({len(d['drive'])})" + (":" if d["drive"] else ""))
    out += [f"  {line}" for line in d["drive"]]
    if d["provenance"]:
        out.append(f"sources or day of import changed ({len(d['provenance'])}): " + ", ".join(d["provenance"]))
    if d["hand"]:   # an import never writes them: a line here is a hand change, or an import that went too far
        out.append(f"hand fields changed ({len(d['hand'])}): an import never touches them")
        out += [f"  {line}" for line in d["hand"]]
    return out


def _import_lines(reg: list[dict]) -> list[str]:
    """The view's lines on an imported registry: the generated counts, the documents read and the divergences the
    import reported. None for a registry with no imported entry: its view is what it was."""
    got = [m for m in reg if is_imported(m)]
    if not got:
        return []
    c = tally(reg)
    out = ["", "## Counts", "",
           f"Generated from the registry: {c['tree']} in the tree, {c['proposed']} proposed, {c['all']} in all "
           f"({len(got)} imported).", "", "| Brick | In the tree | Proposed |", "|---|---|---|"]
    out += [f"| {b} | {n['tree']} | {n['proposed']} |" for b, n in c["bricks"].items()]
    days = sorted({str(_day(m.get(IMPORTED))) for m in got if _day(m.get(IMPORTED))})
    out += ["", "## The import", "", f"Imported {', '.join(days) or '?'} from the documents below; the brain never "
            "edits these fields: a correction goes to the documents, then to a new import.", ""]
    out += [f"- {ref} ({when or 'no date'}): {n} module(s)" for ref, (when, n) in _documents(got)] or ["- None."]
    out += ["", "## Divergences between the documents", "",
            "Reported by the import, never settled by the brain: the owner settles them in the documents.", ""]
    return out + ([f"- {mid}: {_cell(d)}" for mid, d in _divergences(got)] or ["None."])


def _sources(m: dict) -> list[dict]:
    """An entry's documents that name a ref."""
    src = m.get(SOURCE) if isinstance(m.get(SOURCE), list) else []
    return [s for s in src if isinstance(s, dict) and str(s.get("ref") or "").strip()]


def _documents(got: list[dict]) -> list[tuple[str, tuple[str, int]]]:
    """(ref, (its latest date, how many entries it gave)) of every document the imported entries name, by ref."""
    docs: dict[str, tuple[str, int]] = {}
    for s in (s for m in got for s in _sources(m)):
        ref = _cell(s["ref"])
        when, n = docs.get(ref, ("", 0))
        docs[ref] = (max(when, str(_day(s.get("date")) or "")), n + 1)
    return sorted(docs.items())


def _divergences(got: list[dict]) -> list[tuple[str, str]]:
    """(module id, text) of every divergence the import reported, by module."""
    return [(str(m["id"]), d) for m in sorted(got, key=lambda m: _id_key(str(m["id"])))
            for d in (m.get("divergences") if _strings(m.get("divergences")) else [])]


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _short(text: str, n: int = 90) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def _since(m: dict) -> date | None:
    try:
        return date.fromisoformat(str(m.get("since") or ""))
    except ValueError:
        return None


def _index(nodes: list[dict]) -> tuple[dict[str, list], dict[str, list]]:
    """Module -> the items with it as primary (any status), and -> the open items with it as secondary."""
    primary: dict[str, list] = {}
    secondary: dict[str, list] = {}
    for n in nodes:
        mod = str(_props(n).get("module") or "")
        if mod:
            primary.setdefault(mod, []).append(n)
        for s in _secondary(n) if n.get("status") in OPEN else []:
            secondary.setdefault(s, []).append(n)
    return primary, secondary


def _order(reg: list[dict]) -> list[tuple[str, dict]]:
    """(brick, module) sorted by brick, then by id (P2 before P12)."""
    return sorted(((str(m.get("brick") or "?"), m) for m in reg),
                  key=lambda bm: (bm[0], len(str(bm[1]["id"])), str(bm[1]["id"])))


def _gaps(reg: list[dict], counts, primary: dict[str, list]) -> list[str]:
    out = []
    for m in reg:
        d, o, _ = counts(str(m["id"]))
        since = _since(m)
        if d or o:
            continue
        if m.get("status") == "proposed" and since:
            out.append(f"- {m['id']} ({m.get('name', '')}): proposed {since}, no item done or open: back to sleep "
                       f"from {since + timedelta(days=DORMANT_DAYS)} if none comes")
        else:
            out.append(f"- {m['id']} ({m.get('name', '')}): no item done or open in the brain")
    known = {str(m["id"]) for m in reg}
    out += [f"- {mod}: {len(primary[mod])} item(s) name it, the registry does not know it"
            for mod in sorted(set(primary) - known - {NONE})]
    return out or ["None."]


def _section(b: str, m: dict, counts, primary: dict[str, list], secondary: dict[str, list]) -> list[str]:
    mid = str(m["id"])
    d, o, s = counts(mid)
    out = ["", f"## {mid}", "",
           f"**{_cell(m.get('name', ''))}**, brick {b}: phase {m.get('phase') or '?'}, {m.get('status', 'tree')}"
           + (f", in the lab {m['lab']}" if m.get("lab") else "") + f". In the brain: {d} done, {o} open, {s} open "
           "as secondary."]
    if m.get("note"):
        out += ["", _cell(m["note"])]
    rows = sorted((n for n in primary.get(mid, []) if n.get("status") in OPEN), key=lambda n: n["id"])
    if rows:
        out += [""] + [f"- `{n['id']}` [{_props(n).get('priority', '-')}] {_short(n.get('title', ''))}" for n in rows]
    if secondary.get(mid):
        out += ["", "Secondary: " + ", ".join(f"`{n['id']}`" for n in sorted(secondary[mid], key=lambda n: n["id"]))]
    return out


def data(store: Path, root: Path | None = None) -> dict:
    """The map as data (brain modules --json): each module with its counts, the open items placed, the problems."""
    reg, nodes = registry(store, root) or [], items(store)
    primary, secondary = _index(nodes)
    opened = [n for n in nodes if n.get("status") in OPEN]
    mods = []
    for b, m in _order(reg):
        got = primary.get(str(m["id"]), [])
        mods.append({**{k: m[k] for k in ("id", "name", "phase", "status", "lab", "since") if k in m}, "brick": b,
                     "done": sum(1 for n in got if n.get("status") == "done"),
                     "open": sum(1 for n in got if n.get("status") in OPEN),
                     "secondary": len(secondary.get(str(m["id"]), []))})
    more, missing = placed_nodes(store), unplaced(store, root)
    return {"modules": mods, "open_items": len(opened),
            "placed": sum(1 for n in opened if _props(n).get("module")),
            "outside": sum(1 for n in opened if _props(n).get("module") == NONE), "problems": problems(store, root),
            "features": len(more["features"]), "features_unplaced": missing["features"],
            "done_items": len(more["done"]), "done_unplaced": missing["done"], "warnings": warnings(store, root),
            **_import_data(store, root, reg)}


def _import_data(store: Path, root: Path | None, reg: list[dict]) -> dict:
    """brain modules --json's keys on the import (wi-brain-module-registry-import): the counts, how many entries are
    imported, their problems."""
    return {"counts": tally(reg), "imported": len([m for m in reg if is_imported(m)]),
            "registry_problems": registry_problems(store, root)}


def render(store: Path, store_label: str = "notes/graph", root: Path | None = None) -> str:
    reg = registry(store, root) or []
    nodes = items(store)
    primary, secondary = _index(nodes)

    def counts(mid: str) -> tuple[int, int, int]:
        got = primary.get(mid, [])
        return (sum(1 for n in got if n.get("status") == "done"), sum(1 for n in got if n.get("status") in OPEN),
                len(secondary.get(mid, [])))

    opened = [n for n in nodes if n.get("status") in OPEN]
    nones = sorted((n for n in opened if _props(n).get("module") == NONE), key=lambda n: n["id"])
    out = [HEAD.format(reg=registry_label(store, store_label, root)),
           f"**{len(reg)} modules ({sum(1 for m in reg if m.get('status') == 'proposed')} proposed); "
           f"{sum(1 for n in opened if _props(n).get('module'))} of {len(opened)} open items placed, "
           f"{len(nones)} outside the tree.**", "", *_placed_line(store, root),
           "| Module | Name | Brick | Phase | Status | Done | Open | Secondary |", "|---|---|---|---|---|---|---|---|"]
    for b, m in _order(reg):
        d, o, s = counts(str(m["id"]))
        out.append(f"| [{m['id']}](#{str(m['id']).lower()}) | {_cell(m.get('name', ''))} | {b} | "
                   f"{_cell(m.get('phase', ''))} | {_cell(m.get('status', 'tree'))} | {d} | {o} | {s} |")
    out += ["", "## Gaps", ""] + _gaps(reg, counts, primary)
    out += _import_lines(reg)
    for b, m in _order(reg):
        out += _section(b, m, counts, primary, secondary)
    out += ["", "## Outside the tree", ""] + ([f"- `{n['id']}`: {_cell(_props(n).get('module_reason', ''))}"
                                               for n in nones] or ["None."])
    return "\n".join(out) + "\n"


def write(root: Path, store: Path, store_label: str = "notes/graph", view: str = VIEW) -> bool:
    """Write the view (``view``, relative to ``root``); True when it changed."""
    f = root / view
    text = render(store, store_label, root)
    if f.is_file() and f.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8", newline="\n")
    return True


def stale(root: Path, store: Path, store_label: str = "notes/graph", view: str = VIEW) -> bool:
    f = root / view
    return not f.is_file() or f.read_text(encoding="utf-8").replace("\r\n", "\n") != render(store, store_label, root)
