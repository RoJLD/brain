"""The module map (wi-brain-module-map): each open item's module, ``props.module`` (its primary, one) and
``props.modules_secondary`` (a list), against the registry of modules the store keeps, ``<store>/modules.yaml``;
the generated view ``notes/modules_graph.md`` (brain sync; ``modules_graph.md`` beside the store's other views when
they are not in notes/, brain.projects.views_dir) and brain check's warnings. Zero token. A store without
a registry is not concerned.

The registry is a YAML list, one entry per module:
``{id: P2, name: kettle-core, brick: P, phase: MVP, status: tree, lab: now, since: 2026-08-01, note: ...}``:
``phase`` the product's phase the platform's tree gives it (MVP, V1.5, V2, V3, P5...), ``status`` ``tree`` (in the
platform's tree) or ``proposed`` (proposed by the brain, waiting on the owner), ``lab`` the brain's own phase,
``since`` the day a proposed module was proposed. An open item's ``props.module`` is an id of the registry, or
``none`` with ``props.module_reason`` (outside the tree: the brain's own process).

The features (``Feature`` nodes) and the done items carry a module too, which the technical reference reads
(wi-brain-module-backfill): the view counts how many are placed, and brain check warns (never fails) about one with no
module, or one the registry does not know; ``brain modules --check`` lists them as warnings, its exit code being the
open items' only.

The view gives, per brick then per module: its phase and status, its state in the brain (items done and open with it
as primary, open items with it as secondary), its open items, and the gaps: a module with no item done or open, a
proposed one with none since 90 days (to put back to sleep), an item whose module the registry does not know. It
holds no date of its own: it changes only when the registry or the items do.
"""

from __future__ import annotations

import re
from datetime import date, timedelta
from pathlib import Path

from . import graph

REGISTRY = "modules.yaml"
FILE = "modules_graph.md"
VIEW = f"notes/{FILE}"   # the view of a project's first store at a root it owns
NONE = "none"
DORMANT_DAYS = 90
OPEN = ("todo", "doing", "blocked")
HEAD = ("# Modules\n\nGENERATED by `brain sync` (brain.modules) from the items' `props.module` and the registry "
        "`{reg}`. Do not edit: set an item's module with `brain item set <id> props.module=<id>`, or change the "
        "registry.\n")


def registry(store: Path) -> list[dict] | None:
    """The registry's entries (those with an id), None when the store keeps none."""
    f = store / REGISTRY
    if not f.is_file():
        return None
    return [m for m in graph.load_yaml_list(f) if isinstance(m, dict) and m.get("id")]


def applies(store: Path) -> bool:
    return (store / REGISTRY).is_file()


def items(store: Path, node_type: str = "WorkItem") -> list[dict]:
    """The store's nodes of ``node_type`` (its WorkItem nodes by default) that have an id (one without is
    research_graph check's to report)."""
    out = []
    for f in sorted((store / "nodes").glob("*.yaml")):
        out += [n for n in graph.load_yaml_list(f) if isinstance(n, dict) and n.get("type") == node_type
                and n.get("id")]
    return out


def _props(n: dict) -> dict:
    return n.get("props") if isinstance(n.get("props"), dict) else {}


def _secondary(n: dict) -> list[str]:
    """props.modules_secondary: a list, or a string of ids separated by commas (as brain item set writes it)."""
    s = _props(n).get("modules_secondary") or []
    s = re.split(r"[,\s]+", s.strip("[] ")) if isinstance(s, str) else s if isinstance(s, list) else []
    return list(dict.fromkeys(str(x) for x in s if str(x)))   # an id given twice counts once


def problems(store: Path) -> list[str]:
    """What brain check warns about: an open item with no module, ``none`` without its reason, a module or a
    secondary module the registry does not know, a secondary that repeats the primary."""
    reg = registry(store)
    if reg is None:
        return []
    known, out = {str(m["id"]) for m in reg}, []
    for n in items(store):
        if n.get("status") not in OPEN:
            continue
        nid, p = n["id"], _props(n)
        mod = str(p.get("module") or "")
        if not mod:
            out.append(f"{nid}: no props.module (a module of {REGISTRY}, or none with props.module_reason)")
        elif mod == NONE and not p.get("module_reason"):
            out.append(f"{nid}: props.module is none without props.module_reason")
        elif mod != NONE and mod not in known:
            out.append(f"{nid}: props.module {mod} is not in {REGISTRY}")
        for s in _secondary(n):
            if s not in known:
                out.append(f"{nid}: props.modules_secondary {s} is not in {REGISTRY}")
            elif s == mod:
                out.append(f"{nid}: props.modules_secondary repeats its module {s}")
    return out


FEATURE = "Feature"
SHOWN = 10   # the ids a warning names before « and N more »


def placed_nodes(store: Path) -> dict[str, list[dict]]:
    """The nodes beyond the open items that the reference reads by module (wi-brain-module-backfill): the features
    (``Feature`` nodes, any status) and the done items."""
    return {"features": items(store, FEATURE), "done": [n for n in items(store) if n.get("status") == "done"]}


def unplaced(store: Path) -> dict[str, list[str]]:
    """The features and the done items with no ``props.module``, by kind (``features``, ``done``): the ids, sorted.
    A store without a registry is not concerned (empty lists)."""
    if not applies(store):
        return {"features": [], "done": []}
    return {kind: sorted(str(n["id"]) for n in nodes if not str(_props(n).get("module") or ""))
            for kind, nodes in placed_nodes(store).items()}


def _named(ids: list[str]) -> str:
    more = len(ids) - SHOWN
    return ", ".join(ids[:SHOWN]) + (f" and {more} more" if more > 0 else "")


def warnings(store: Path) -> list[str]:
    """What brain check warns about beyond :func:`problems`, never a failure (``brain modules --check`` does not
    count them either): the features and the done items with no module, one line per kind, and those whose module is
    not in the registry or is ``none`` without its reason, one line each. Once a brain has placed them all
    (wi-brain-module-backfill), a line here names a new one."""
    reg = registry(store)
    if reg is None:
        return []
    known, out = {str(m["id"]) for m in reg}, []
    missing = unplaced(store)
    how = {"features": ("feature(s)", "brain features set <id> module=<module>"),
           "done": ("done item(s)", "brain item set <id> props.module=<module>")}
    for kind, nodes in placed_nodes(store).items():
        if missing[kind]:
            what, cmd = how[kind]
            out.append(f"{len(missing[kind])} {what} with no props.module: {_named(missing[kind])} ({cmd})")
        for n in sorted(nodes, key=lambda n: str(n["id"])):
            mod, p = str(_props(n).get("module") or ""), _props(n)
            if mod == NONE and not p.get("module_reason"):
                out.append(f"{n['id']}: props.module is none without props.module_reason")
            elif mod and mod != NONE and mod not in known:
                out.append(f"{n['id']}: props.module {mod} is not in {REGISTRY}")
    return out


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _short(text: str, n: int = 90) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def _since(m: dict) -> date | None:
    try:
        return date.fromisoformat(str(m.get("since") or ""))
    except ValueError:
        return None


def _index(nodes: list[dict]) -> tuple[dict[str, list], dict[str, list]]:
    """Module -> the items with it as primary (any status), and -> the open items with it as secondary."""
    primary: dict[str, list] = {}
    secondary: dict[str, list] = {}
    for n in nodes:
        mod = str(_props(n).get("module") or "")
        if mod:
            primary.setdefault(mod, []).append(n)
        for s in _secondary(n) if n.get("status") in OPEN else []:
            secondary.setdefault(s, []).append(n)
    return primary, secondary


def _order(reg: list[dict]) -> list[tuple[str, dict]]:
    """(brick, module) sorted by brick, then by id (P2 before P12)."""
    return sorted(((str(m.get("brick") or "?"), m) for m in reg),
                  key=lambda bm: (bm[0], len(str(bm[1]["id"])), str(bm[1]["id"])))


def _gaps(reg: list[dict], counts, primary: dict[str, list]) -> list[str]:
    out = []
    for m in reg:
        d, o, _ = counts(str(m["id"]))
        since = _since(m)
        if d or o:
            continue
        if m.get("status") == "proposed" and since:
            out.append(f"- {m['id']} ({m.get('name', '')}): proposed {since}, no item done or open: back to sleep "
                       f"from {since + timedelta(days=DORMANT_DAYS)} if none comes")
        else:
            out.append(f"- {m['id']} ({m.get('name', '')}): no item done or open in the brain")
    known = {str(m["id"]) for m in reg}
    out += [f"- {mod}: {len(primary[mod])} item(s) name it, the registry does not know it"
            for mod in sorted(set(primary) - known - {NONE})]
    return out or ["None."]


def _section(b: str, m: dict, counts, primary: dict[str, list], secondary: dict[str, list]) -> list[str]:
    mid = str(m["id"])
    d, o, s = counts(mid)
    out = ["", f"## {mid}", "",
           f"**{_cell(m.get('name', ''))}**, brick {b}: phase {m.get('phase') or '?'}, {m.get('status', 'tree')}"
           + (f", in the lab {m['lab']}" if m.get("lab") else "") + f". In the brain: {d} done, {o} open, {s} open "
           "as secondary."]
    if m.get("note"):
        out += ["", _cell(m["note"])]
    rows = sorted((n for n in primary.get(mid, []) if n.get("status") in OPEN), key=lambda n: n["id"])
    if rows:
        out += [""] + [f"- `{n['id']}` [{_props(n).get('priority', '-')}] {_short(n.get('title', ''))}" for n in rows]
    if secondary.get(mid):
        out += ["", "Secondary: " + ", ".join(f"`{n['id']}`" for n in sorted(secondary[mid], key=lambda n: n["id"]))]
    return out


def data(store: Path) -> dict:
    """The map as data (brain modules --json): each module with its counts, the open items placed, the problems."""
    reg, nodes = registry(store) or [], items(store)
    primary, secondary = _index(nodes)
    opened = [n for n in nodes if n.get("status") in OPEN]
    mods = []
    for b, m in _order(reg):
        got = primary.get(str(m["id"]), [])
        mods.append({**{k: m[k] for k in ("id", "name", "phase", "status", "lab", "since") if k in m}, "brick": b,
                     "done": sum(1 for n in got if n.get("status") == "done"),
                     "open": sum(1 for n in got if n.get("status") in OPEN),
                     "secondary": len(secondary.get(str(m["id"]), []))})
    more, missing = placed_nodes(store), unplaced(store)
    return {"modules": mods, "open_items": len(opened),
            "placed": sum(1 for n in opened if _props(n).get("module")),
            "outside": sum(1 for n in opened if _props(n).get("module") == NONE), "problems": problems(store),
            "features": len(more["features"]), "features_unplaced": missing["features"],
            "done_items": len(more["done"]), "done_unplaced": missing["done"], "warnings": warnings(store)}


def render(store: Path, store_label: str = "notes/graph") -> str:
    reg = registry(store) or []
    nodes = items(store)
    primary, secondary = _index(nodes)

    def counts(mid: str) -> tuple[int, int, int]:
        got = primary.get(mid, [])
        return (sum(1 for n in got if n.get("status") == "done"), sum(1 for n in got if n.get("status") in OPEN),
                len(secondary.get(mid, [])))

    opened = [n for n in nodes if n.get("status") in OPEN]
    nones = sorted((n for n in opened if _props(n).get("module") == NONE), key=lambda n: n["id"])
    out = [HEAD.format(reg=f"{store_label}/{REGISTRY}"),
           f"**{len(reg)} modules ({sum(1 for m in reg if m.get('status') == 'proposed')} proposed); "
           f"{sum(1 for n in opened if _props(n).get('module'))} of {len(opened)} open items placed, "
           f"{len(nones)} outside the tree.**", ""]
    more, missing = placed_nodes(store), unplaced(store)
    if more["features"] or more["done"]:   # what the reference reads by module (wi-brain-module-backfill)
        out += [f"Features placed: {len(more['features']) - len(missing['features'])} of {len(more['features'])}; "
                f"done items placed: {len(more['done']) - len(missing['done'])} of {len(more['done'])}.", ""]
    out += ["| Module | Name | Brick | Phase | Status | Done | Open | Secondary |", "|---|---|---|---|---|---|---|---|"]
    for b, m in _order(reg):
        d, o, s = counts(str(m["id"]))
        out.append(f"| [{m['id']}](#{str(m['id']).lower()}) | {_cell(m.get('name', ''))} | {b} | "
                   f"{_cell(m.get('phase', ''))} | {_cell(m.get('status', 'tree'))} | {d} | {o} | {s} |")
    out += ["", "## Gaps", ""] + _gaps(reg, counts, primary)
    for b, m in _order(reg):
        out += _section(b, m, counts, primary, secondary)
    out += ["", "## Outside the tree", ""] + ([f"- `{n['id']}`: {_cell(_props(n).get('module_reason', ''))}"
                                               for n in nones] or ["None."])
    return "\n".join(out) + "\n"


def write(root: Path, store: Path, store_label: str = "notes/graph", view: str = VIEW) -> bool:
    """Write the view (``view``, relative to ``root``); True when it changed."""
    f = root / view
    text = render(store, store_label)
    if f.is_file() and f.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8", newline="\n")
    return True


def stale(root: Path, store: Path, store_label: str = "notes/graph", view: str = VIEW) -> bool:
    f = root / view
    return not f.is_file() or f.read_text(encoding="utf-8").replace("\r\n", "\n") != render(store, store_label)
