WAVE, ERA = "wave", "era"
KINDS = (WAVE, ERA)
FILE = "plan_graph.md"
VIEW = f"notes/{FILE}"   # the view of a project's first store at a root it owns
OPEN = ("todo", "doing", "blocked")
CLOSED = ("reached", "dropped")   # a wave no longer current: it may hold no open item
SATISFIED = ("done", "reached", "validated", "active", "live")   # research_graph's satisfied prerequisites
RELEASE_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
RELEASE_IN_RE = re.compile(r"^\s*v?(\d+\.\d+\.\d+)(?![\d.])")   # a free-text props.wave that names a release
SEQ_RE = re.compile(r"^wave-s(\d+)$")   # a wave's id that carries its place, never a version
WAVE_ID_RE = re.compile(r"wave-(?:s\d+|\d+\.\d+\.\d+)(?![\w.])")   # the ids a props.renamed_from names
ID_RE = re.compile(r"^wave-[a-z0-9][a-z0-9-]*$")   # a new wave id: no dot, so no version
PRIORITY = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
QUICKWIN_SHARE = 0.2   # the share of a wave's places kept for quick wins (spec-brain-sizing-prioritization 5.3)
HEAD = ("<!-- GENERATED by `brain sync` (brain.waves) from the graph's milestones of kind wave and era. Do not edit: "
        "change the milestones and the items' part_of edges in the store, then brain sync. -->\n")


def release_key(text) -> tuple[int, int, int] | None:
    """(X, Y, Z) of a well-formed release ``X.Y.Z``, else None."""
    m = RELEASE_RE.match(str(text or "").strip())
    return tuple(int(x) for x in m.groups()) if m else None


def _props(node: dict) -> dict:
    p = node.get("props")
    return p if isinstance(p, dict) else {}


def kind(node: dict) -> str:
    return str(_props(node).get("kind") or "") if node.get("type") == "Milestone" else ""


def _short(text, n: int = 90) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 3] + "..."


@dataclass
class Plan:
    """The store's milestones, items and links that the waves and eras read."""
    nodes: dict[str, dict]
    parents: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))   # child -> its milestones
    members: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))   # milestone -> its part_of
    deps: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))      # item -> its prerequisites
    ddrs: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))      # item -> pending DDRs on it
    edges: list[dict] = field(default_factory=list)   # part_of, depends_on, gated_by and delivers: the rank's input

    @cached_property
    def ranker(self) -> ranking.Ranker:
        """The frontier's rank and each item's score (brain.ranking)."""
        return ranking.Ranker(self.nodes, self.edges)

    def seq(self, wid: str) -> int | None:
        """A wave's place given by its props.seq or its id (``wave-sN``); None for a legacy wave."""
        raw = _props(self.nodes.get(wid) or {}).get("seq")
        n = int(raw) if isinstance(raw, int) and not isinstance(raw, bool) else (
            int(raw) if isinstance(raw, str) and raw.strip().isdigit() else None)
        if n is None:
            m = SEQ_RE.match(wid)
            n = int(m.group(1)) if m else None
        return n if n else None

    @cached_property
    def waves(self) -> list[str]:
        """The waves in order: a legacy wave (no sequence) by its props.release (a malformed one last), its place
        counted among them from 1; a wave with a sequence at its N, after a legacy wave of the same place."""
        ws = [k for k, n in self.nodes.items() if kind(n) == WAVE]

        def planned(w: str):
            key = release_key(_props(self.nodes[w]).get("release"))
            return (key is None, key or (0, 0, 0), w)
        place = {w: i + 1 for i, w in enumerate(sorted((w for w in ws if self.seq(w) is None), key=planned))}
        return sorted(ws, key=lambda w: (place[w] if self.seq(w) is None else self.seq(w), self.seq(w) is not None, w))

    @cached_property
    def labels(self) -> dict[str, tuple[str, str]]:
        """Each wave's (label, shipped): its label, props.release, else the next patch after the release the wave
        before it shipped as (computed); what it shipped as, a reached wave's props.shipped_as, else its label. ''
        when nothing comes before it to count from."""
        out: dict[str, tuple[str, str]] = {}
        prev = None
        for w in self.waves:
            p = _props(self.nodes[w])
            own = release_key(p.get("release")) or (prev and (prev[0], prev[1], prev[2] + 1)) or None
            shipped = (release_key(p.get("shipped_as")) if self.status(w) == "reached" else None) or own
            out[w] = (".".join(map(str, own)) if own else "", ".".join(map(str, shipped)) if shipped else "")
            prev = shipped or prev
        return out

    def computed(self, wid: str) -> bool:
        """Whether a wave's label is computed (it holds no props.release)."""
        return release_key(_props(self.nodes.get(wid) or {}).get("release")) is None

    def shipped(self, wid: str) -> str:
        """The release a wave shipped as (a reached one's props.shipped_as), else its label."""
        return self.labels.get(wid, ("", ""))[1]

    def former(self, wid: str) -> list[str]:
        """The ids a wave had before a rename (props.renamed_from)."""
        return WAVE_ID_RE.findall(str(_props(self.nodes.get(wid) or {}).get("renamed_from") or ""))

    def next_seq(self) -> int:
        """The place of a new wave: one more than the last."""
        return max([len(self.waves)] + [self.seq(w) or 0 for w in self.waves]) + 1

    @cached_property
    def eras(self) -> list[str]:
        return sorted(k for k, n in self.nodes.items() if kind(n) == ERA)

    def release(self, wid: str) -> tuple[int, int, int] | None:
        """A wave's release as a key (its label: written or computed), None without one."""
        return release_key(self.labels.get(wid, ("", ""))[0])

    def label(self, wid: str) -> str:
        """A wave's release: written (props.release) or computed (:attr:`labels`); its id when it has none."""
        if wid not in self.nodes:   # a wave brain wave close is about to create
            return wid.removeprefix("wave-")
        return self.labels.get(wid, ("", ""))[0] or wid

    def status(self, nid: str) -> str:
        return str((self.nodes.get(nid) or {}).get("status") or "")

    def is_item(self, nid: str) -> bool:
        return (self.nodes.get(nid) or {}).get("type") == "WorkItem"

    def resolve(self, ref: str) -> str | None:
        """A wave by its id, an id it had (props.renamed_from), its release (its label), or the release it shipped
        as."""
        ref = str(ref or "").strip()
        if kind(self.nodes.get(ref) or {}) == WAVE:
            return ref
        for hits in ([w for w in self.waves if ref in self.former(w)], [w for w in self.waves if self.label(w) == ref],
                     [w for w in self.waves if self.status(w) == "reached" and self.shipped(w) == ref]):
            if hits:
                return hits[0] if len(hits) == 1 else None
        return None

    def for_release(self, version: str) -> str | None:
        """The wave a version PR of ``version`` closes: the one :meth:`resolve` finds, else, when the release jumped
        (``version`` the next minor or major after the release the wave before the current one shipped as), the
        current wave (wi-brain-wave-ids-decoupled)."""
        w = self.resolve(version)
        key = release_key(version)
        if w or key is None:
            return w
        pend = pending_waves(self)
        if not pend:
            return None
        cur = release_key(self.label(pend[0]))
        if cur is None:
            return None
        before = (cur[0], cur[1], cur[2] - 1) if cur[2] else None   # the release the current wave counts from
        base = before or cur
        return pend[0] if key in ((base[0], base[1] + 1, 0), (base[0] + 1, 0, 0)) and key > cur else None

    def planned(self, nid: str) -> list[str]:
        """The waves an item is part_of (one at most, brain check says), by release."""
        order = {w: i for i, w in enumerate(self.waves)}
        return sorted({p for p in self.parents.get(nid, ()) if p in order}, key=order.__getitem__)

    def via(self, nid: str) -> list[str]:
        """The waves an item was carried through after its first, in order (props.carried_via)."""
        raw = _props(self.nodes.get(nid) or {}).get("carried_via") or ""
        return [v.strip() for v in str(raw).split(",") if v.strip()]

    def same_release(self, ref: str) -> list[str]:
        """The waves of release ``ref`` (more than one: brain check refuses it)."""
        return [w for w in self.waves if self.label(w) == str(ref or "").strip()]

    def wave_of(self, nid: str) -> str | None:
        """The item's wave now: the one its props.carried_to names, else the one it is part_of."""
        to = _props(self.nodes.get(nid) or {}).get("carried_to")
        if to:
            return self.resolve(str(to))
        planned = self.planned(nid)
        return planned[0] if planned else None

    def carried_in(self, nid: str) -> str | None:
        """The earlier wave an item was carried from into its wave now (the last it went through), else None."""
        planned, now = self.planned(nid), self.wave_of(nid)
        if not planned or not now or planned[0] == now:
            return None
        via = [self.resolve(v) for v in self.via(nid)]
        return next((v for v in reversed(via) if v and v != now), planned[0])

    def items_of(self, wid: str) -> list[str]:
        """The items whose wave is ``wid`` now (carried in included, carried out left out)."""
        cands = set(self.members.get(wid, ())) | {k for k, n in self.nodes.items()
                                                  if _props(n).get("carried_to") and self.is_item(k)}
        return sorted(i for i in cands if self.is_item(i) and self.wave_of(i) == wid)

    def carried_out(self, wid: str) -> list[str]:
        """The items planned in ``wid``, or carried through it, and carried to another wave."""
        moved = {k for k, n in self.nodes.items() if self.is_item(k) and _props(n).get("carried_to")}
        through = {i for i in moved if wid in (self.resolve(v) for v in self.via(i))}
        return sorted(i for i in (moved & set(self.members.get(wid, ()))) | through if self.wave_of(i) != wid)

    def blockers(self, nid: str) -> list[str]:
        return [d for d in self.deps.get(nid, ()) if self.status(d) not in SATISFIED]

    def owner_waits(self, nid: str) -> list[str]:
        """What waits on the owner for an item: its props.open, its external_blocker, the pending DDRs on it."""
        p = _props(self.nodes.get(nid) or {})
        out = [f"open: {_short(p['open'])}"] if p.get("open") else []
        if p.get("external_blocker"):
            out.append(f"external: {_short(p['external_blocker'])}")
        out += [f"DDR {d}" for d in sorted(self.ddrs.get(nid, ()))]
        return out

    def startable(self, nid: str) -> bool:
        """todo, its prerequisites satisfied, nothing waiting on the owner, not blocked."""
        return self.status(nid) == "todo" and not self.blockers(nid) and not self.owner_waits(nid)


def _list(path: Path) -> list:
    if not path.is_file():
        return []
    data = graph.load_yaml_file(path)
    return data if isinstance(data, list) else []


def _pending_ddrs(root: Path | None) -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    if not root or not (root / records.RECORDS_DIR / "ddr").is_dir():
        return out
    for _, d in decisions.load(root):
        if d.get("status") == "pending":
            for i in (d.get("links") or {}).get("items") or []:
                out[str(i)].append(str(d.get("id")))
    return out


def load(store: Path, root: Path | None = None) -> Plan:
    """The plan of ``store``; ``root`` holds the records whose pending DDRs wait on the owner."""
    nodes = {str(n["id"]): n for f in sorted((store / "nodes").glob("*.yaml")) for n in _list(f)
             if isinstance(n, dict) and n.get("id")}
    plan = Plan(nodes, ddrs=_pending_ddrs(root))
    for f in [store / "edges.yaml", *sorted((store / "edges").glob("*.yaml"))]:
        for e in _list(f):
            if not isinstance(e, dict) or not e.get("from"):
                continue
            src, dst, etype = str(e["from"]), str(e.get("to")), e.get("type")
            if etype in ("part_of", "depends_on", "gated_by", "delivers"):
                plan.edges.append(e)
            if etype == "part_of" and (nodes.get(dst) or {}).get("type") == "Milestone":
                plan.parents[src].append(dst)
                plan.members[dst].append(src)
            elif etype in ("depends_on", "gated_by"):
                plan.deps[src].append(dst)
    return plan


def applies(store: Path) -> bool:
    """The store holds a wave or an era: its plan view and checks apply."""
    return any(kind(n) in KINDS for f in sorted((store / "nodes").glob("*.yaml")) for n in _list(f)
               if isinstance(n, dict))


# --- brain check ---

def _kind_problems(plan: Plan) -> list[str]:
    out = []
    for k, n in sorted(plan.nodes.items()):
        raw = _props(n).get("kind")
        if raw in (None, ""):
            continue
        if n.get("type") != "Milestone":   # another type's kind is its own (a DDR's kind: action)
            if raw in KINDS:
                out.append(f"{k}: props.kind {raw} is a Milestone's, not a {n.get('type')}'s")
        elif raw not in KINDS:
            out.append(f"{k}: props.kind {raw!r} is wave or era")
    return out


def _wave_problems(plan: Plan) -> list[str]:
    out, seen = [], {}
    for w in plan.waves:
        rel = _props(plan.nodes[w]).get("release")
        if rel not in (None, "") and release_key(rel) is None:
            out.append(f"{w}: props.release is a release X.Y.Z (not {rel!r})")
        elif plan.release(w) is None:
            out.append(f"{w}: no release: no props.release and no wave before it to count from (brain wave add "
                       f"X.Y.Z for a store's first wave)")
        elif plan.label(w) in seen:
            out.append(f"{w}: release {rel} is also {seen[plan.label(w)]}'s (one wave per release)")
        else:
            seen[plan.label(w)] = w
        bad = sorted(m for m in plan.members.get(w, ()) if not plan.is_item(m))
        if bad:
            out.append(f"{w}: a wave's members are work items, not {', '.join(bad)}")
    return out


def _era_problems(plan: Plan) -> list[str]:
    out = []
    for e in plan.eras:
        bad = sorted(m for m in plan.members.get(e, ()) if (plan.nodes.get(m) or {}).get("type") != "Milestone")
        if bad:
            out.append(f"{e}: an era's members are milestones, not {', '.join(bad)}")
    return out


def _item_problems(plan: Plan) -> list[str]:
    out = []
    for k in sorted(k for k in plan.nodes if plan.is_item(k)):
        planned = plan.planned(k)
        if len(planned) > 1:
            out.append(f"{k}: in {len(planned)} waves ({', '.join(planned)}): one wave per item at most")
        to = _props(plan.nodes[k]).get("carried_to")
        if not to:
            continue
        target = plan.resolve(str(to))
        if target is None:
            out.append(f"{k}: props.carried_to {to!r} names no wave")
        elif planned and plan.waves.index(target) <= plan.waves.index(planned[0]):
            out.append(f"{k}: carried_to {plan.label(target)} is not after its wave {plan.label(planned[0])}")
        bad = [v for v in plan.via(k) if plan.resolve(v) is None]
        if bad:
            out.append(f"{k}: props.carried_via names no wave: {', '.join(bad)}")
    return out


def _closed_left(plan: Plan, statuses: tuple[str, ...]) -> list[str]:
    """A wave of ``statuses`` while an open item still has it as its wave (planned there, or carried into it)."""
    out = []
    for w in plan.waves:
        if plan.status(w) in statuses:
            left = [i for i in plan.items_of(w) if plan.status(i) in OPEN]
            if left:
                out.append(f"{w}: {plan.status(w)}, and {len(left)} open item(s) still in it: {', '.join(left)} "
                           f"(carry each to a pending wave, brain item set ID props.carried_to=X.Y.Z, or drop it)")
    return out


def problems(plan: Plan) -> list[str]:
    """brain check's errors on the waves and eras: a dropped wave that still holds an open item is one (that item is
    in no live wave); a reached one is a warning (the owner, 2026-11-10), as a store adopting waves mid-flight has
    them, and the version PR's closure check still refuses it (:func:`closure_problems`)."""
    return (_kind_problems(plan) + _wave_problems(plan) + _era_problems(plan) + _item_problems(plan)
            + _closed_left(plan, ("dropped",)))


def warnings(plan: Plan) -> list[str]:
    """brain check's warnings: a reached wave that still holds an open item, a wave in no milestone or era, an era
    without its exit or whose exit is due."""
    out = list(_closed_left(plan, ("reached",)))
    for w in plan.waves:
        if not plan.parents.get(w):
            out.append(f"{w}: a wave in no milestone or era (brain item link {w} part_of MS)")
    for e in plan.eras:
        if not _props(plan.nodes[e]).get("exit"):
            out.append(f"{e}: an era without its exit (props.exit: the Go/NoGo question asked once its milestones "
                       "are reached)")
        if exit_due(plan, e):
            out.append(f"{e}: its milestones are all reached: its exit is due, a Go/NoGo DDR to {config.name_of()} "
                       f"(brain decision ask)")
    return out


def exit_due(plan: Plan, era: str) -> bool:
    ms = plan.members.get(era, ())
    return plan.status(era) == "pending" and bool(ms) and all(plan.status(m) in CLOSED for m in ms)


def closure_problems(plan: Plan, version: str) -> list[str]:
    """The closure rule on a version PR: the wave named by ``version`` may hold no open item that is neither carried
    to a later wave (props.carried_to) nor dropped, and it is closed (reached by brain wave close). [] when the store
    has no such wave. What brain check refuses about that wave (its release twice, an item of it in two waves) is
    said too: the rule cannot be read through it."""
    same = plan.same_release(version)
    if len(same) > 1:
        return [f"release {version} names {len(same)} waves ({', '.join(same)}): one wave per release (brain check)"]
    w = plan.for_release(version)
    if w is None:
        return []
    out = [f"{i}: in {len(plan.planned(i))} waves ({', '.join(plan.planned(i))}), {w} among them: one wave per item "
           f"(brain check)" for i in sorted(plan.members.get(w, ())) if len(plan.planned(i)) > 1]
    left = [i for i in plan.items_of(w) if plan.status(i) in OPEN]
    if left:
        out.append(f"wave {version} ({w}) holds {len(left)} open item(s) neither carried nor dropped: "
                   f"{', '.join(left)}; brain wave close {version} --carry-to X.Y.Z (or --drop ID) --write, then "
                   f"brain sync")
    elif plan.status(w) == "pending":
        out.append(f"wave {version} ({w}) is still pending: brain wave close {version} --write reaches it, then "
                   f"brain sync")
    return out


# --- brain next and the view ---

def _rank(plan: Plan, nid: str) -> tuple:
    """The owner's priority (a confirmed one before the same proposed), the owner's order, then value over effort
    (brain.ranking)."""
    return plan.ranker.key(nid)


def _sorted(plan: Plan, ids) -> list[str]:
    return sorted(ids, key=lambda i: _rank(plan, i))


REPORT_GROUPS = ("carried", "startable", "waiting", "other", "closed")


def _group(plan: Plan, nid: str) -> str:
    """An item's group in its wave, the first that holds: closed, carried in, startable, waiting on the owner, other."""
    if plan.status(nid) not in OPEN:
        return "closed"
    if plan.carried_in(nid):
        return "carried"
    if plan.startable(nid):
        return "startable"
    return "waiting" if plan.owner_waits(nid) else "other"


def wave_report(plan: Plan, wid: str) -> dict:
    """A wave's items in their groups: carried in, startable, waiting on the owner, other open, closed."""
    items = plan.items_of(wid)
    groups: dict[str, list[str]] = {k: [] for k in REPORT_GROUPS}
    for i in items:
        groups[_group(plan, i)].append(i)
    node = plan.nodes[wid]
    out = {"id": wid, "release": plan.label(wid), "status": plan.status(wid), "title": str(node.get("title") or ""),
           "week": str(_props(node).get("week") or ""), "parents": sorted(plan.parents.get(wid, ())),
           "items": len(items), "done": sum(1 for i in items if plan.status(i) == "done"),
           "open": len(items) - len(groups["closed"])}
    out.update({k: [_row(plan, i) for i in _sorted(plan, ids)] for k, ids in groups.items()})
    out["carried_out"] = [_row(plan, i) for i in plan.carried_out(wid)]
    return out | _ranked(plan, out, items)


def _ranked(plan: Plan, out: dict, items: list[str]) -> dict:
    """A wave's quick wins (its carried and startable items of size S and high value, in rank order), its quick-win
    slot and the open items whose value the owner set (brain.ranking)."""
    ready = out["carried"] + out["startable"]
    return {"quick_wins": [r["id"] for r in ready if r["rank"]["quick_win"]],
            "slot": quickwin_slot(plan, out["id"]),
            "value_overrides": plan.ranker.overrides([i for i in items if plan.status(i) in OPEN])}


def _sized_high(plan: Plan, nid: str) -> bool:
    """Size S and a high value (brain.ranking's quick win, whatever the item's state)."""
    return plan.ranker.score(nid).quick_win


def quickwin_slot(plan: Plan, wid: str, exclude=()) -> dict:
    """A wave's quick-win slot (wi-brain-wave-quickwin-slot; spec-brain-sizing-prioritization 5.3): about
    ``QUICKWIN_SHARE`` of its places (its items, closed ones included, at least one place once it has an item) kept
    for items of size S with a high value. ``filled``: the wave's own items of that kind (done ones too, dropped ones
    not), in rank order; ``free``: the places still free; ``candidates``: the startable quick wins outside the wave (in
    no wave, or in a later one; ``exclude``: those proposed for an earlier wave already), in rank order, as many as the
    free places: what would fill it, each with the command that moves it (``moves``). A wave closed (reached or
    dropped) has no free place: nothing is added to it."""
    items = plan.items_of(wid)
    places = len(items)
    slot = max(1, math.floor(places * QUICKWIN_SHARE + 0.5)) if places else 0
    filled = _sorted(plan, [i for i in items if plan.status(i) != "dropped" and _sized_high(plan, i)])
    free = 0 if plan.status(wid) in CLOSED else max(0, slot - len(filled))
    order = {w: k for k, w in enumerate(plan.waves)}
    here = order.get(wid, -1)

    def outside(i: str) -> bool:
        w = plan.wave_of(i)
        return w != wid and (w is None or order.get(w, -1) > here)

    pool = [k for k in plan.nodes if plan.is_item(k) and plan.startable(k) and outside(k) and _sized_high(plan, k)
            and k not in exclude]
    cands = _sorted(plan, pool)[:free]
    return {"share": QUICKWIN_SHARE, "places": places, "slot": slot, "filled": filled, "free": free,
            "candidates": cands, "moves": {k: move_command(plan, k, wid) for k in cands}}


def move_command(plan: Plan, nid: str, wid: str) -> str:
    """The command that puts ``nid`` in the wave ``wid`` and leaves it in one wave (brain check): a link for an item in
    no wave; for one part_of a later wave, that edge removed first; for one carried, its carried_to moved."""
    if _props(plan.nodes.get(nid) or {}).get("carried_to"):
        return f"brain item set {nid} carried_to={plan.label(wid)}"
    later = plan.planned(nid)
    link = f"brain item link {nid} part_of {wid}"
    return f"brain item unlink {nid} {later[0]}, then {link}" if later else link


def slot_line(slot: dict, wid: str) -> str:
    """'quick-win slot: 2 of 10 places (20 %); filled by a, b; 1 free: candidate c (brain item link c part_of W)'."""
    if not slot or not slot.get("slot"):
        return ""
    text = (f"quick-win slot: {slot['slot']} of {slot['places']} place(s) ({slot['share']:.0%}, size S and a high "
            "value); filled by " + (", ".join(slot["filled"]) or "none"))
    if not slot["free"]:
        return text
    text += f"; {slot['free']} free"
    if slot["candidates"]:
        first = slot["candidates"][0]
        how = (slot.get("moves") or {}).get(first) or f"brain item link {first} part_of {wid}"
        return text + f": candidate(s) {', '.join(slot['candidates'])} ({how})"
    return text + ": no startable quick win outside the wave"


def _row(plan: Plan, nid: str) -> dict:
    n, p = plan.nodes[nid], _props(plan.nodes[nid])
    came, now = plan.carried_in(nid), plan.wave_of(nid)
    moved = bool(p.get("carried_to"))
    return {"id": nid, "title": str(n.get("title") or ""), "status": plan.status(nid),
            "priority": str(p.get("priority") or ""), "waits_on_owner": plan.owner_waits(nid),
            "after": plan.blockers(nid), "carried_from": plan.label(came) if came else "",
            "carried_to": (plan.label(now) if now else str(p["carried_to"])) if moved else "",
            "rank": plan.ranker.score(nid).as_dict()}


def pending_waves(plan: Plan) -> list[str]:
    return [w for w in plan.waves if plan.status(w) == "pending" and plan.release(w) is not None]


def next_report(plan: Plan) -> dict:
    """brain next's data: the current wave (the lowest release not closed) and the next one."""
    pend = pending_waves(plan)
    cur = wave_report(plan, pend[0]) if pend else None
    nxt = wave_report(plan, pend[1]) if len(pend) > 1 else None
    if cur and nxt:   # one item proposed for one slot: the current wave's candidates are not the next's
        nxt["slot"] = quickwin_slot(plan, pend[1], exclude=cur["slot"]["candidates"])
    return {"owner": config.name_of(), "waves": len(plan.waves), "current": cur, "next": nxt}


def _row_text(r: dict, owner: str, out: bool = False) -> str:
    """An item's line; ``out``: in the wave it was carried out of (its carried_to said, not its carried_from)."""
    notes = [r["priority"]] if r["priority"] else []
    if out and r["carried_to"]:
        notes.append(f"carried to {r['carried_to']}")
    elif r["carried_from"]:
        notes.append(f"carried from {r['carried_from']}")
    if r["after"]:
        notes.append(f"after {', '.join(r['after'])}")
    if r["waits_on_owner"]:
        notes.append(f"waits on {owner}: {'; '.join(r['waits_on_owner'])}")
    return f"{r['id']} [{r['status']}] {_short(r['title'], 80)}" + (f" ({', '.join(notes)})" if notes else "")


def _wave_head(w: dict) -> str:
    where = f", part of {', '.join(w['parents'])}" if w["parents"] else ""
    week = f", week of {w['week']}" if w["week"] else ""
    return (f"Wave {w['release']} ({w['id']}{week}{where}): {w['open']} open of {w['items']} "
            f"({w['done']} done)")


GROUPS = (("carried", "carried from an earlier wave, first"), ("startable", "startable"),
          ("waiting", "waits on {owner}"), ("other", "other open"))


def _current_lines(cur: dict, owner: str, explain: bool, slot: bool = True) -> list[str]:
    """The current wave's head, its quick wins, its groups in rank order (with --explain, each carried or startable
    item's score under it, then the values the owner set)."""
    out = [_wave_head(cur)]
    if cur.get("quick_wins"):
        out.append(f"  quick wins (size S, high value), first: {', '.join(cur['quick_wins'])}")
    line = slot_line(cur.get("slot") or {}, cur["id"]) if slot else ""   # not in the view: brain next's own
    if line:
        out.append(f"  {line}")
    for key, label in GROUPS:
        if cur[key]:
            out.append(f"  {label.format(owner=owner)}:")
            parts = explain and key in ("carried", "startable")
            for r in cur[key]:
                out += [f"    {_row_text(r, owner)}"] + ([f"        {r['rank']['explain']}"] if parts else [])
    if explain and cur.get("value_overrides"):
        out.append(f"  value set by {owner} on {len(cur['value_overrides'])} open item(s) (props.value): "
                   f"{', '.join(cur['value_overrides'])}")
    return out


def render_next(rep: dict, explain: bool = False, slot: bool = True) -> list[str]:
    """brain next's text; ``explain``: each carried and startable item's score parts under it (brain.ranking)."""
    owner = rep["owner"]
    cur = rep["current"]
    if cur is None and rep.get("waves"):
        return [f"No open wave: all {rep['waves']} wave(s) are closed (reached or dropped); plan the next one: brain "
                f"wave add X.Y.Z --parent MS"]
    if cur is None:
        return ["No open wave: a Milestone with props.kind wave and props.release X.Y.Z (brain wave import proposes "
                "them from the items' props.wave)"]
    out = _current_lines(cur, owner, explain, slot)
    if not cur["open"]:
        out.append(f"  nothing open: close it with its version PR (brain wave close {cur['release']})")
    nxt = rep["next"]
    if nxt:
        out.append("Next: " + _wave_head(nxt))
        for key, label in GROUPS[:2]:
            if nxt[key]:
                out.append(f"  {label.format(owner=owner)}: {', '.join(r['id'] for r in nxt[key])}")
    else:
        out.append("Next: no later wave planned")
    return out


def _md_row(r: dict, owner: str, out: bool = False) -> str:
    box = "x" if r["status"] == "done" else " "
    text = _row_text(r, owner, out)
    return f"- [{box}] " + (f"~~{text}~~" if r["status"] == "dropped" else text)


def _md_wave(plan: Plan, wid: str, depth: int, owner: str) -> list[str]:
    w = wave_report(plan, wid)
    title = f" — {w['title']}" if w["title"] and w["title"] != f"Wave {w['release']}" else ""
    out = ["", f"{'#' * depth} Wave {w['release']}{title} [{w['status']}]", "", _wave_head(w) + "."]
    for key, label in GROUPS:
        if w[key]:
            said = label.format(owner=owner)
            out += ["", f"{said[:1].upper()}{said[1:]}:", ""] + [_md_row(r, owner) for r in w[key]]
    for key, label in (("closed", "Closed"), ("carried_out", "Carried out")):
        if w[key]:
            out += ["", f"{label}:", ""] + [_md_row(r, owner, key == "carried_out") for r in w[key]]
    return out


def _md_milestone(plan: Plan, mid: str, depth: int, owner: str, placed: set[str]) -> list[str]:
    out = ["", f"{'#' * depth} {mid}{_title(plan, mid)}"]
    trig = _props(plan.nodes[mid]).get("trigger")
    if trig:
        out += ["", f"Trigger: {_short(trig, 200)}"]
    for w in (w for w in plan.waves if w in plan.members.get(mid, ()) and w not in placed):
        placed.add(w)
        out += _md_wave(plan, w, depth + 1, owner)
    return out


def _title(plan: Plan, nid: str) -> str:
    title = plan.nodes[nid].get("title")
    return (f" — {title}" if title else "") + f" [{plan.status(nid)}]"


def _era_milestones(plan: Plan, eid: str) -> list[str]:
    return sorted(m for m in plan.members.get(eid, ()) if (plan.nodes.get(m) or {}).get("type") == "Milestone"
                  and kind(plan.nodes[m]) != WAVE)


def _era_lines(plan: Plan, eid: str) -> list[str]:
    """An era's exit (counted on the members exit_due waits for, its waves included), its stage change and what it
    serves."""
    p, ms = _props(plan.nodes[eid]), plan.members.get(eid, ())
    reached = sum(1 for m in ms if plan.status(m) in CLOSED)
    due = "; due now" if exit_due(plan, eid) else ""
    out = [f"Exit (a Go/NoGo DDR once its {len(ms)} milestone(s) are reached, {reached} so far): "
           f"{_short(p.get('exit') or 'not set', 200)}{due}"]
    return out + [f"{label}: {_short(p[key], 200)}" for key, label in (("stage_to", "Stage at its exit"),
                                                                         ("serves", "Serves")) if p.get(key)]


def _md_era(plan: Plan, eid: str, owner: str, placed: set[str]) -> list[str]:
    out = ["", f"## Era {eid}{_title(plan, eid)}", ""] + _era_lines(plan, eid)
    for w in (w for w in plan.waves if w in plan.members.get(eid, ()) and w not in placed):
        placed.add(w)
        out += _md_wave(plan, w, 3, owner)
    for m in _era_milestones(plan, eid):
        placed.add(m)
        out += _md_milestone(plan, m, 3, owner, placed)
    return out


def render(plan: Plan) -> str:
    """The generated view: brain next's lines, then era > milestone > wave > items. Deterministic and dateless."""
    owner = config.name_of()
    out = [HEAD, "# Plan: eras, milestones, waves", "",
           f"{len(plan.eras)} era(s), {len(plan.waves)} wave(s) ({len(pending_waves(plan))} open). A wave is a "
           "release, written or computed (its id carries no version); the version PR closes it (brain wave close). "
           "Read it from the command line with `brain next`.", "", "## Next", "",
           "```"] + render_next(next_report(plan), slot=False) + ["```"]
    placed: set[str] = set()
    for e in plan.eras:
        out += _md_era(plan, e, owner, placed)
    loose = [m for m in sorted(plan.nodes) if plan.nodes[m].get("type") == "Milestone" and not kind(plan.nodes[m])
             and m not in placed and any(w in plan.members.get(m, ()) for w in plan.waves)]
    if loose:
        out += ["", "## Milestones in no era"]
        for m in loose:
            out += _md_milestone(plan, m, 3, owner, placed)
    rest = [w for w in plan.waves if w not in placed]
    if rest:
        out += ["", "## Waves in no milestone or era"]
        for w in rest:
            out += _md_wave(plan, w, 3, owner)
    return "\n".join(out) + "\n"


def write(root: Path, store: Path, view: str = VIEW) -> bool:
    """Write the view (``view``, relative to ``root``); True when it changed."""
    f = root / view
    text = render(load(store, root))
    if f.is_file() and f.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8", newline="\n")
    return True


def stale(root: Path, store: Path, view: str = VIEW) -> bool:
    f = root / view
    return not f.is_file() or f.read_text(encoding="utf-8").replace("\r\n", "\n") != render(load(store, root))


# --- brain wave close ---

class WaveError(graph.GraphError):
    pass


@dataclass(frozen=True)
class Closing:
    wave: str
    release: str
    carry_to: str          # the wave id the carried items go to, '' when none
    carried: list[str]
    dropped: list[str]
    left: list[str]        # open items neither carried nor dropped: the wave cannot close
    done: int
    created: bool = False  # the carry-to wave does not exist yet: closing creates it beside the closed one
    shipped_as: str = ""   # the version the wave ships as (props.shipped_as): the version closed
    carry_release: str = ""   # the release --carry-to named, when closing creates its wave


def _wave_to_close(plan: Plan, version: str) -> str:
    w = plan.for_release(version)
    if w is None:
        raise WaveError(f"{version}: no wave of that release, and not the next minor or major after the current "
                        f"wave's (brain next)")
    if plan.status(w) != "pending":
        raise WaveError(f"{w}: already {plan.status(w)}")
    return w


def _carry_target(plan: Plan, w: str, carry_to: str) -> str:
    """The later wave ``carry_to`` names ('' when none is given); a release with no wave yet names the wave that
    closing creates (the next ``wave-sN``, beside the closed one: the owner, 2026-11-10; its release computed)."""
    if not carry_to:
        return ""
    target = plan.resolve(carry_to)
    if not target:
        key = release_key(carry_to)
        if key is None:
            raise WaveError(f"--carry-to {carry_to}: no wave of that name, and not a release X.Y.Z to create")
        if key <= (plan.release(w) or (0, 0, 0)):
            raise WaveError(f"--carry-to {carry_to}: not after {plan.label(w)}")
        return f"wave-s{plan.next_seq()}"
    if plan.waves.index(target) <= plan.waves.index(w):
        raise WaveError(f"--carry-to {carry_to}: not after {plan.label(w)}")
    if plan.status(target) != "pending":
        raise WaveError(f"--carry-to {carry_to}: {target} is {plan.status(target) or 'without a status'}, not pending "
                        "(an item carried there would be in no live wave)")
    return target


def plan_close(plan: Plan, version: str, carry_to: str = "", drop: list[str] | None = None) -> Closing:
    """What closing the wave ``version`` does: its open items carried to ``carry_to``, those of ``drop`` dropped."""
    w = _wave_to_close(plan, version)
    target = _carry_target(plan, w, carry_to)
    items = plan.items_of(w)
    opened = [i for i in items if plan.status(i) in OPEN]
    drop = list(dict.fromkeys(drop or []))
    unknown = [d for d in drop if d not in opened]
    if unknown:
        raise WaveError(f"--drop {', '.join(unknown)}: not an open item of {w}")
    rest = [i for i in opened if i not in drop]
    done = sum(1 for i in items if plan.status(i) == "done")
    created = bool(target) and target not in plan.nodes
    return Closing(w, plan.label(w), target, rest if target else [], drop, [] if target else rest, done,
                   created=created, shipped_as=_shipped_as(plan, w, version),
                   carry_release=carry_to if created else "")


def _shipped_as(plan: Plan, w: str, version: str) -> str:
    """The version a wave closes as: the release given, else its label (closed by its id)."""
    return version if release_key(version) else plan.label(w)


def close(store: Path, version: str, carry_to: str = "", drop: list[str] | None = None, *, write: bool = False,
          today: str | None = None, root: Path | None = None) -> Closing:
    """The closure of a wave: its open items carried to ``carry_to`` (props.carried_to) or dropped, then the wave
    reached with what it did. Writes only with ``write`` and when nothing is left."""
    plan = load(store, root)
    c = plan_close(plan, version, carry_to, drop)
    if not write or c.left:
        return c
    day = today or date.today().isoformat()
    if c.created:   # the next wave, part of what the closed wave is part of; its release computed, unless --carry-to
        parents = plan.parents.get(c.wave) or []   # named another one (then pinned: props.release)
        add(store, c.carry_release, parent=parents[0] if parents else "", today=day,
            pin=c.carry_release != next_release(plan), decided=f"created by brain wave close {c.release} --carry-to")
    for i in c.dropped:
        graph.close_item(store, i, "", f"at the close of wave {c.release}", today=day, status="dropped")
    for i in c.carried:   # carried again: the wave it leaves joins the ones it went through
        via = plan.via(i) + [c.wave] if plan.carried_in(i) else []
        graph.set_item(store, i, [f"props.carried_to={c.carry_to}"] + ([f"props.carried_via={', '.join(via)}"]
                                                                        if via else []))
    to = f", {len(c.carried)} carried to {plan.label(c.carry_to)}" if c.carried else ""
    graph.set_item(store, c.wave, ["status=reached", f"props.shipped_as={c.shipped_as}",
                                   f"props.reached={day}: closed by brain wave close ({c.done} done{to}, "
                                   f"{len(c.dropped)} dropped)"])
    return c


def next_release(plan: Plan) -> str:
    """The release a new wave's label is computed as: the next patch after the last wave's ('' with no wave)."""
    if not plan.waves:
        return ""
    key = release_key(plan.shipped(plan.waves[-1]))
    return f"{key[0]}.{key[1]}.{key[2] + 1}" if key else ""


def add(store: Path, version: str = "", *, parent: str = "", week: str = "", title: str = "", decided: str = "",
        today: str | None = None, pin: bool = False) -> dict:
    """A new wave ``wave-sN`` (its place; its id carries no version: wi-brain-wave-ids-decoupled), part of ``parent``
    (a milestone or an era). Its release is computed (:func:`next_release`); ``version``, when given, must be that
    release, or pins the release of a store's first wave; ``pin`` (brain wave import) pins it whatever it is."""
    plan = load(store)
    if parent and (plan.nodes.get(parent) or {}).get("type") != "Milestone":
        raise WaveError(f"--parent {parent}: not a milestone or an era")
    seq = plan.next_seq()
    props: dict = {"kind": WAVE, "seq": seq}
    pinned = _pinned(plan, version, pin)
    props.update({k: v for k, v in (("release", pinned), ("week", week), ("decided", decided)) if v})
    return graph.add_item(store, f"wave-s{seq}", title or f"Wave s{seq}", node_type="Milestone",
                          status="pending", props=props, milestone=parent, today=today)


def _pinned(plan: Plan, version: str, pin: bool) -> str:
    """The release a new wave pins ('' when it is computed); :class:`WaveError` for a release that is not the
    computed one (unless ``pin``), already a wave's, or missing for a store's first wave."""
    computed = next_release(plan)
    if not version:
        if not computed:
            raise WaveError("a store's first wave names its release: brain wave add X.Y.Z")
        return ""
    if release_key(version) is None:
        raise WaveError(f"{version}: a release X.Y.Z")
    if plan.resolve(version):
        raise WaveError(f"{version}: already a wave ({plan.resolve(version)})")
    if computed and version != computed and not pin:
        raise WaveError(f"{version}: a new wave's release is computed, {computed} (the next patch after the last "
                        f"wave's); brain wave add without a release, and its version PR closes it as what it ships")
    return version if pin or not computed else ""


# --- brain wave import ---

@dataclass(frozen=True)
class Import:
    waves: dict[str, list[str]]       # release -> the items whose props.wave names it, not yet in a wave
    existing: dict[str, str]          # release -> the wave that holds it already
    to_place: dict[str, list[str]]    # a props.wave that names no release -> its items
    before: dict[str, list[str]] = field(default_factory=dict)   # release before ``start`` -> its items, left as is


def plan_import(store: Path, start: str = "") -> Import:
    """The waves the items' props.wave names; ``start`` (X.Y.Z): the releases before it, already tagged, are listed
    and left out, so that no past release becomes a pending wave that brain next would name."""
    if start and release_key(start) is None:
        raise WaveError(f"--from {start}: a release X.Y.Z (the first release to import)")
    plan = load(store)
    waves, to_place = _wave_values(plan)
    order = sorted(waves, key=lambda r: release_key(r) or (0, 0, 0))
    floor = release_key(start) or (0, 0, 0)
    kept = [r for r in order if (release_key(r) or (0, 0, 0)) >= floor]
    return Import({r: waves[r] for r in kept}, {r: plan.resolve(r) for r in kept if plan.resolve(r)},
                  dict(sorted(to_place.items())), {r: waves[r] for r in order if r not in kept})


def _wave_values(plan: Plan) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """The items in no wave by their free-text props.wave: (the release it names -> its items, any other value -> its
    items)."""
    waves: dict[str, list[str]] = defaultdict(list)
    to_place: dict[str, list[str]] = defaultdict(list)
    for k in sorted(k for k in plan.nodes if plan.is_item(k)):
        raw = _props(plan.nodes[k]).get("wave")
        if raw in (None, "") or plan.planned(k):
            continue
        m = RELEASE_IN_RE.match(str(raw))
        if m:
            waves[m.group(1)].append(k)
        else:
            to_place[" ".join(str(raw).split())].append(k)
    return waves, to_place


def do_import(store: Path, *, write: bool = False, today: str | None = None, start: str = "") -> Import:
    """Propose (``write``: create) a wave per release the items' free-text props.wave names, from ``start`` on, and
    their part_of edges; props.wave is kept as the record of when it was planned."""
    imp = plan_import(store, start)
    if not write:
        return imp
    day = today or date.today().isoformat()
    for rel, items in imp.waves.items():
        wid = imp.existing.get(rel)
        if not wid:
            wid = add(store, rel, today=day, pin=True,
                      decided=f"brain wave import, {day}, from the items' props.wave")["id"]
        graph.append_edges(store, [{"from": i, "to": wid, "type": "part_of"} for i in items], "edges/work.yaml",
                           f"{day}: brain wave import ({rel})")
    return imp
