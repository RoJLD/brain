"""Waves and eras: the plan as a tree of milestones, at zero token (wi-brain-waves-as-releases, wi-brain-eras).

A Milestone may carry ``props.kind``:

- ``wave``: a release's batch of work. Its id carries no version (wi-brain-wave-ids-decoupled, the owner's WAVES-3 to
  WAVES-5): ``wave-sN``, N its place in the order of the waves (``props.seq``); its release is a label, computed:
  :meth:`Plan.label` is its ``props.release`` (a legacy wave ``wave-X.Y.Z``, or one pinned by brain wave import or
  --carry-to when it is not the computed one), else computed: the next patch after the release the last wave before
  it that was not dropped shipped as. A reached wave's ``props.shipped_as`` (the version its PR shipped) is what the
  later waves count from, and it resolves the wave too. So when a wave ships as a higher version than planned, the
  later waves follow without an edit. A dropped wave holds no release (its ids still resolve). ``props.week``
  optional. Its members are work items (``part_of``); it is itself ``part_of`` a milestone or an era. An item is in
  one wave at most: the one it is ``part_of``, or, once that wave closed without it, the later wave its
  ``props.carried_to`` names (a wave id or its release). The edge to the first wave stays: it says where the item was
  planned. An item carried again keeps the waves it went through, in order, in ``props.carried_via`` (wave ids,
  comma-separated). A wave renamed (brain wave rename) keeps its former ids in ``props.renamed_from``: they still
  resolve.
- ``era``: a milestone of milestones (members ``part_of`` it are milestones), whose exit is the Go/NoGo question
  (``props.exit``) put to the owner as a DDR once its milestones are reached; ``props.stage_to`` the stage change
  that exit may carry, ``props.serves`` a free label (the phase or tier of a wider plan it serves).

No new node type and no schema change: a milestone without a kind is read as before, and an engine that does not know
the kinds reads a wave or an era as a plain milestone.

The waves' order: a legacy wave (no sequence) by its props.release, counted from 1 among them; a wave with a
sequence at its N. The current wave is the first one still pending. A wave is closed by its version PR (``brain wave
close X.Y.Z``, X.Y.Z its label, or the next minor or major when the release jumped: the current wave): each open item
of it is carried by name to a later wave or dropped, then the wave is reached with ``props.shipped_as`` X.Y.Z;
``release_check.py --store`` refuses a version PR whose wave still holds an open item that is neither, or is not
reached yet (the closure rule, docs/release.md).

A wave keeps about ``QUICKWIN_SHARE`` (a fifth) of its places for quick wins, items of size S with a high value
(brain.ranking): ``quickwin_slot`` says the slot, what fills it and, while a place is free, the startable quick wins
outside the wave that would (wi-brain-wave-quickwin-slot); ``brain next`` and ``brain wave plan`` show it.

The generated view (``plan_graph.md`` beside the store's other views, written by ``brain sync`` alone) shows era >
milestone > wave > items, and ``brain next`` prints its first section.
"""

