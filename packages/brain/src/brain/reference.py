"""The technical reference (wi-brain-technical-reference, first slice of spec-brain-architecture-docs): a generated
``docs/reference/`` per project, never edited by hand, the entry point that spares a reader the whole decision log.

- **README.md**: the twelve arc42 sections (brain.arc42, wi-brain-reference-arc42), each from its source in the
  graph, the prose a person writes from ``docs/reference.yaml`` (:func:`load_prose`, ``schemas/reference.schema.json``:
  a required field missing fails ``brain reference`` and ``brain check``); its section 5 is the modules of the store's
  registry (``modules.yaml``, brain.modules), each with its features, decisions in force and items, and its section 9
  the decisions by module and those no module holds (« unplaced », counted: a debt line).
- **modules/<id>.md**, one per module: what it does (its features, have and planned), the decisions in force on each of
  its nodes, the rules its items deliver, its specs, its items done and open, its open questions.

**Decisions in force** (spec 5.2). The unit is the answered DDR (its question, the chosen option, the date and who
answered), linked to the ADR it went to; an ADR that no DDR went to shows by its title; an ADR some DDR went to (a
batch of answers) is never listed by its title alone. The subject of a unit is the module of the nodes it is about
(a DDR's ``links.items`` and ``links.specs``; the nodes an ADR decides, ``decided_by``), else « unplaced ». On one
node the newest answer is in force and the earlier ones fold under it; an ADR a REVERSAL supersedes (``supersedes``,
or status superseded) is marked superseded. A DDR answered again holds its newest answer only. No inference beyond.

**The neutral render** (:func:`render_public`): the engine's own reference for its public repo, by feature domain,
drawn only from what the engine owns: the features of one repo (their public titles, ids and that repo's own code
and docs). It names no module, spec, ADR, DDR, item nor rule of the private brain; :func:`denied` is what
``brain check --public`` would refuse in it.

Zero token: written by ``brain reference --write`` and, once ``docs/reference/`` exists, by ``brain sync``. No date
of its own: the same graph gives the same files.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from . import arc42, features, graph, modules, records, schema

DIR = "docs/reference"
YAML = "docs/reference.yaml"   # the prose a person writes (schemas/reference.schema.json)
KIND = "reference"             # its name in brain.schema.SCHEMAS
MODULES_DIR = "modules"
DOMAINS_DIR = "domains"
MARKER = "GENERATED by `brain reference`"
UNPLACED = "unplaced"
OPEN = ("todo", "doing", "blocked")
ANSWERED = ("answered", "applied", "archived", "read")
PUBLIC_NOTE = "a public render"   # what the public README says: brain sync never rewrites it
UP = "../../../"   # from docs/reference/domains/ back to the repo's root, where its code links start


def _cell(text) -> str:
    return " ".join(str(text or "").replace("|", "\\|").split())


def _short(text, n: int = 110) -> str:
    text = _cell(text)
    return text if len(text) <= n else text[: n - 1] + "…"


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-") or "other"


def page_name(mid: str) -> str:
    """A module page's file name: its id with any character outside letters, digits, dot, dash and underscore made a
    dash, and no leading dot (an id with a path separator or '..' stays inside modules/)."""
    return (re.sub(r"[^A-Za-z0-9._-]", "-", mid).lstrip(".") or "module") + ".md"


def generated(text: str) -> bool:
    """Whether a page is this module's: its third line (after the title and a blank line) opens with the marker; a
    page that only quotes it elsewhere is the owner's."""
    lines = text.splitlines()
    return len(lines) > 2 and lines[2].startswith(MARKER)


@dataclass
class Unit:
    """A decision as the reference shows it: an answered DDR, or an ADR no DDR went to."""
    id: str
    kind: str                    # ddr | adr
    date: str                    # YYYY-MM-DD (the answer's, or the ADR's)
    text: str                    # « question → choice (by, date) » or the ADR's title
    adrs: list[str] = field(default_factory=list)   # the ADRs it went to (a DDR), itself (an ADR)
    about: list[str] = field(default_factory=list)  # the nodes it is about
    superseded: bool = False
    superseded_by: str = ""      # the ADR that supersedes it, when a supersedes edge names it


@dataclass
class Model:
    """What the reference reads: the store's nodes and edges, the registry, the DDR records, and the units."""
    nodes: dict
    edges: list
    registry: list
    units: list[Unit]
    pending: list[dict]          # the DDRs not answered yet (open questions), as records


def _edges(store: Path) -> list[dict]:
    files = [store / "edges.yaml", *sorted((store / "edges").glob("*.yaml"))]
    return [e for f in files for e in graph.load_yaml_list(f) if isinstance(e, dict) and e.get("from") and e.get("to")]


def _props(n: dict) -> dict:
    return n.get("props") if isinstance(n.get("props"), dict) else {}


def _day(stamp) -> str:
    return str(stamp or "")[:10]


def _adr_day(nid: str) -> str:
    m = re.match(r"(?:adr|sdr)-(\d{4}-\d{2}-\d{2})-", nid)
    return m.group(1) if m else ""


def _answer(d: dict) -> dict:
    return d.get("answer") if isinstance(d.get("answer"), dict) else {}


def _strs(value) -> list[str]:
    """A record's list of ids as strings: a list kept, one string a list of one, anything else none."""
    if isinstance(value, str):
        return [value] if value else []
    return [str(x) for x in value if x is not None] if isinstance(value, list) else []


def _ddr_text(d: dict) -> str:
    ans = _answer(d)
    choice = ", ".join(_strs(ans.get("choices"))) or _short(ans.get("other", ""), 90)
    by = str(ans.get("by") or "")
    return f"{_short(d.get('question') or d.get('title'), 120)} → **{_short(choice, 120)}**" \
        + (f" ({by}, {_day(ans.get('at'))})" if by else f" ({_day(ans.get('at'))})")


def _links(d: dict) -> dict:
    return d.get("links") if isinstance(d.get("links"), dict) else {}


def _about(d: dict) -> list[str]:
    links = _links(d)
    return _strs(links.get("items")) + _strs(links.get("specs"))


def _ddr_unit(d: dict) -> Unit:
    return Unit(str(d["id"]), "ddr", _day(_answer(d).get("at")), _ddr_text(d), _strs(_links(d).get("adrs")),
                _about(d))


def _answered(d: dict) -> bool:
    """An answered DDR the reference can read: an id, an answer as a mapping, an answered status."""
    return bool(d.get("id")) and bool(_answer(d)) and d.get("status") in ANSWERED


def _decided(edges: list[dict]) -> dict[str, list[str]]:
    """{ADR: the nodes it decides} (``decided_by``)."""
    out: dict[str, list[str]] = {}
    for e in (e for e in edges if e.get("type") == "decided_by"):
        out.setdefault(str(e["to"]), []).append(str(e["from"]))
    return out


def _mark(units: list[Unit], nodes: dict, edges: list[dict], decided: dict[str, list[str]]) -> None:
    """A unit whose ADR is superseded marked so; a DDR that names no node about the nodes its ADRs decide."""
    superseded = {str(e["to"]): str(e["from"]) for e in edges if e.get("type") == "supersedes"}
    for u in units:
        old = [a for a in u.adrs if a in superseded or nodes.get(a, {}).get("status") == "superseded"]
        if old:
            u.superseded, u.superseded_by = True, superseded.get(old[0], "")   # by whom, when an edge says it
        if u.kind == "ddr" and not u.about:
            u.about = sorted({x for a in u.adrs for x in decided.get(a, [])})


def load(root: Path, store: Path) -> Model:
    """The reference's model of ``store`` (and the DDR records under ``root``)."""
    nodes = {nid: node for nid, (_, node) in graph.node_index(store).items()}
    edges = _edges(store)
    ddrs = [d for _, d in records.load(root).get("ddr", [])] if (root / records.RECORDS_DIR).is_dir() else []
    units = [_ddr_unit(d) for d in ddrs if _answered(d)]
    went = {a for u in units for a in u.adrs}   # an ADR some DDR went to: never shown by its title alone
    decided = _decided(edges)
    units += [Unit(nid, "adr", _adr_day(nid), _short(n.get("title"), 140), [nid], sorted(decided.get(nid, [])))
              for nid, n in nodes.items() if n.get("type") == "ADR" and nid not in went]
    _mark(units, nodes, edges, decided)
    return Model(nodes, edges, modules.registry(store, root) or [], units,
                 [d for d in ddrs if d.get("id") and d.get("status") == "pending"])


def module_of(m: Model, nid: str) -> str:
    """A node's module: its props.module when the registry knows it, else ''."""
    mod = str(_props(m.nodes.get(nid, {})).get("module") or "")
    return mod if mod in {str(x["id"]) for x in m.registry} else ""


def subjects(m: Model, u: Unit) -> list[str]:
    """The modules a unit is about (the modules of its nodes), or [UNPLACED]."""
    mods = sorted({module_of(m, x) for x in u.about} - {""})
    return mods or [UNPLACED]


def in_force(m: Model, nids: set[str]) -> list[tuple[str, Unit, list[Unit]]]:
    """(node, the unit in force on it, the earlier ones folded) for each node of ``nids`` some unit is about: the
    newest answer wins (by date, then id)."""
    by_node: dict[str, list[Unit]] = {}
    for u in m.units:
        for x in u.about:
            if x in nids:
                by_node.setdefault(x, []).append(u)
    out = []
    for nid in sorted(by_node):
        us = sorted(by_node[nid], key=lambda u: (u.date, u.id), reverse=True)
        live = [u for u in us if not u.superseded] or us
        out.append((nid, live[0], [u for u in us if u is not live[0]]))
    return out


def _unit_line(u: Unit) -> str:
    went = f" (in {', '.join(f'`{a}`' for a in u.adrs)})" if u.kind == "ddr" and u.adrs else ""
    gone = (", superseded" + (f" by `{u.superseded_by}`" if u.superseded_by else "")) if u.superseded else ""
    return f"`{u.id}`: {u.text}{went}{gone}"


def _members(m: Model, mid: str) -> set[str]:
    return {nid for nid in m.nodes if module_of(m, nid) == mid}


def _linked(m: Model, nids: set[str], etype: str, ntype: str) -> list[str]:
    return sorted({str(e["to"]) for e in m.edges if e.get("type") == etype and str(e["from"]) in nids
                   and m.nodes.get(str(e["to"]), {}).get("type") == ntype})


def _title(m: Model, nid: str) -> str:
    return _short(m.nodes.get(nid, {}).get("title", ""))


def _status_rank(m: Model, f: str) -> tuple:
    st = m.nodes[f].get("status")
    return (features.STATUSES.index(st) if st in features.STATUSES else 9, f)


def _list(title: str, lines: list[str], none: str = "None.") -> list[str]:
    return ["", title, ""] + (lines or [none])


def _decisions_section(m: Model, own: set[str]) -> list[str]:
    out = []
    for nid, live, earlier in in_force(m, own):
        out += [f"- **`{nid}`** {_title(m, nid)}", f"  - {_unit_line(live)}"]
        out += [f"  - earlier: {_unit_line(u)}" for u in earlier]
    return _list("## Decisions in force", out, "None recorded on its nodes.")


def _items_section(m: Model, own: set[str]) -> list[str]:
    items = sorted(n for n in own if m.nodes[n].get("type") == "WorkItem")
    done = [n for n in items if m.nodes[n].get("status") == "done"]
    opened = [n for n in items if m.nodes[n].get("status") in OPEN]
    lines = [f"- [ ] `{n}`: {_title(m, n)}" for n in opened] + [f"- [x] `{n}`: {_title(m, n)}" for n in done]
    return _list(f"## Items: {len(done)} done, {len(opened)} open", lines)


def _asked_about(m: Model, d: dict, mid: str) -> bool:
    return any(module_of(m, x) == mid for x in _about(d))


def render_module(m: Model, mod: dict, store_label: str, prose: dict | None = None) -> str:
    mid = str(mod["id"])
    own = _members(m, mid)
    feats = sorted((n for n in own if m.nodes[n].get("type") == features.TYPE), key=lambda f: _status_rank(m, f))
    items = {n for n in own if m.nodes[n].get("type") == "WorkItem"}
    note = f" {_cell(mod['note'])}" if mod.get("note") else ""
    texts = (prose or {}).get("modules")
    intro = str(texts.get(mid) or "").strip() if isinstance(texts, dict) else ""
    out = [f"# {mid} {_cell(mod.get('name'))}".rstrip(), "",
           f"{MARKER} from `{store_label}` (its modules.yaml, its nodes and the DDR records) and `{YAML}`. Do not "
           "edit: change the graph or the YAML, then brain sync.", "",
           *([intro, ""] if intro else []),
           f"Brick {mod.get('brick') or '?'}, phase {mod.get('phase') or '?'}, {mod.get('status', 'tree')}.{note}"]
    out += _list("## What it does", [f"- **{_title(m, f)}** `{f}` ({m.nodes[f].get('status')})" for f in feats],
                 "No feature yet.")
    out += _decisions_section(m, own)
    out += _list("## Rules", [f"- `{r}`: {_title(m, r)}" for r in _linked(m, items, "delivers", "Rule")],
                 "None delivered by its items.")
    out += _list("## Specs", [f"- `{s}`: {_title(m, s)}" for s in _linked(m, own, "specified_by", "Spec")])
    out += _items_section(m, own)
    out += _list("## Open questions", [f"- `{d['id']}`" for d in sorted(m.pending, key=lambda d: str(d["id"]))
                                       if _asked_about(m, d, mid)])
    return "\n".join(out) + "\n"


def _placed(m: Model) -> dict[str, list[Unit]]:
    """{module or UNPLACED: the units about it}."""
    placed: dict[str, list[Unit]] = {mid: [] for mid in [str(x["id"]) for x in m.registry] + [UNPLACED]}
    for u in m.units:
        for s in subjects(m, u):
            placed.setdefault(s, []).append(u)
    return placed


def _index_row(m: Model, mod: dict, placed: dict[str, list[Unit]]) -> str:
    mid = str(mod["id"])
    own = _members(m, mid)
    kinds = [m.nodes[n].get("type") for n in own]
    st = [m.nodes[n].get("status") for n in own if m.nodes[n].get("type") == "WorkItem"]
    return (f"| [{mid}]({MODULES_DIR}/{page_name(mid)}) | {_cell(mod.get('name'))} | {mod.get('brick') or '?'} | "
            f"{kinds.count(features.TYPE)} | {st.count('done')} | {sum(1 for s in st if s in OPEN)} | "
            f"{len(placed.get(mid, []))} |")


def render_index(m: Model, store_label: str, prose: dict | None = None, ctx: dict | None = None) -> str:
    """docs/reference/README.md: the twelve arc42 sections (brain.arc42), the module pages as section 5."""
    out = ["# Technical reference", "",
           f"{MARKER} from `{store_label}` and `{YAML}`: the twelve arc42 sections, each from its source in the graph "
           "(every statement with its status and its id), the prose from the YAML; one page per module of the "
           "registry (`modules.yaml`) with what it does, the decisions in force on its nodes (the newest answered "
           "DDR, the earlier ones folded; an ADR no DDR went to by its title), its rules, specs, items and open "
           "questions. Do not edit: change the graph or the YAML, then brain sync. The decision log stays the "
           "history.", "",
           "Sections: " + " · ".join(f"[{t}](#{_slug(t)})" for _, t in arc42.SECTIONS)]
    ctx = {"placed": _placed(m), **(ctx or {})}
    out += arc42.sections(m, prose or {}, ctx)
    return "\n".join(out) + "\n"


# --- the prose: docs/reference.yaml ---

def load_prose(root: Path) -> tuple[dict, list[str]]:
    """(docs/reference.yaml as a mapping, what it breaks of its schema): ({}, []) when the repo has none (the
    skeleton then shows its facts only); an unreadable file is ({}, [why])."""
    f = Path(root) / YAML
    if not f.is_file():
        return {}, []
    try:
        data = graph.load_yaml(f.read_text(encoding="utf-8"))
    except (OSError, ValueError, graph._yaml().YAMLError) as exc:
        return {}, [f"{YAML}: cannot be read ({exc})"]
    if not isinstance(data, dict):
        return {}, [f"{YAML}: not a mapping (its fields: v, goals, strategy, glossary...)"]
    return data, [f"{YAML}: {e}" for e in schema.schema_errors(KIND, data, schema.mode())]


def _context(root: Path, store: Path) -> dict:
    """What section 3 and 7 read beyond the store: the registry, this project's name and its stacks."""
    from . import resume
    try:
        p = resume.project_for(root)
    except SystemExit:   # a project the registry refuses: the sections say what they can without it
        p = None
    stacks = []
    if p is not None and p.registered:
        stacks = sorted(map(str, p.stacks)) if isinstance(p.stacks, dict) else ([str(p.stacks)] if p.stacks else [])
    return {"registry": arc42.registry(root), "project": p.name if p is not None and p.registered else "",
            "stacks": stacks}


def render(root: Path, store: Path, store_label: str = "notes/graph") -> dict[str, str]:
    """{path relative to docs/reference/: text} of the project's reference."""
    m = load(root, store)
    prose, _ = load_prose(root)
    out = {"README.md": render_index(m, store_label, prose, _context(root, store))}
    for mod in m.registry:
        out[f"{MODULES_DIR}/{page_name(str(mod['id']))}"] = render_module(m, mod, store_label, prose)
    return out


# --- the neutral render (the engine's public repo) ---

def _public_prose(prose: dict | None) -> list[str]:
    """The public repo's own prose (its docs/reference.yaml): goals, strategy, glossary; checked by :func:`denied`
    like the rest of the render."""
    prose = prose or {}
    out = []
    for key, title in (("goals", "Goals"), ("strategy", "Strategy")):
        if str(prose.get(key) or "").strip():
            out += [f"## {title}", "", str(prose[key]).strip(), ""]
    terms = [g for g in prose.get("glossary") or [] if isinstance(g, dict) and g.get("term")]
    if terms:
        out += ["## Glossary", "", "| Term | Means |", "|---|---|"]
        out += [f"| {_cell(g['term'])} | {_cell(g.get('means'))} |"
                for g in sorted(terms, key=lambda g: str(g["term"]).lower())] + [""]
    return out


def render_public(store: Path, repo: str, default_repo: str = "", prose: dict | None = None) -> dict[str, str]:
    """{path: text} of the neutral reference of ``repo``: by feature domain, from its features only (public titles
    and ids, the repo's own code and docs), headed by the goals, strategy and glossary of the public repo's own
    docs/reference.yaml when it has one; no module, spec, ADR, DDR, item nor rule."""
    fm = features.load_store(store, default_repo)
    repo = repo.lower()
    feats = sorted(f for f in fm.features if fm.repo.get(f) == repo)
    by_domain: dict[str, list[str]] = {}
    for f in feats:
        by_domain.setdefault(str((fm.features[f].get("props") or {}).get("domain") or "other"), []).append(f)
    head = [f"# Technical reference — {repo}", "",
            f"{MARKER} from the features of this repo ({PUBLIC_NOTE}: their neutral titles, this repo's own code "
            "and docs, nothing of the brain that tracks it). Do not edit: it is rendered again into a checkout of this "
            f"repo (`brain reference --public --repo {repo} --out <checkout>/{DIR} --write`).", ""]
    head += _public_prose(prose)
    if not feats:
        return {"README.md": "\n".join(head + ["No feature yet."]) + "\n"}
    out = {}
    index = head + (["## Building blocks, by feature domain", ""] if prose else []) + [
        "| Domain | Features | have | partial | planned | Ids |", "|---|---|---|---|---|---|"]
    for d in sorted(by_domain):
        fs = by_domain[d]
        st = [str(fm.features[f].get("status")) for f in fs]
        ids = ", ".join(f"`{features.shown_id(fm, f, True)}`" for f in fs)
        index.append(f"| [{d}]({DOMAINS_DIR}/{_slug(d)}.md) | {len(fs)} | {st.count('have')} | "
                     f"{st.count('partial')} | {st.count('planned')} | {ids} |")
        out[f"{DOMAINS_DIR}/{_slug(d)}.md"] = _domain_page(fm, d, fs, repo)
    out["README.md"] = "\n".join(index) + "\n"
    return out


def _domain_page(fm: features.Model, domain: str, fs: list[str], repo: str) -> str:
    """One domain's page of the neutral render: its features nested by parent, each with its own code and docs."""
    page = [f"# {domain}", "", f"{MARKER} (the public render of `{repo}`'s features). Do not edit.", ""]
    for f, depth in features._order(fm, fs):
        p = "  " * depth
        page.append(f"{p}- **{features._cell(features.shown_title(fm, f, True))}** "
                    f"`{features.shown_id(fm, f, True)}` ({fm.features[f].get('status')})")
        code = features._code_cell(fm, f, repo, True)
        docs = features._shown_links(fm, f, "documented_in", repo, True)
        page += [f"{p}  - code: " + code.replace("](", f"]({UP}")] if code else []   # links from the root
        page += [f"{p}  - docs: " + ", ".join(f"`{x}`" for x in docs)] if docs else []
    return "\n".join(page) + "\n"


def denied(files: dict[str, str], cfg=None) -> list[str]:
    """What brain check --public would refuse in a public render, one line each (``path: line``)."""
    return [f"{p}: {line}" for p, text in sorted(files.items()) for line in features.denied_lines(text, cfg)]


# --- writing and checking ---

def _read(f: Path) -> str | None:
    """A page as it is (CRLF read as LF, bad bytes replaced), None when there is none."""
    return f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n") if f.is_file() else None


def stale(base: Path, files: dict[str, str]) -> list[str]:
    """The files of ``base`` (a docs/reference/ folder) that are not the render: missing, different, or a generated
    page no longer rendered."""
    out = [p for p, text in sorted(files.items()) if _read(base / p) != text]
    for sub in (MODULES_DIR, DOMAINS_DIR):
        for f in sorted((base / sub).glob("*.md")) if (base / sub).is_dir() else []:
            rel = f"{sub}/{f.name}"
            if rel not in files and generated(_read(f) or ""):
                out.append(rel)
    return out


def write(base: Path, files: dict[str, str]) -> tuple[list[str], list[str]]:
    """Write the render into ``base``; the generated pages no longer rendered are removed. (the paths changed, the
    paths kept: a page there that is not generated, the owner's, is never overwritten)."""
    changed, kept = [], []
    for p in stale(base, files):
        f = base / p
        old = _read(f)
        if old is not None and not generated(old):
            kept.append(p)
        elif p in files:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(files[p], encoding="utf-8", newline="\n")
            changed.append(p)
        else:
            f.unlink()
            changed.append(p)
    return changed, kept


def private_render(base: Path) -> bool:
    """Whether ``base`` holds a project's reference that brain sync keeps current: its README.md is this module's
    render, not a public one (the owner's opt-in is `brain reference --write`, which writes it)."""
    head = _read(base / "README.md") or ""
    return generated(head) and PUBLIC_NOTE not in "\n".join(head.splitlines()[:5])
