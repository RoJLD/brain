"""The documentation dependency graph (wi-brain-docs-graph; docs/docs-graph.md): a catalogue of every doc file a Doc
node belongs to, the links declared between docs, and staleness, at zero token.

- **Catalogue**: per doc file (the Doc nodes of brain.links are its sections): its kind (Diataxis: tutorial, how-to,
  reference, explanation; ``generated`` and ``dated-spec`` apart), its last commit, its owner when declared, the nodes
  its sections cite (the ``documented_in`` edges into them) and the docs that cite it (a section that names its path).
  A doc declares its kind and owner in its first lines: ``<!-- doc: kind=how-to owner=ops -->``; otherwise its kind
  comes from its path and its first lines (a ``GENERATED`` marker, a dated name).
- **Declared links**: a hand edge ``depends_on`` from a Doc section to another (the store's own edges files), with
  ``props.reason``: a dependency the text does not cite. One without a reason is a warning.
- **Staleness** (``doc.stale``): a hand-written doc whose cited node changed after the doc's last commit (the node's
  entry in the store's YAML, compared as text with the store as of that commit), or whose declared parent's last
  commit is later than its own. A doc with uncommitted changes is being edited: never stale. Generated docs and dated
  specs are exempt (a spec is history). Section level: each stale section is named.

The view ``docs_graph.md`` (beside the store's other views, written by ``brain sync``), ``brain check``'s warnings,
the scout's ``doc.reread`` lines (``brain audit --diff``: a change edits a node a doc it does not touch cites) and
:func:`to_docgraph` (``brain docgraph emit``, the docgraph/v1 contract) read the same catalogue.
"""

from __future__ import annotations

import posixpath
import re
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from . import graph, links, mergedriver

FILE = "docs_graph.md"
KINDS = ("tutorial", "how-to", "reference", "explanation", "generated", "dated-spec")
EXEMPT = ("generated", "dated-spec")
DECLARED = re.compile(r"<!--\s*doc:(?P<body>[^>]*?)-->")
PAIR = re.compile(r"(\w+)=(\S+)")
DATED_NAME = re.compile(r"^\d{4}-\d{2}-\d{2}")
HEAD_LINES = 6
GIT_TIMEOUT = 60
CHUNK = 200   # paths per git command line
HEAD = ("# Documentation graph\n\nGENERATED by `brain sync` (brain.docsgraph) from the Doc nodes, their documented_in "
        "edges, the declared depends_on links between docs and git. Do not edit: declare a doc's kind and owner in "
        "its first lines (`<!-- doc: kind=how-to owner=ops -->`), a dependency as a depends_on edge with "
        "props.reason, then brain sync.\n")


@dataclass
class Doc:
    """A doc file of the catalogue."""
    repo: str
    path: str
    kind: str = "explanation"
    owner: str = ""
    sections: list[str] = field(default_factory=list)        # its Doc node ids
    titles: dict[str, str] = field(default_factory=dict)      # a section's id -> its title
    cites: dict[str, set[str]] = field(default_factory=dict)  # a section's id -> the node ids that cite it
    cited_by: set[str] = field(default_factory=set)           # the paths of the docs whose sections name it
    parents: list[tuple[str, str, str]] = field(default_factory=list)   # (its section, the parent section, reason)
    last: datetime | None = None    # its last commit; None: not committed, or its checkout is not here
    sha: str = ""                   # that commit
    top: Path | None = None         # the checkout it was read from
    dirty: bool = False             # uncommitted changes: being edited
    stale: list[tuple[str, str]] = field(default_factory=list)   # (its section, why)

    @property
    def exempt(self) -> bool:
        return self.kind in EXEMPT

    @property
    def key(self) -> str:
        return f"{self.repo}:{self.path}"


@dataclass
class Catalogue:
    repo: str = ""                                      # the root's repo: its docs are named by their path alone
    docs: dict[str, Doc] = field(default_factory=dict)   # Doc.key -> Doc
    section_of: dict[str, str] = field(default_factory=dict)   # a Doc node id -> its Doc.key
    nodes: dict[str, dict] = field(default_factory=dict)       # the store's nodes by id
    warnings: list[str] = field(default_factory=list)


# --- reading ----------------------------------------------------------------------------------------------------------

def applies(store: Path) -> bool:
    """A store whose schema has the Doc type and whose links graph is written (brain.links)."""
    return links.applies(store) and links.files(store)[0].is_file()


def declared(text: str) -> dict[str, str]:
    """The kind and owner a doc declares in its first lines (``<!-- doc: kind=how-to owner=ops -->``)."""
    m = DECLARED.search("\n".join(text.splitlines()[:HEAD_LINES]))
    return dict(PAIR.findall(m.group("body"))) if m else {}


def kind_of(path: str, text: str) -> str:
    """A doc's kind: its declaration, else generated (a GENERATED marker in its first lines), dated-spec (a spec of
    docs/specs, or a file named by its date: a record of that day), how-to (a runbook, an install or release page),
    tutorial, reference (docs/reference, a formats or schema page), else explanation."""
    kind = declared(text).get("kind", "")
    if kind in KINDS:
        return kind
    if "GENERATED" in "\n".join(text.splitlines()[:HEAD_LINES]):
        return "generated"
    name = posixpath.basename(path).lower()
    if links.is_spec(path) or DATED_NAME.match(name):
        return "dated-spec"
    low = path.lower()
    if "runbook" in low or "how-to" in low or "howto" in low or name in ("install.md", "release.md"):
        return "how-to"
    if "tutorial" in low or "quickstart" in low or "getting-started" in low:
        return "tutorial"
    if "/reference/" in f"/{low}" or name in ("formats.md", "schema.md"):
        return "reference"
    return "explanation"


def _git(top: Path, *args: str) -> str:
    """git's output in ``top`` ('' on any failure: no git, not a repo, a timeout); paths unquoted (core.quotePath)."""
    try:
        r = subprocess.run(["git", "-C", str(top), "-c", "core.quotePath=false", *args], capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=GIT_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return r.stdout if r.returncode == 0 else ""


def _chunks(paths: list[str]) -> list[list[str]]:
    """``paths`` in groups that keep a git command line short (Windows caps it near 32k characters)."""
    return [paths[i:i + CHUNK] for i in range(0, len(paths), CHUNK)]


def last_commits(top: Path, paths: list[str]) -> dict[str, tuple[datetime, str]]:
    """The last commit (time, sha) of each path (a git log per group of paths; a path never committed is left out)."""
    out: dict[str, tuple[datetime, str]] = {}
    for group in _chunks(paths):
        when: tuple[datetime, str] | None = None
        for line in _git(top, "log", "--format=%x00%cI %H", "--name-only", "--", *group).splitlines():
            if line.startswith("\x00"):
                stamp, _, sha = line[1:].strip().partition(" ")
                when = (datetime.fromisoformat(stamp), sha)
            elif line.strip() and when is not None and line.strip() not in out:
                out[line.strip()] = when
    return out


def dirty(top: Path, paths: list[str]) -> set[str]:
    """The paths with uncommitted changes (staged, unstaged or untracked; a rename's new path)."""
    out: set[str] = set()
    for group in _chunks(paths):
        for line in _git(top, "status", "--porcelain", "--", *group).splitlines():
            if len(line) > 3:
                out.add(line[3:].split(" -> ")[-1].strip().strip('"'))
    return out


def _norm(text: str) -> str:
    """An entry's text without its whole-line comments and blank lines: what a change of the node itself changes (a
    comment at the end of an entry's line is part of that line)."""
    return "\n".join(x.rstrip() for x in text.splitlines() if x.strip() and not x.lstrip().startswith("#"))


def entries_of(text: str) -> dict[str, str]:
    """The node entries of a store's YAML file, by id (mergedriver.entries), normalised; {} when it is not a list of
    entries."""
    got = mergedriver.entries(text)
    return {nid: _norm(t) for nid, t in got.items} if got else {}


def _hand_files(nodes_dir: Path) -> list[Path]:
    return sorted(p for p in nodes_dir.glob("*.yaml") if not p.name.startswith("_generated"))


def entries_now(store: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for f in _hand_files(store / "nodes"):
        out.update(entries_of(f.read_text(encoding="utf-8")))
    return out


def store_location(store: Path) -> tuple[Path, str]:
    """(the git top of the store's repo, the store's path inside it, posix: '' at the top) or (store, '') when not in
    git."""
    top = _git(store, "rev-parse", "--show-toplevel").strip()
    if not top:
        return store, ""
    top_p = Path(top).resolve()
    try:
        rel = store.resolve().relative_to(top_p).as_posix()
    except ValueError:
        return top_p, ""
    return top_p, "" if rel == "." else rel


def _batch(top: Path, specs: list[str]) -> dict[str, str | None] | None:
    """The text of each ``<rev>:<path>`` (None when missing), through one git cat-file --batch; None when git fails."""
    if not specs:
        return {}
    try:
        r = subprocess.run(["git", "-C", str(top), "cat-file", "--batch"],
                           input="".join(f"{s}\n" for s in specs).encode("utf-8"), capture_output=True,
                           timeout=GIT_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode:
        return None
    out: dict[str, str | None] = {}
    data, pos = r.stdout, 0
    for spec in specs:
        end = data.find(b"\n", pos)
        if end < 0:
            return None   # cut short: nothing judged from it
        head = data[pos:end].split()
        pos = end + 1
        if len(head) < 3 or head[-1] == b"missing":
            out[spec] = None
            continue
        size = int(head[2])
        out[spec] = data[pos:pos + size].decode("utf-8", "replace")
        pos += size + 1
    return out


def _names_at(top: Path, nodes_dir: str, rev: str) -> list[str]:
    """The store's hand node files at ``rev`` (a file since split or renamed included)."""
    return [posixpath.basename(p) for p in _git(top, "ls-tree", "--name-only", rev, f"{nodes_dir}/").splitlines()
            if p.endswith(".yaml") and not posixpath.basename(p).startswith("_generated")]


def entries_at_revs(top: Path, prefix: str, revs: list[str]) -> dict[str, dict[str, str]]:
    """The node entries of the store's hand files at each of ``revs`` (their names read at each rev, the files in one
    cat-file for all, a blob parsed once). A rev git cannot read is left out: nothing is judged against it."""
    nodes_dir = f"{prefix}/nodes" if prefix else "nodes"
    specs = [f"{rev}:{nodes_dir}/{n}" for rev in revs for n in _names_at(top, nodes_dir, rev)]
    texts = _batch(top, specs)
    if texts is None:
        return {}
    memo: dict[str, dict[str, str]] = {}
    out: dict[str, dict[str, str]] = {rev: {} for rev in revs if any(s.startswith(f"{rev}:") for s in specs)}
    for spec in specs:
        text = texts.get(spec)
        if text is None:
            continue
        if text not in memo:
            memo[text] = entries_of(text)
        out[spec.split(":", 1)[0]].update(memo[text])
    return out


def entries_at(top: Path, prefix: str, rev: str) -> dict[str, str]:
    """The node entries of the store's hand files at ``rev`` ({} when git cannot read it)."""
    return entries_at_revs(top, prefix, [rev]).get(rev, {})


def first_parents(top: Path) -> list[tuple[datetime, str]]:
    """HEAD's first-parent chain, newest first: (commit time, sha)."""
    out = []
    for line in _git(top, "log", "--first-parent", "--format=%cI %H", "HEAD").splitlines():
        when, _, sha = line.partition(" ")
        if sha:
            out.append((datetime.fromisoformat(when), sha))
    return out


def rev_at(chain: list[tuple[datetime, str]], when: datetime) -> str:
    """The newest commit of ``chain`` (first_parents) made at or before ``when``; '' when none."""
    return next((sha for t, sha in chain if t <= when), "")


def _anchor_path(node: dict) -> str:
    return str(node.get("anchor", "")).split("#", 1)[0]


def load(root: Path, store: Path, repo: str, roots: dict[str, Path] | None = None) -> Catalogue:
    """The catalogue of ``store``'s docs: ``repo`` is the root's repo (its docs are read under ``root``), ``roots`` the
    checkouts of the project's other repos (links.anchor_roots); a doc whose checkout is not here has no last commit
    and is never stale."""
    cat = Catalogue(repo=repo)
    gen_nodes, gen_edges = links.files(store)
    gen = _dicts(gen_nodes)
    cat.nodes = {str(n.get("id")): n for n in [*_hand_nodes(store), *gen]}
    for n in gen:
        _add_section(cat, n, str(n.get("repo") or repo))
    cat.docs = {k: d for k, d in cat.docs.items() if d.sections}   # a path named that is no doc of the graph
    for e in _edges_of(gen_edges, "documented_in"):
        _cite(cat, str(e.get("from")), str(e.get("to")))
    for f in _hand_files(store / "edges"):
        for e in _edges_of(f, "depends_on"):
            _declare(cat, str(e.get("from")), str(e.get("to")), str((e.get("props") or {}).get("reason") or ""))
    _read_files(cat, {repo: root, **(roots or {})})
    return cat


def _hand_nodes(store: Path) -> list[dict]:
    return [n for f in _hand_files(store / "nodes") for n in _dicts(f)]


def _dicts(f: Path) -> list[dict]:
    return [x for x in graph.load_yaml_list(f) if isinstance(x, dict)]


def _cite(cat: Catalogue, nid: str, section: str) -> None:
    if section in cat.section_of:
        cat.docs[cat.section_of[section]].cites.setdefault(section, set()).add(nid)


def _edges_of(f: Path, etype: str) -> list[dict]:
    return [e for e in _dicts(f) if e.get("type") == etype]


def _add_section(cat: Catalogue, n: dict, repo: str) -> None:
    """A Doc node joins its file's entry; the docs its section names (props.paths) are cited by that file."""
    path, sid = _anchor_path(n), str(n.get("id"))
    if n.get("type") != "Doc" or not path:
        return
    doc = cat.docs.setdefault(f"{repo}:{path}", Doc(repo, path))
    doc.sections.append(sid)
    doc.titles[sid] = str(n.get("title", path))
    cat.section_of[sid] = doc.key
    for p in (n.get("props") or {}).get("paths") or []:
        if p != path and str(p).endswith(".md"):
            cat.docs.setdefault(f"{repo}:{p}", Doc(repo, p)).cited_by.add(path)


def _declare(cat: Catalogue, src: str, dst: str, reason: str) -> None:
    """A hand depends_on edge: a declared link when both ends are Doc sections; a warning when one end only is, or
    when it gives no reason."""
    if src not in cat.section_of and dst not in cat.section_of:
        return   # a dependency between other nodes
    if src not in cat.section_of or dst not in cat.section_of:
        cat.warnings.append(f"docs: depends_on {src} -> {dst}: both ends must be Doc sections")
        return
    if not reason:
        cat.warnings.append(f"docs: depends_on {src} -> {dst} gives no props.reason (a declared link says why the "
                            f"docs depend on each other)")
    cat.docs[cat.section_of[src]].parents.append((src, dst, reason))


def _read_files(cat: Catalogue, roots: dict[str, Path]) -> None:
    by_repo: dict[str, list[Doc]] = {}
    for d in cat.docs.values():
        by_repo.setdefault(d.repo, []).append(d)
    for r, docs in by_repo.items():
        top = roots.get(r)
        if top is None:
            continue
        paths = [d.path for d in docs]
        commits, edited = last_commits(top, paths), dirty(top, paths)
        for d in docs:
            f = top / d.path
            text = f.read_text(encoding="utf-8", errors="replace") if f.is_file() else ""
            d.kind, d.owner = kind_of(d.path, text), declared(text).get("owner", "")
            d.last, d.sha = commits.get(d.path, (None, ""))
            d.dirty, d.top = d.path in edited, top.resolve()


# --- staleness --------------------------------------------------------------------------------------------------------

def mark_stale(cat: Catalogue, store: Path) -> None:
    """Set each hand-written, committed, unedited doc's stale sections: a cited node whose entry differs from the
    store's as of the doc's last commit (a node created since counts), a declared parent committed after it, or
    being edited. A doc of the store's own repo is compared with the store at its own last commit (merged by a merge
    commit too); a doc of another repo with the store's last first-parent commit made before its last commit."""
    top, prefix = store_location(store)
    now = entries_now(store)
    todo = [d for d in cat.docs.values() if not d.exempt and not d.dirty and d.last is not None]
    chain = first_parents(top) if any(d.top != top for d in todo) else []
    rev_of = {d.key: d.sha if d.top == top else rev_at(chain, d.last) for d in todo}
    at = entries_at_revs(top, prefix, sorted(set(rev_of.values()) - {""}))
    for d in todo:
        _stale_sections(d, at.get(rev_of[d.key]), now)
        _stale_parents(cat, d)


def _stale_parents(cat: Catalogue, d: Doc) -> None:
    """The sections of ``d`` whose declared parent is being edited or was committed after ``d``."""
    for sec, parent, _ in d.parents:
        p = cat.docs.get(cat.section_of.get(parent, ""))
        if p is not None and p.dirty:
            d.stale.append((sec, f"its declared parent {p.path} is being edited"))
        elif p is not None and p.last is not None and p.last > d.last:
            d.stale.append((sec, f"its declared parent {p.path} changed after its last commit"))


def _stale_sections(d: Doc, then: dict[str, str] | None, now: dict[str, str]) -> None:
    """The sections of ``d`` that cite a node whose entry now differs from ``then`` (the store at its last commit)."""
    if then is None:
        return
    for sec in d.sections:
        changed = sorted(nid for nid in d.cites.get(sec, ()) if nid in now and then.get(nid) != now[nid])
        if changed:
            more = f" (+{len(changed) - 5})" if len(changed) > 5 else ""
            d.stale.append((sec, f"cites {', '.join(changed[:5])}{more}, changed after its last commit "
                                 f"({d.last.date().isoformat()})"))


def catalogue(root: Path, store: Path, repo: str, roots: dict[str, Path] | None = None) -> Catalogue:
    cat = load(root, store, repo, roots)
    mark_stale(cat, store)
    return cat


def stale_lines(cat: Catalogue, own_only: bool = False) -> list[str]:
    """The stale sections, one line each (``own_only``: the docs of the store's own repo, the view's)."""
    return [f"doc.stale: {d.path} § {d.titles.get(sec, sec).split(' § ', 1)[-1]}: {why}: re-read it"
            for d in sorted(cat.docs.values(), key=lambda x: x.key) if d.repo == cat.repo or not own_only
            for sec, why in d.stale]


# --- the view ---------------------------------------------------------------------------------------------------------

def render(cat: Catalogue) -> str:
    """The generated view: the catalogue by kind, then the stale sections and the declared links."""
    docs = sorted(cat.docs.values(), key=lambda d: (KINDS.index(d.kind) if d.kind in KINDS else 9, d.key))
    lines = [HEAD, "| Doc | Kind | Last commit | Owner | Sections | Cites | Cited by | Stale |",
             "|---|---|---|---|---|---|---|---|"]
    lines += [_row(d, cat.repo) for d in docs]
    stale = stale_lines(cat, own_only=True)
    lines += ["", f"## Docs to re-read ({len(stale)})", ""]
    lines += [f"- {x.removeprefix('doc.stale: ')}" for x in stale] or ["None."]
    declared_links = [(d, s, p, r) for d in docs for s, p, r in d.parents]
    lines += ["", f"## Declared links ({len(declared_links)})", ""]
    lines += [f"- {s} depends on {p}: {r or '(no reason given)'}" for d, s, p, r in declared_links] or ["None."]
    return "\n".join(lines) + "\n"


def _row(d: Doc, own: str) -> str:
    """A doc's row; another repo's doc shows no last commit and no staleness (brain check says them): its checkout
    moves on its own, and the view is a function of this repo."""
    cites = len(set().union(*d.cites.values())) if d.cites else 0
    mine = d.repo == own
    last = "-" if not mine or not d.last else ("edited" if d.dirty else d.last.date().isoformat())
    stale = "exempt" if d.exempt else (str(len(d.stale)) if d.stale and mine else "")
    name = d.path if mine else f"{d.repo}: {d.path}"
    return (f"| `{name}` | {d.kind} | {last} | {d.owner or '-'} | {len(d.sections)} | {cites} | {len(d.cited_by)} | "
            f"{stale} |")


def write(root: Path, view: str, text: str) -> bool:
    f = root / view
    if f.is_file() and f.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8", newline="\n")
    return True


def is_stale_view(root: Path, view: str, text: str) -> bool:
    f = root / view
    return not f.is_file() or f.read_text(encoding="utf-8").replace("\r\n", "\n") != text


# --- the scout: docs to re-read ---------------------------------------------------------------------------------------

def reread(top: Path, store_prefix: str, base_rev: str, new_rev: str, touched: set[str], cat: Catalogue) -> list[dict]:
    """The scout's info lines: each doc a change does not touch whose sections cite a node the change edits (its entry
    differs between the base and the change, in the store at ``store_prefix`` of the repo at ``top``)."""
    before = entries_at(top, store_prefix, base_rev)
    if not before:   # git could not read the base's store (or it had none): nothing is judged against it
        return []
    after = entries_at(top, store_prefix, new_rev) if new_rev else entries_now(top / store_prefix if store_prefix
                                                                                  else top)
    edited = {nid for nid in set(before) | set(after) if before.get(nid) != after.get(nid)}
    out = []
    for d in sorted(cat.docs.values(), key=lambda x: x.key):
        if d.exempt or (d.repo == cat.repo and d.path in touched):
            continue
        hit = sorted({nid for ids in d.cites.values() for nid in ids} & edited)
        if hit:
            out.append({"tag": "info", "severity": "info", "check": "doc.reread", "class": "", "unit": d.path,
                        "why": f"cites {', '.join(hit[:5])}{' ...' if len(hit) > 5 else ''}, which the change edits: "
                               "docs to re-read", "fix": ""})
    return out


# --- docgraph/v1 ------------------------------------------------------------------------------------------------------

TYPE_MAP = {"ADR": "decision", "DDR": "decision", "WorkItem": "item", "Milestone": "milestone", "Test": "test",
            "Lesson": "finding"}
STATUS_MAP = {"todo": "open", "doing": "open", "blocked": "open", "done": "done", "dropped": "dropped",
              "pending": "planned", "reached": "closed", "active": "accepted", "superseded": "superseded",
              "proposed": "proposed", "answered": "accepted", "open": "open"}


def _dg_id(node: dict) -> str | None:
    t = TYPE_MAP.get(str(node.get("type")))
    return f"{t}:{node['id']}" if t else None


def _dg_section(d: Doc, sec: str, node: dict) -> dict:
    """A Doc section as a docgraph document node."""
    anchor = str(node.get("anchor", d.path))
    out = {"id": f"document:{sec}", "type": "document", "kind": d.kind, "title": d.titles.get(sec, d.path),
           "source": {"path": d.path, **({"anchor": anchor.split("#", 1)[1]} if "#" in anchor else {})}}
    if d.owner:
        out["owner"] = d.owner
    if d.last:
        out["updated"] = d.last.isoformat()
    if any(s == sec for s, _ in d.stale):
        out.update(status="stale", native_status="active")
    return out


def _dg_node(node: dict, did: str) -> dict:
    """A cited node of a type the contract has."""
    status = str(node.get("status"))
    out = {"id": did, "type": TYPE_MAP[str(node["type"])], "title": str(node.get("title", node["id"])),
           "source": {"path": "notes/graph"}}
    if status in STATUS_MAP:
        out.update(status=STATUS_MAP[status], native_status=status)
    return out


def _dg_cited(cat: Catalogue, d: Doc, sec: str, nodes: list, edges: list, seen: set) -> None:
    """The nodes a section cites, of the types the contract has (each once), and their documented_in edges."""
    for nid in sorted(d.cites.get(sec, ())):
        node = cat.nodes.get(nid) or {}
        did = _dg_id(node) if node else None
        if did is None:
            continue
        if did not in seen:
            seen.add(did)
            nodes.append(_dg_node(node, did))
        edges.append({"from": did, "to": f"document:{sec}", "type": "documented_in", "origin": "derived",
                      "source": {"path": d.path}})


def to_docgraph(cat: Catalogue, by: str, repo: str = "", ref: str = "", now: datetime | None = None) -> dict:
    """The catalogue as a docgraph/v1 document: a document node per Doc section (kind its file's), the cited nodes of
    the types the contract has (decisions, items, milestones, tests, lessons as findings), documented_in and the
    declared depends_on edges, and the checks this catalogue runs (doc.stale, cycle among the declared links)."""
    from . import docgraph
    now = now or datetime.now(timezone.utc)
    nodes, edges, findings, seen = [], [], [], set()
    for d in sorted(cat.docs.values(), key=lambda x: x.key):
        for sec in d.sections:
            nodes.append(_dg_section(d, sec, cat.nodes.get(sec, {})))
            _dg_cited(cat, d, sec, nodes, edges, seen)
        edges += [{"from": f"document:{sec}", "to": f"document:{parent}", "type": "depends_on", "origin": "declared",
                   "reason": reason or "(none given)", "confirmed": True} for sec, parent, reason in d.parents]
        findings += [{"id": "doc.stale", "severity": "warning", "subjects": [f"document:{sec}"], "message": why}
                     for sec, why in d.stale]
    findings += [{"id": "cycle", "severity": "error", "subjects": c, "message": "declared depends_on links loop"}
                 for c in _cycles([(e["from"], e["to"]) for e in edges if e["type"] == "depends_on"])]
    run = ["doc.stale", "cycle"]
    generated = {"at": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "by": by, "sources": {"files": True, "store": True}}
    generated.update({k: v for k, v in (("repo", repo), ("ref", ref)) if v})
    return {"schema": docgraph.ID, "generated": generated, "nodes": nodes, "edges": edges, "checks": findings,
            "checks_run": run, "checks_not_run": [c for c in docgraph.CHECK_IDS if c not in run]}


def _cycles(pairs: list[tuple[str, str]]) -> list[list[str]]:
    """The cycles of a small directed graph, each once (its nodes sorted)."""
    import networkx as nx
    return [list(c) for c in sorted({tuple(sorted(c)) for c in nx.simple_cycles(nx.DiGraph(pairs))})]
