"""``brain merge-driver``: a local git merge driver for a brain's generated views, append-only logs and graph YAML
(wi-brain-generated-merge; the owner's ADRs on ST-16 and SCALE-5, docs/merge-driver.md).

Git runs it on a merge (``git merge``, ``git pull``, ``git rebase``, ``git cherry-pick``, ``git merge-tree``) for the
paths ``.gitattributes`` gives ``merge=brain``, once the repo's git config defines the driver (``brain merge-driver
install --apply``, which the installer runs): ``brain merge-driver run %O %A %B %P %L``. It writes the result into %A
and exits 0 when it resolved everything, 1 when conflict markers remain. GitHub never runs a custom driver; it serves
the merges of the default branch into a branch, made locally in each worktree, so that the PR GitHub merges is clean.

The kind of a path, from its name and its first lines:

- **view**: a generated view, whose first lines say ``GENERATED by``` (the kanban, the roadmap, the decision queue,
  the audit, FEATURES.md) or whose name starts with ``_generated_``: one side is kept whole (the default branch's when
  one side is its version, else ours) and the path is marked for ``brain refresh``, which regenerates it;
- **log**: ``journal.md`` and ``decisions.md``, append-only and dated (``## YYYY-MM-DD``): what both sides appended is
  kept (the union), the new entries in date order; an edit both sides made to the same old lines stays a conflict,
  and so does a union whose dates are out of order when neither side's were;
- **union**: ``edges/*.yaml``, one edge per line: both sides' new lines, a line both added once; ``CHANGELOG.md``: the
  same in its Unreleased section only, where a ``### Added`` both sides opened becomes one;
- **yaml**: any other ``.yaml`` or ``.yml`` that is a list of ``id:`` entries: merged entry by entry (an entry changed
  on one side takes that side, the new entries of both sides are kept where they were added, an entry changed on both
  sides is merged line by line, else key by key with its props one level down and written as brain item set writes
  a node, else left as a conflict); a file that is not such a list is merged as text; a dated CHANGELOG without an
  Unreleased section is a log, newest first when written so;
- **text**: anything else: git's three-way merge (``git merge-file``).

Whatever goes wrong falls back to ``git merge-file``, so the driver never leaves a file without its conflict markers.
:func:`replay` replays a repo's past merges with and without the driver (``git merge-tree``, nothing checked out).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

NAME = "brain"                 # merge=brain in .gitattributes, merge.brain.* in the git config
MARK = "brain-refresh"         # in the worktree's git dir: the views kept from one side, until brain refresh
NO_MARK = "BRAIN_MERGE_NO_MARK"  # set: mark nothing (a replay)
LOGS = ("journal.md", "decisions.md")
DATED = re.compile(r"^## (\d{4}-\d{2}-\d{2})\b")
H2 = re.compile(r"^## ")
H3 = re.compile(r"^### ")
UNRELEASED = re.compile(r"^## \[?unreleased\]?\s*$", re.I)
GENERATED = re.compile(r"GENERATED by `")
HEAD_LINES = 5                 # a view's marker is in its first lines
ENTRY = re.compile(r"^(?P<ind>[ ]*)-[ ]")
ENTRY_ID = re.compile(r"^(?P<ind>[ ]*)-[ ]+(?:\{[ ]*)?id:[ ]*(?P<q>[\"']?)(?P<id>[^\"',}\s]+)(?P=q)")
INNER = 41                     # the marker size of the driver's own merge-file runs (never in a brain's files)

# The .gitattributes lines brain init writes (templates/generic/gitattributes) and brain merge-driver install checks.
ATTRIBUTES = """\
# brain merge-driver: generated views keep one side (then brain refresh), logs and edges are unioned, the graph's
# YAML is merged by id. brain merge-driver install --apply defines the driver; without it git merges these as text.
notes/journal.md merge=brain
notes/decisions.md merge=brain
notes/kanban_graph.md merge=brain
notes/roadmap_graph.md merge=brain
notes/decision_queue.md merge=brain
notes/audit.md merge=brain
notes/graph/nodes/*.yaml merge=brain
notes/graph/edges/*.yaml merge=brain
FEATURES.md merge=brain
CHANGELOG.md merge=brain
"""


class DriverError(RuntimeError):
    """git merge-file could not run: the caller falls back or reports."""


@dataclass
class Conflict:
    ours: list[str]
    base: list[str]
    theirs: list[str]


@dataclass
class Result:
    text: str
    conflicts: int = 0
    note: str = ""


# --- three-way merge by git ------------------------------------------------------------------------------------

def _decode(data: bytes) -> str:
    return data.decode("utf-8", "surrogateescape")


def _encode(text: str) -> bytes:
    return text.encode("utf-8", "surrogateescape")


def _lines(text: str) -> list[str]:
    return text.splitlines(keepends=True)


def _git(*args: str, cwd=None, data: bytes | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=cwd, input=data, capture_output=True, timeout=120,
                          stdin=None if data is not None else subprocess.DEVNULL)


def merge3(base: str, ours: str, theirs: str) -> list:
    """git merge-file --diff3 of three texts: a list of merged lines (str) and :class:`Conflict` hunks, in order."""
    with tempfile.TemporaryDirectory(prefix="brain-merge-") as d:
        files = []
        for name, text in (("ours", ours), ("base", base), ("theirs", theirs)):
            f = Path(d) / name
            f.write_bytes(_encode(text))
            files.append(str(f))
        r = _git("merge-file", "-p", "--diff3", f"--marker-size={INNER}", "-L", "ours", "-L", "base", "-L",
                 "theirs", *files)
    if r.returncode < 0 or r.returncode > 127:
        raise DriverError(f"git merge-file failed ({_decode(r.stderr).strip() or r.returncode})")
    return parse(_decode(r.stdout))


def parse(text: str, size: int = INNER) -> list:
    """The lines and conflicts of a diff3-style merge (markers of ``size``)."""
    start, mid, sep, end = ("<" * size + " "), ("|" * size + " "), ("=" * size), (">" * size + " ")
    out: list = []
    part = None
    cur: Conflict | None = None
    for line in _lines(text):
        bare = line.rstrip("\r\n")
        if cur is None and line.startswith(start):
            cur, part = Conflict([], [], []), "ours"
        elif cur is not None and line.startswith(mid) and part == "ours":
            part = "base"
        elif cur is not None and bare == sep and part in ("ours", "base"):
            part = "theirs"
        elif cur is not None and line.startswith(end) and part == "theirs":
            out.append(cur)
            cur, part = None, None
        elif cur is not None:
            getattr(cur, part).append(line)
        else:
            out.append(line)
    if cur is not None:
        raise DriverError("an unterminated conflict in git merge-file's output")
    return out


def _nl(text: str) -> str:
    return "\r\n" if text.count("\r\n") * 2 > text.count("\n") else "\n"


def _join(chunks: list[list[str]]) -> list[str]:
    """Lines of consecutive chunks, a newline added where a chunk's last line has none."""
    out: list[str] = []
    for chunk in chunks:
        if out and chunk and not out[-1].endswith("\n"):
            out[-1] += "\n"
        out.extend(chunk)
    return out


def render(segments: list, size: int = 7, style: str = "merge", nl: str = "\n") -> Result:
    """Segments back to text, a conflict as git writes it (``style`` diff3 or zdiff3 shows the base)."""
    out: list[str] = []
    n = 0
    for seg in segments:
        if isinstance(seg, str):
            out = _join([out, [seg]])
            continue
        n += 1
        block = [["<" * size + " ours" + nl], seg.ours]
        if style in ("diff3", "zdiff3"):
            block += [["|" * size + " base" + nl], seg.base]
        block += [["=" * size + nl], seg.theirs, [">" * size + " theirs" + nl]]
        out = _join([out, *block])
    return Result("".join(out), n)


def text_merge(base: str, ours: str, theirs: str, size: int = 7, style: str = "merge") -> Result:
    """git's own three-way merge."""
    return render(merge3(base, ours, theirs), size, style, _nl(ours))


# --- the kinds -------------------------------------------------------------------------------------------------

def kind_of(path: str, ours: str, theirs: str) -> str:
    """view, log, union, changelog, yaml or text (module docstring)."""
    p = Path(path.replace("\\", "/"))
    name = p.name.lower()
    head = lambda t: "".join(_lines(t)[:HEAD_LINES])  # noqa: E731
    if name.startswith("_generated_") or GENERATED.search(head(ours)) or GENERATED.search(head(theirs)):
        return "view"
    if name in LOGS:
        return "log"
    if name == "changelog.md":
        return "changelog"
    if p.suffix.lower() in (".yaml", ".yml"):
        return "union" if p.parent.name.lower() == "edges" else "yaml"
    return "text"


def _blob(data: bytes, cwd=None) -> str:
    r = _git("hash-object", "--no-filters", "--stdin", cwd=cwd, data=data)
    return _decode(r.stdout).strip() if r.returncode == 0 else ""


def _default_blobs(path: str, cwd=None) -> set[str]:
    """The blob ids of ``path`` on the default branch (origin/HEAD's target, else origin/main and main)."""
    head = _decode(_git("symbolic-ref", "--quiet", "refs/remotes/origin/HEAD", cwd=cwd).stdout).strip()
    refs = [head] if head else []
    refs += [f"refs/remotes/origin/{n}" for n in ("main", "master")] + [f"refs/heads/{n}" for n in ("main", "master")]
    out = set()
    for ref in dict.fromkeys(refs):
        r = _git("rev-parse", "--verify", "--quiet", f"{ref}:{path}", cwd=cwd)
        if r.returncode == 0:
            out.add(_decode(r.stdout).strip())
    return out


def marker_file(cwd=None) -> Path | None:
    r = _git("rev-parse", "--git-dir", cwd=cwd)
    if r.returncode:
        return None
    gitdir = Path(_decode(r.stdout).strip())
    return (gitdir if gitdir.is_absolute() else Path(cwd or os.getcwd()) / gitdir) / MARK


def mark(path: str, cwd=None) -> None:
    """Add ``path`` to the views brain refresh must regenerate in this worktree."""
    if os.environ.get(NO_MARK):
        return
    f = marker_file(cwd)
    if f is None:
        return
    have = marked(cwd)
    if path not in have:
        with f.open("a", encoding="utf-8") as fh:
            fh.write(path + "\n")


def marked(cwd=None) -> list[str]:
    """The views the driver kept from one side in this worktree, not regenerated yet."""
    f = marker_file(cwd)
    try:
        return [x for x in f.read_text(encoding="utf-8").splitlines() if x] if f else []
    except OSError:
        return []


def clear(cwd=None) -> list[str]:
    """Forget the marks (brain refresh regenerated the views); returns what was marked."""
    was = marked(cwd)
    f = marker_file(cwd)
    if f and was:
        try:
            f.unlink()
        except OSError:
            pass
    return was


def view(path: str, ours: bytes, theirs: bytes, cwd=None) -> tuple[bytes, str]:
    """(the side kept, which): the default branch's version when theirs is it and ours is not, else ours."""
    blobs = _default_blobs(path, cwd)
    if blobs and _blob(theirs, cwd) in blobs and _blob(ours, cwd) not in blobs:
        return theirs, "theirs (the default branch's)"
    return ours, "ours"


def _sections(lines: list[str]) -> tuple[list[str], list[list[str]]]:
    """(the lines before the first dated heading, the dated sections)."""
    lead: list[str] = []
    secs: list[list[str]] = []
    for line in lines:
        if DATED.match(line):
            secs.append([line])
        elif secs:
            secs[-1].append(line)
        else:
            lead.append(line)
    return lead, secs


def _spaced(out: list, chunks: list[list[str]], nl: str) -> None:
    """Append the chunks' lines to ``out``, a blank line before a heading that follows a non-blank line."""
    for chunk in chunks:
        if not chunk:
            continue
        last = next((x for x in reversed(out) if isinstance(x, str)), "") if out else ""
        if H2.match(chunk[0]) and last.strip():
            out.append(nl if last.endswith("\n") else nl + nl)
        elif last and not last.endswith("\n"):
            out.append(nl)
        out.extend(chunk)


def _trimmed(lines: list[str], lead: bool = False) -> list[str]:
    """A section (or the ``lead`` lines appended to the entry before) without its trailing blank lines: the blank
    before each heading is :func:`_spaced`'s."""
    out = list(lines)
    while len(out) > (0 if lead else 1) and not out[-1].strip():
        out.pop()
    return out


def _dates(text: str) -> list[str]:
    return [m.group(1) for m in map(DATED.match, _lines(text)) if m]


def _ordered(dates: list[str]) -> bool:
    return all(a <= b for a, b in zip(dates, dates[1:], strict=False))


def log(base: str, ours: str, theirs: str, size: int = 7, style: str = "merge") -> Result:
    """The union of an append-only dated log (module docstring); a log written newest first (its dates never
    increase, a dated CHANGELOG) gets its new entries newest first."""
    nl = _nl(ours)
    newest_first = _newest_first(ours) and _newest_first(theirs)
    out: list = []
    last = ""        # the date of the last entry before the hunk
    early = False    # a new entry dated before it (oldest first only)
    united = False   # the last segment was a union
    for seg in merge3(base, ours, theirs):
        if isinstance(seg, str) or seg.base:
            m = DATED.match(seg) if isinstance(seg, str) else None
            last = m.group(1) if m else last
            if m and united:   # an old entry right after the union (a newest-first log): its blank line
                _spaced(out, [[seg]], nl)
            else:
                out.append(seg)
            united = False
            continue
        united = True
        (lo, so), (lt, st) = _sections(seg.ours), _sections(seg.theirs)
        # stable both ways: ours first on a tie
        secs = sorted(so + st, key=lambda s: DATED.match(s[0]).group(1), reverse=newest_first)
        if not newest_first:
            early = early or any(DATED.match(s[0]).group(1) < last for s in secs)
            last = DATED.match(secs[-1][0]).group(1) if secs else last
        _spaced(out, [_trimmed(lo, lead=True), _trimmed(lt, lead=True), *[_trimmed(x) for x in secs]], nl)
    res = render(out, size, style, nl)
    sides = (_dates(ours), _dates(theirs))
    order = (lambda d: _ordered(d[::-1])) if newest_first else _ordered
    if not res.conflicts and (early or (not order(_dates(res.text)) and all(order(d) for d in sides))):
        res = text_merge(base, ours, theirs, size, style)
        res.note = "a new entry is dated before an older one: left as a conflict"
    return res


def _newest_first(text: str) -> bool:
    dates = _dates(text)
    return len(dates) > 1 and dates[0] > dates[-1] and _ordered(dates[::-1])


def _entry(line: str) -> bool:
    return bool(ENTRY.match(line))


def _dedupe(lines: list[str], ours: str, theirs: str) -> list[str]:
    """Drop an entry line repeated more often than either side had it (both sides added the same edge)."""
    def count(text: str) -> Counter:
        return Counter(x.rstrip("\r\n") for x in _lines(text) if _entry(x))
    co, ct = count(ours), count(theirs)
    seen: Counter = Counter()
    out = []
    for line in lines:
        key = line.rstrip("\r\n")
        if _entry(line):
            seen[key] += 1
            if seen[key] > max(co[key], ct[key], 1):
                continue
        out.append(line)
    return out


def _line_union(seg: Conflict) -> list[str] | None:
    """A hunk of a one-entry-per-line file merged line by line: ours without the lines theirs deleted, then theirs'
    new lines; None when both sides replaced the same line (an entry changed both ways)."""
    def key(x: str) -> str:
        return x.rstrip("\r\n")
    b, o, t = ({key(x) for x in part if _entry(x)} for part in (seg.base, seg.ours, seg.theirs))
    if (b - o) & (b - t) and (o - b) and (t - b):
        return None
    out = [x for x in seg.ours if not (_entry(x) and key(x) in b - t)]   # blank and comment lines stay
    old = {key(x) for x in seg.base if not _entry(x) and x.strip()}
    groups: list[list[str]] = [[]]   # theirs, by runs of lines a blank line opens
    for x in seg.theirs:
        if not x.strip() and groups[-1] and groups[-1][-1].strip():
            groups.append([])
        groups[-1].append(x)
    add: list[str] = []
    for g in groups:
        entries = [x for x in g if _entry(x)]
        new = [x for x in entries if key(x) not in b and key(x) not in o]
        if entries and not new:   # every edge of the run is ours already: its comment goes with them
            continue
        add += [x for x in g if (x in new if _entry(x) else not x.strip() or key(x) not in old)]
    nl = "\r\n" if any(x.endswith("\r\n") for x in seg.ours + seg.theirs) else "\n"
    gap = [nl] if out and out[-1].strip() and add and add[0].strip() else []
    return _join([out, gap, add])


def _yaml_ok(text: str) -> bool:
    try:
        import yaml
        yaml.safe_load(text)
    except ImportError:
        return True
    except Exception:  # noqa: BLE001 - any parse error means the union is not valid YAML
        return False
    return True


def union(base: str, ours: str, theirs: str, size: int = 7, style: str = "merge", *, yaml_check: bool = True,
          section: re.Pattern | None = None) -> Result:
    """Both sides' additions kept (ours first), an entry line both added once; ``section``: only in the ``##``
    section whose heading matches it (a CHANGELOG's Unreleased), the other conflicts left."""
    nl = _nl(ours)
    out: list = []
    heading = ""
    for seg in merge3(base, ours, theirs):
        if isinstance(seg, str):
            if H2.match(seg):
                heading = seg
            out.append(seg)
            continue
        if section is not None:
            opened = _opens(seg.ours, section) and _opens(seg.theirs, section)   # both opened it right here
            if seg.base or not (opened or section.match(heading)):
                out.append(seg)
                continue
            rest = seg.theirs[1:] if opened else seg.theirs   # its heading once
            while rest and not rest[0].strip():
                rest = rest[1:]
            gap = [nl] if opened and seg.ours and seg.ours[-1].strip() else []
            out.extend(_join([seg.ours, gap, rest]))
            heading = seg.ours[0] if opened else heading
            continue
        lines = _line_union(seg)
        out.extend(lines if lines is not None else [seg])
    lines = [x for x in out if isinstance(x, str)]
    if len(lines) == len(out):
        out = _dedupe(out, ours, theirs)
        if section is not None:
            out = _coalesce(out, section)
    res = render(out, size, style, nl)
    if yaml_check and not res.conflicts and not _yaml_ok(res.text):
        res = text_merge(base, ours, theirs, size, style)
        res.note = "the union is not valid YAML: left as a conflict"
    return res


def _opens(lines: list[str], section: re.Pattern) -> bool:
    """Whether a hunk starts with the section's heading (both sides opened an Unreleased section at one place)."""
    return bool(lines) and bool(section.match(lines[0]))


def _coalesce(lines: list[str], section: re.Pattern) -> list[str]:
    """In the section ``section`` matches, a ``###`` heading given twice becomes one, the second's lines appended to
    the first's."""
    start = next((i for i, x in enumerate(lines) if section.match(x)), None)
    if start is None:
        return lines
    stop = next((i for i in range(start + 1, len(lines)) if H2.match(lines[i])), len(lines))
    body = lines[start + 1:stop]
    lead, subs = [], []
    for line in body:
        if H3.match(line):
            subs.append([line])
        elif subs:
            subs[-1].append(line)
        else:
            lead.append(line)
    merged: dict[str, list[str]] = {}
    for sub in subs:
        key = sub[0].strip().lower()
        if key not in merged:
            merged[key] = sub
            continue
        first = merged[key]
        tail = []
        while first and not first[-1].strip():
            tail.insert(0, first.pop())
        items = sub[1:]
        while items and not items[-1].strip():
            items.pop()
        while items and not items[0].strip():
            items.pop(0)
        first.extend(_join([items, tail or ["\n"]]))
    new = lead + [x for sub in merged.values() for x in sub]
    return lines[:start + 1] + new + lines[stop:]


# --- YAML by id ------------------------------------------------------------------------------------------------

@dataclass
class Entries:
    head: list[str] = field(default_factory=list)
    items: list[tuple[str, str]] = field(default_factory=list)   # (id, its text, the comments above it included)
    tail: list[str] = field(default_factory=list)

    def by_id(self) -> dict[str, str]:
        return dict(self.items)


def entries(text: str) -> Entries | None:
    """A list of ``id:`` entries split entry by entry (the blank and comment lines above an entry go with it), or
    None when the file is not one (no such entry, an entry without an id, another key between them, an id twice)."""
    lines = _lines(text)
    first = next((i for i, x in enumerate(lines) if ENTRY_ID.match(x)), None)
    if first is None:
        return None
    ind = len(ENTRY_ID.match(lines[first]).group("ind"))
    out = Entries(head=lines[:first])
    glue: list[str] = []
    cur: list | None = None
    for line in lines[first:]:
        bare = line.strip()
        indent = len(line) - len(line.lstrip(" "))
        m = ENTRY_ID.match(line)
        if m and len(m.group("ind")) == ind:
            if cur:
                out.items.append((cur[0], "".join(cur[1])))
            cur, glue = [m.group("id"), glue + [line]], []
        elif not bare or (bare.startswith("#") and indent <= ind):
            glue.append(line)
        elif indent > ind and cur is not None:
            cur[1].extend(glue + [line])
            glue = []
        else:
            return None
    if cur:
        out.items.append((cur[0], "".join(cur[1])))
    out.tail = glue
    ids = [i for i, _ in out.items]
    return out if len(ids) == len(set(ids)) else None


def _load_entry(text: str) -> dict | None:
    try:
        import yaml
        data = yaml.safe_load(text)
    except Exception:  # noqa: BLE001 - not loadable: no semantic merge
        return None
    return data[0] if isinstance(data, list) and len(data) == 1 and isinstance(data[0], dict) else None


def _merge_keys(b: dict, o: dict, t: dict, nested: tuple = ("props",)) -> dict | None:
    """A three-way merge key by key (``props`` one level down): ours' order, theirs' new keys after; None when a key
    changed both ways."""
    out: dict = {}
    for key in [*o, *(k for k in t if k not in o)]:
        bv, ov, tv = b.get(key), o.get(key), t.get(key)
        if key in nested and isinstance(ov, dict) and isinstance(tv, dict) and isinstance(bv or {}, dict) \
                and ov != tv and ov != bv and tv != bv:
            sub = _merge_keys(bv or {}, ov, tv, ())
            if sub is None:
                return None
            out[key] = sub
            continue
        if ov == tv or tv == bv:
            if key in o:
                out[key] = ov
        elif ov == bv:
            if key in t:
                out[key] = tv
        else:
            return None
    return out   # a key one side deleted and the other left as it was is gone: neither branch above keeps it


def merge_node(bt: str, ot: str, tt: str) -> str | None:
    """An entry both sides changed, merged key by key (both added props, say: a close on one side, an extension on
    the other) and written as brain item set writes a node (brain.graph.render_node), ours' comments above it kept;
    None when a key changed both ways or the entry is not a column-0 node."""
    bn, on, tn = (_load_entry(x) for x in (bt, ot, tt))
    if on is None or tn is None or not ENTRY_ID.match(next((x for x in _lines(ot) if ENTRY.match(x)), "")):
        return None
    lines = _lines(ot)
    start = next(i for i, x in enumerate(lines) if ENTRY.match(x))
    if ENTRY.match(lines[start]).group("ind"):
        return None
    node = _merge_keys(bn or {}, on, tn)
    if node is None:
        return None
    from .graph import render_node
    return "".join(lines[:start]) + render_node(node).replace("\n", _nl(ot))


def yaml_by_id(base: str, ours: str, theirs: str, size: int = 7, style: str = "merge") -> Result:
    """Entry by entry (module docstring); a file that is not a list of id entries, or a result that does not load,
    merged as text."""
    eb, eo, et = entries(base), entries(ours), entries(theirs)
    if eb is None or eo is None or et is None:
        return text_merge(base, ours, theirs, size, style)
    b, o, t = eb.by_id(), eo.by_id(), et.by_id()
    segs: list = merge3("".join(eb.head), "".join(eo.head), "".join(et.head))
    body: list[tuple[str, list]] = []   # (id, segments)

    def merged(bt: str, ot: str, tt: str) -> list:
        if ot == bt or ot == tt:
            return [tt]
        if tt == bt:
            return [ot]
        segs = merge3(bt, ot, tt)
        if any(isinstance(s, Conflict) for s in segs):
            node = merge_node(bt, ot, tt)
            if node is not None:
                return [node]
        return segs

    for nid, ot in eo.items:
        if nid in b:
            if nid not in t:
                if ot != b[nid]:
                    body.append((nid, [Conflict(_lines(ot), _lines(b[nid]), [])]))
                continue
            body.append((nid, merged(b[nid], ot, t[nid])))
        else:
            body.append((nid, merged("", ot, t.get(nid, ot))))
    ours_new = {nid for nid, _ in eo.items if nid not in b and nid not in t}
    prev = None
    for nid, tt in et.items:
        place = None
        if nid not in o and nid not in b:
            place = [tt]
        elif nid not in o and tt != b[nid]:
            place = [Conflict([], _lines(b[nid]), _lines(tt))]
        if place is not None:
            ids = [i for i, _ in body]
            at = ids.index(prev) + 1 if prev in ids else 0
            while at < len(body) and body[at][0] in ours_new:
                at += 1
            body.insert(at, (nid, place))
        if nid in {i for i, _ in body}:
            prev = nid
    for _, part in body:
        segs.extend(part)
    segs.extend(merge3("".join(eb.tail), "".join(eo.tail), "".join(et.tail)))
    flat: list = []
    for seg in segs:
        flat.extend(_lines(seg) if isinstance(seg, str) else [seg])
    res = render(flat, size, style, _nl(ours))
    if not res.conflicts and (not _yaml_ok(res.text) or entries(res.text) is None):
        res = text_merge(base, ours, theirs, size, style)
        res.note = "the merge by id did not load: left as text"
    return res


# --- the driver ------------------------------------------------------------------------------------------------

def _style(cwd=None) -> str:
    r = _git("config", "merge.conflictStyle", cwd=cwd)
    return _decode(r.stdout).strip().lower() if r.returncode == 0 else "merge"


def resolve(path: str, base: bytes, ours: bytes, theirs: bytes, size: int = 7, cwd=None) -> tuple[bytes, Result,
                                                                                                    str]:
    """(the merged bytes, the result, the kind) of one path."""
    o, a, b = _decode(base), _decode(ours), _decode(theirs)
    kind = kind_of(path, a, b)
    style = _style(cwd)
    if kind == "view":
        data, side = view(path, ours, theirs, cwd)
        mark(path, cwd)
        return data, Result(_decode(data), 0, f"kept {side}; brain refresh regenerates it"), kind
    try:
        if kind == "log":
            res = log(o, a, b, size, style)
        elif kind == "union":
            res = union(o, a, b, size, style)
        elif kind == "changelog" and not any(map(UNRELEASED.match, _lines(a) + _lines(b))) and _dates(a):
            kind, res = "log", log(o, a, b, size, style)   # a dated changelog, no Unreleased section: a log
        elif kind == "changelog":
            res = union(o, a, b, size, style, yaml_check=False, section=UNRELEASED)
        elif kind == "yaml":
            res = yaml_by_id(o, a, b, size, style)
        else:
            res = text_merge(o, a, b, size, style)
    except (DriverError, OSError, ValueError, RecursionError) as exc:
        res = text_merge(o, a, b, size, style)
        res.note = f"fell back to git's merge ({type(exc).__name__}: {exc})"
    return _encode(res.text), res, kind


def run(base: str, ours: str, theirs: str, path: str, size: int = 7) -> int:
    """git's entry: merge %O %A %B for %P, the result into %A; 0 resolved, 1 conflicts left, 2 nothing written."""
    try:
        data = [Path(f).read_bytes() for f in (base, ours, theirs)]
    except OSError as exc:
        print(f"brain merge-driver: {path}: {exc}", file=sys.stderr)
        return 2
    try:
        out, res, kind = resolve(path, *data, size=max(size, 7))
    except Exception as exc:  # noqa: BLE001 - the last resort: git's own merge, never a file without markers
        try:
            res = text_merge(*(_decode(d) for d in data), max(size, 7))
        except DriverError:
            print(f"brain merge-driver: {path}: {exc}; git merge-file failed too, ours left", file=sys.stderr)
            return 2
        out, kind, res.note = _encode(res.text), "text", f"fell back to git's merge ({type(exc).__name__})"
    Path(ours).write_bytes(out)
    if res.note or res.conflicts:
        print(f"brain merge-driver: {path} ({kind}): " + (res.note or f"{res.conflicts} conflict(s) left"),
              file=sys.stderr)
    return 1 if res.conflicts else 0


# --- install ---------------------------------------------------------------------------------------------------

def command(launcher: str | None = None) -> str:
    """The driver's command line for git (run by sh): the brain launcher on PATH by its full path, else this Python."""
    exe = launcher or shutil.which("brain")
    head = f'"{Path(exe).as_posix()}"' if exe else f'"{Path(sys.executable).as_posix()}" -m brain'
    return f"{head} merge-driver run %O %A %B %P %L"


def attribute_lines(repo: Path) -> list[str]:
    """The lines of the repo's .gitattributes that name the driver."""
    f = repo / ".gitattributes"
    try:
        text = f.read_text(encoding="utf-8")
    except OSError:
        return []
    return [x for x in text.splitlines() if re.search(rf"\bmerge={NAME}\b", x) and not x.lstrip().startswith("#")]


@dataclass
class Plan:
    repo: str
    driver: str
    current: str
    attributes: list[str]
    error: str = ""

    @property
    def done(self) -> bool:
        return self.current == self.driver


def plan(repo: Path, launcher: str | None = None) -> Plan:
    r = _git("rev-parse", "--show-toplevel", cwd=repo)
    if r.returncode:
        return Plan(str(repo), "", "", [], error="not a git repository")
    top = Path(_decode(r.stdout).strip())
    cur = _decode(_git("config", "--local", f"merge.{NAME}.driver", cwd=top).stdout).strip()
    return Plan(str(top), command(launcher), cur, attribute_lines(top))


def install(repo: Path, apply: bool = False, launcher: str | None = None, as_json: bool = False) -> int:
    """Define the driver in the repo's git config (shared by its worktrees): the plan, or --apply. Idempotent."""
    p = plan(repo, launcher)
    if p.error:
        print(f"brain merge-driver install: {repo}: {p.error}", file=sys.stderr)
        return 1
    changed = False
    if apply and not p.done:
        for key, value in ((f"merge.{NAME}.name", "brain: views keep one side, logs union, YAML by id"),
                           (f"merge.{NAME}.driver", p.driver)):
            r = _git("config", "--local", key, value, cwd=p.repo)
            if r.returncode:
                print(f"brain merge-driver install: git config {key} failed: {_decode(r.stderr).strip()}",
                      file=sys.stderr)
                return 1
        changed = True
    if as_json:
        print(json.dumps({"repo": p.repo, "driver": p.driver, "current": p.current, "set": p.done or changed,
                          "changed": changed, "attributes": p.attributes}, indent=2))
        return 0
    state = "already set" if p.done else ("set" if changed else
                                          ("to set (--apply)" if not p.current else f"to change from {p.current!r}"
                                                                                    " (--apply)"))
    print(f"merge    {p.repo}: merge.{NAME}.driver = {p.driver} ({state})")
    if not p.attributes:
        print(f"merge    {p.repo}/.gitattributes names no path merge={NAME}: add brain init's lines:")
        print("\n".join("           " + x for x in ATTRIBUTES.splitlines()))
    else:
        print(f"merge    {len(p.attributes)} path pattern(s) use it in .gitattributes")
    return 0


def status(cwd=None, as_json: bool = False) -> int:
    """The views waiting for brain refresh in this worktree, and whether the driver is defined."""
    views = marked(cwd)
    cur = _decode(_git("config", f"merge.{NAME}.driver", cwd=cwd).stdout).strip()
    if as_json:
        print(json.dumps({"driver": cur, "marked": views}, indent=2))
        return 0
    print(f"driver   {cur or 'not defined here (brain merge-driver install --apply)'}")
    print(f"views    {len(views)} kept from one side, waiting for brain refresh" + "".join(f"\n  {v}" for v in views))
    return 0


# --- replay ----------------------------------------------------------------------------------------------------

def _merge_tree(repo: Path, ours: str, theirs: str, driver: str, attrs: Path, env: dict) -> tuple[str, list[str]]:
    """(the merged tree, the conflicted paths) of ``git merge-tree`` with that driver for merge=brain. Git runs from
    the scratch folder ``attrs`` sits in, the repo named by GIT_DIR: the driver's temporary files land there, never in
    a checkout (a production one included), and only ``attrs`` gives the attributes."""
    r = subprocess.run(["git", "-c", f"core.attributesFile={attrs.as_posix()}", "-c", f"merge.{NAME}.driver={driver}",
                        "merge-tree", "--write-tree", "--name-only", "--no-messages", ours, theirs],
                       cwd=attrs.parent, capture_output=True, timeout=600, env={**env, "GIT_DIR": _git_dir(repo)},
                       stdin=subprocess.DEVNULL)
    if r.returncode not in (0, 1):
        raise DriverError(f"git merge-tree {ours} {theirs}: {_decode(r.stderr).strip() or r.returncode}")
    lines = [x for x in _decode(r.stdout).splitlines() if x]
    return (lines[0] if lines else ""), lines[1:]


def _git_dir(repo: Path) -> str:
    r = _git("rev-parse", "--path-format=absolute", "--git-common-dir", cwd=repo)
    if r.returncode:
        raise DriverError(f"{repo}: not a git repository")
    return _decode(r.stdout).strip()


def _rev(repo: Path, spec: str) -> str:
    r = _git("rev-parse", "--verify", "--quiet", spec, cwd=repo)
    return _decode(r.stdout).strip() if r.returncode == 0 else ""


def merges(repo: Path, since: str = "", rev: str = "HEAD") -> list[tuple[str, str, str]]:
    """(merge, first parent, second parent) of the two-parent merges reachable from ``rev`` (since a date)."""
    args = ["log", "--merges", "--format=%H %P", rev] + ([f"--since={since}"] if since else [])
    out = []
    for line in _decode(_git(*args, cwd=repo).stdout).splitlines():
        parts = line.split()
        if len(parts) == 3:
            out.append((parts[0], parts[1], parts[2]))
    return out


def replay(repo: Path, pairs: list[tuple[str, str, str]], attributes: str = ATTRIBUTES,
           driver: str | None = None) -> list[dict]:
    """Each (merge, ours, theirs) merged again by ``git merge-tree``, as text then with the driver: the conflicted
    paths of each, and for each path the driver resolved, whether its result is the merge's own (``same``) or not
    (``differs``: a view the merge regenerated, an order, a resolution by hand)."""
    driver = driver or f'"{Path(sys.executable).as_posix()}" -m brain.mergedriver %O %A %B %P %L'
    env = dict(os.environ, **{NO_MARK: "1"})
    out = []
    with tempfile.TemporaryDirectory(prefix="brain-replay-") as d:
        attrs = Path(d) / "attributes"
        attrs.write_text(attributes, encoding="utf-8")
        for merge, ours, theirs in pairs:
            _, before = _merge_tree(repo, ours, theirs, "git merge-file --marker-size=%L %A %O %B", attrs, env)
            tree, after = _merge_tree(repo, ours, theirs, driver, attrs, env)
            resolved = {}
            for path in before:
                if path in after:
                    continue
                mine = _rev(repo, f"{tree}:{path}")
                theirs_ = _rev(repo, f"{merge}:{path}") if merge else ""
                resolved[path] = "same" if mine and mine == theirs_ else "differs"
            out.append({"merge": merge, "ours": ours, "theirs": theirs, "before": before, "after": after,
                        "resolved": resolved})
    return out


def summary(results: list[dict]) -> list[str]:
    """The replay in a few lines: merges conflicted before and after, per path."""
    before = sum(1 for r in results if r["before"])
    after = sum(1 for r in results if r["after"])
    files_b = Counter(p for r in results for p in r["before"])
    files_a = Counter(p for r in results for p in r["after"])
    same = Counter(p for r in results for p, v in r["resolved"].items() if v == "same")
    lines = [f"{len(results)} merge(s) replayed: {before} conflicted as text, {after} with the driver",
             f"{sum(files_b.values())} conflicted file(s) as text, {sum(files_a.values())} with the driver"]
    for path, n in files_b.most_common():
        lines.append(f"  {path}: {n} -> {files_a.get(path, 0)}"
                     + (f" ({same[path]} identical to the merge's own result)" if same.get(path) else ""))
    for path, n in files_a.most_common():
        if path not in files_b:
            lines.append(f"  {path}: 0 -> {n} (the driver conflicted where text merged)")
    return lines


def main_replay(repo: Path, since: str, specs: list[str], as_json: bool, rev: str = "HEAD") -> int:
    pairs: list[tuple[str, str, str]] = []
    for spec in specs:
        if ".." in spec:   # OURS..THEIRS: two heads merged as they are today (two PRs against each other)
            a, _, b = spec.partition("..")
            pairs.append(("", _rev(repo, a), _rev(repo, b)))
        else:
            sha = _rev(repo, spec)
            parents = _decode(_git("rev-list", "--parents", "-n", "1", sha, cwd=repo).stdout).split()
            if len(parents) != 3:
                print(f"brain merge-driver replay: {spec} is not a two-parent merge", file=sys.stderr)
                return 1
            pairs.append(tuple(parents))   # type: ignore[arg-type]
    if since or not specs:
        pairs += merges(repo, since, rev)
    if any(not x for p in pairs for x in p[1:]):
        print("brain merge-driver replay: a revision does not resolve", file=sys.stderr)
        return 1
    results = replay(repo, pairs)
    if as_json:
        print(json.dumps(results, indent=2))
    else:
        print("\n".join(summary(results)))
    return 0


