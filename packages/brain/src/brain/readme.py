"""Generated READMEs (wi-brain-readme-sync): a repo's ``README.md`` rendered from the engine's template
(``templates/readme/README.md.tmpl``) and the repo's ``readme.yaml`` (``schemas/readme.schema.json``), the facts
pulled from their sources. Zero token.

- **readme.yaml** holds the text only a person writes: what the repo is, why it exists, how to start, its own notes,
  the commands the README quotes and what each does.
- **The facts** come from their sources: the repo's features (the matrix, brain.features: counts by status and
  domain, the top ones, a link to the generated ``FEATURES.md``), each quoted command's usage from its ``--help``
  (the brain command's from its own parser, in this process; another program's by running it), and, for a private
  repo only, the graph's active specs, recent ADRs and pending milestones that touch the repo.
- **A public repo** (a clone of a repo of config.json ``public.repos``, brain.features.public_checkout) is rendered
  neutral: the features' public titles, no spec, ADR, milestone nor item of the private brain.

Opt-in: only a repo whose checkout holds ``readme.yaml`` is rendered or checked (:func:`applies`); a hand-written
README elsewhere is never read. :func:`problems` is what ``brain docs check`` refuses: ``readme.yaml`` invalid (a
required field missing), a quoted command gone (its ``--help`` fails), the README not the template's output (a hand
edit, or a stale render: a feature, a command's help or the graph changed since). ``brain check`` reports the first two
as errors and a stale README as a stale view (brain.views: a warning on the default branch, an error under
``views.strict``).
"""

from __future__ import annotations

import argparse
import os
import re
import string
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import features, graph, schema

FILE = "readme.yaml"
VIEW = "README.md"
KIND = "readme"   # its schema: schemas/readme.schema.json (brain.schema)
MARKER = "GENERATED by `brain docs render`"
TEMPLATE = Path(__file__).resolve().parent / "templates" / "readme" / "README.md.tmpl"
TOP = 8           # the features the recap lists by default (readme.yaml features.top)
RECENT = 5        # the recent ADRs a private README lists
WIDTH = "120"     # argparse wraps a usage at the terminal's width: a fixed one, so the render is stable
HELP_TIMEOUT = 30
OPEN = ("todo", "doing", "blocked")


class ReadmeError(Exception):
    """readme.yaml cannot be read (not YAML, not a mapping)."""


@dataclass
class Facts:
    """What the render reads beyond readme.yaml: the store's features model, the graph's nodes and edges, and whether
    the checkout is a public repo's."""
    repo: str
    model: features.Model | None = None
    nodes: dict = field(default_factory=dict)
    edges: list = field(default_factory=list)
    public: bool = False


def applies(repo_dir: Path) -> bool:
    """Whether the checkout opted in: it holds ``readme.yaml``."""
    return (Path(repo_dir) / FILE).is_file()


def load(repo_dir: Path) -> dict:
    """readme.yaml as a mapping; ReadmeError when it does not parse or is not one."""
    f = Path(repo_dir) / FILE
    try:
        data = graph.load_yaml(f.read_text(encoding="utf-8"))
    except (OSError, ValueError, graph._yaml().YAMLError) as exc:
        raise ReadmeError(f"{FILE}: cannot be read ({exc})") from exc
    if not isinstance(data, dict):
        raise ReadmeError(f"{FILE}: not a mapping (its fields: title, what, why, start...)")
    return data


def spec_errors(spec: dict) -> list[str]:
    """What readme.yaml breaks of its schema (a required field missing, a wrong type; an unknown field in strict mode
    only, brain.schema.mode)."""
    return [f"{FILE}: {e}" for e in schema.schema_errors(KIND, spec, schema.mode())]


# --- the facts ---

def store_facts(store: Path, repo: str, public: bool, default_repo: str = "") -> Facts:
    """The facts of ``repo`` read from ``store``: its features (when the store has the Feature type), and its nodes
    and edges (for the specs, ADRs and milestones of a private repo)."""
    nodes: dict = {}
    for nid, (_, node) in graph.node_index(store).items():
        nodes[nid] = node
    edges = [e for f in [store / "edges.yaml", *sorted((store / "edges").glob("*.yaml"))]
             for e in graph.load_yaml_list(f) if isinstance(e, dict)]
    model = features.load_store(store, default_repo) if features.has_type(graph.load_schema(store)) else None
    return Facts(repo=repo.lower(), model=model, nodes=nodes, edges=edges, public=public)


def _feature_ids(facts: Facts) -> list[str]:
    m = facts.model
    return sorted(f for f in m.features if m.repo.get(f) == facts.repo) if m else []


def _features_block(spec: dict, facts: Facts) -> str:
    """The recap: the counts by status and by domain, the top features (high value first, then have before partial),
    and the link to FEATURES.md (and to the strategy view readme.yaml names)."""
    m, feats = facts.model, _feature_ids(facts)
    cfg = spec.get("features") if isinstance(spec.get("features"), dict) else {}
    if m is None or not feats:
        return ""
    status = {f: str(m.features[f].get("status", "")) for f in feats}
    counts = ", ".join(f"{sum(1 for f in feats if status[f] == s)} {s}" for s in features.STATUSES)
    shown = _top_features(m, feats, status)[: int(cfg.get("top", TOP))]
    out = ["## Features", "", f"**{len(feats)} features: {counts}.** By domain: {_domains(m, feats)}.", ""]
    out += [f"- **{features._cell(features.shown_title(m, f, facts.public))}** ({status[f]})" for f in shown]
    links = [f"The full matrix: [{features.VIEW}]({features.VIEW})"]
    links += [f"the strategy view: [{cfg['strategy']}]({cfg['strategy']})"] if cfg.get("strategy") else []
    return "\n".join(out + ([""] if shown else []) + ["; ".join(links) + "."])


def _domains(m: features.Model, feats: list[str]) -> str:
    """« brewing 2, measures 1 »: the features of each domain."""
    domains: dict[str, int] = {}
    for f in feats:
        d = str((m.features[f].get("props") or {}).get("domain") or "other")
        domains[d] = domains.get(d, 0) + 1
    return ", ".join(f"{d} {n}" for d, n in sorted(domains.items()))


def _top_features(m: features.Model, feats: list[str], status: dict[str, str]) -> list[str]:
    """The top-level have and partial features, high value first, then have before partial, then by id."""
    rank = {"high": 0, "medium": 1, "low": 2}
    shown = [f for f in feats if status[f] in ("have", "partial") and not m.parent(f)]
    return sorted(shown, key=lambda f: (rank.get(str((m.features[f].get("props") or {}).get("value")), 3),
                                        0 if status[f] == "have" else 1, f))


def brain_usage(words: list[str]) -> str | None:
    """The usage of ``brain <words>`` from the brain command's own parser (this engine's), at a fixed width; None
    when a word is not one of its commands."""
    from . import cli
    old = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = WIDTH
    try:
        parser = cli.build_parser()
        for w in words:
            subs = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
            if not subs or w not in subs[0].choices:
                return None
            parser = subs[0].choices[w]
        return parser.format_usage().strip()
    finally:
        if old is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = old


def program_usage(cli: str, words: list[str], cwd: Path) -> str | None:
    """The usage paragraph of ``<cli> <words> --help`` (its first paragraph), run in ``cwd``; None when it cannot run
    or fails."""
    env = {**os.environ, "COLUMNS": WIDTH, "NO_COLOR": "1"}
    try:
        p = subprocess.run([cli, *words, "--help"], cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=HELP_TIMEOUT, env=env)
    except (OSError, subprocess.SubprocessError):
        return None
    if p.returncode != 0 or not p.stdout.strip():
        return None
    return p.stdout.strip().replace("\r\n", "\n").split("\n\n")[0].strip()


def _words(cmd: dict) -> list[str]:
    return [w for w in str(cmd.get("args") or "").split() if not w.startswith("-")]


def usage_of(cmd: dict, repo_dir: Path) -> str | None:
    """A quoted command's usage: the brain command's from this engine's parser, another program's by running it."""
    cli = str(cmd.get("cli") or "")
    return brain_usage(_words(cmd)) if cli == "brain" else program_usage(cli, _words(cmd), repo_dir)


def _quoted(cmd: dict) -> str:
    return " ".join(x for x in (str(cmd.get("cli") or ""), str(cmd.get("args") or "")) if x)


def _commands_block(spec: dict, repo_dir: Path) -> str:
    cmds = [c for c in spec.get("commands") or [] if isinstance(c, dict)]
    if not cmds:
        return ""
    out = ["## Commands"]
    for c in cmds:
        out += ["", f"### `{_quoted(c)}`", ""]
        if c.get("say"):
            out += [str(c["say"]).strip(), ""]
        usage = usage_of(c, repo_dir)
        out += ["    " + line for line in (usage or "(its --help does not run)").split("\n")]
    return "\n".join(out)


def _touching(facts: Facts) -> set[str]:
    """The repo's own nodes: its features and its items (props.repo)."""
    own = set(_feature_ids(facts))
    own |= {nid for nid, n in facts.nodes.items() if n.get("type") == "WorkItem"
            and str((n.get("props") or {}).get("repo") or "").lower() == facts.repo}
    return own


def _graph_block(facts: Facts) -> str:
    """A private repo's active specs, recent ADRs and pending milestones, from the graph (never in a public render)."""
    if facts.public or not facts.nodes:
        return ""
    own = _touching(facts)
    linked = {(e.get("type"), str(e.get("to"))) for e in facts.edges if str(e.get("from")) in own}

    def nodes(etype: str, ntype: str, statuses: tuple) -> list[str]:
        return sorted(t for et, t in linked if et == etype and facts.nodes.get(t, {}).get("type") == ntype
                      and facts.nodes[t].get("status") in statuses)

    specs = nodes("specified_by", "Spec", ("active",))
    adrs = sorted(nodes("decided_by", "ADR", ("active",)), reverse=True)[:RECENT]
    opened = {nid for nid in own if facts.nodes.get(nid, {}).get("status") in OPEN}
    miles = sorted({str(e.get("to")) for e in facts.edges if e.get("type") == "part_of" and str(e.get("from")) in opened
                    and facts.nodes.get(str(e.get("to")), {}).get("type") == "Milestone"
                    and facts.nodes[str(e.get("to"))].get("status") == "pending"})

    def lines(title: str, ids: list[str]) -> list[str]:
        return ["", f"### {title}", ""] + [f"- `{i}`: {features._cell(facts.nodes[i].get('title', ''))}" for i in ids] \
            if ids else []

    body = lines("Active specs", specs) + lines("Recent decisions", adrs) + lines("Milestones ahead", miles)
    return "\n".join(["## In the brain"] + body) if body else ""


def _sections_block(spec: dict) -> str:
    out = []
    for s in spec.get("sections") or []:
        if isinstance(s, dict) and s.get("title"):
            out += [f"## {str(s['title']).strip()}", "", str(s.get("text") or "").strip(), ""]
    return "\n".join(out).strip()


def _start_block(spec: dict) -> str:
    out = []
    for i, step in enumerate(spec.get("start") or [], 1):
        step = step if isinstance(step, dict) else {"text": str(step)}
        out.append(f"{i}. {str(step.get('text') or '').strip()}")
        if step.get("run"):
            out += ["", "   ```bash", *[f"   {x}" for x in str(step["run"]).strip().split("\n")], "   ```", ""]
    return "\n".join(out).strip()


def _links_block(spec: dict) -> str:
    links = [x for x in spec.get("links") or [] if isinstance(x, dict) and x.get("title") and x.get("href")]
    return "\n".join(["## Links", ""] + [f"- [{x['title']}]({x['href']})" for x in links]) if links else ""


def render(spec: dict, facts: Facts, repo_dir: Path) -> str:
    """README.md from the template, ``spec`` (readme.yaml) and ``facts``. No date of its own: it changes only when
    readme.yaml, the template, a feature, a quoted command's help or (private) the graph's linked nodes do."""
    blocks = {
        "marker": f"<!-- {MARKER} from {FILE} and the brain's graph. Do not edit: change {FILE} or its sources, "
                  "then brain docs render --write. -->",
        "title": str(spec.get("title") or "").strip(),
        "tagline": f"> {str(spec['tagline']).strip()}" if spec.get("tagline") else "",
        "what": str(spec.get("what") or "").strip(),
        "why": str(spec.get("why") or "").strip(),
        "start": _start_block(spec),
        "features": _features_block(spec, facts),
        "commands": _commands_block(spec, repo_dir),
        "sections": _sections_block(spec),
        "brain": _graph_block(facts),
        "links": _links_block(spec),
    }
    text = string.Template(TEMPLATE.read_text(encoding="utf-8")).substitute(blocks)
    text = re.sub(r"\n{3,}", "\n\n", text.replace("\r\n", "\n")).strip()
    return text + "\n"


# --- the check ---

@dataclass
class Report:
    """What :func:`check` found: ``errors`` (readme.yaml invalid, a quoted command gone, a public render a public check
    would refuse) and ``stale`` (README.md missing or not the render), with the render."""
    errors: list[str] = field(default_factory=list)
    stale: str = ""
    text: str = ""


def gone(spec: dict, repo_dir: Path) -> list[str]:
    """The quoted commands whose --help does not run (gone, or renamed)."""
    return [f"{FILE}: the quoted command `{_quoted(c)}` is gone (its --help does not run): change or remove it"
            for c in spec.get("commands") or [] if isinstance(c, dict) and usage_of(c, repo_dir) is None]


def check(repo_dir: Path, facts: Facts, cfg=None) -> Report:
    """docs check of one opted-in checkout: its errors, and whether README.md is the render."""
    rep = Report()
    try:
        spec = load(repo_dir)
    except ReadmeError as exc:
        rep.errors.append(str(exc))
        return rep
    rep.errors += spec_errors(spec)
    if rep.errors:
        return rep
    rep.errors += gone(spec, repo_dir)
    rep.text = render(spec, facts, repo_dir)
    if facts.public:
        rep.errors += [f"{VIEW} (public): {line}" for line in features.denied_lines(rep.text, cfg)]
    f = Path(repo_dir) / VIEW
    old = f.read_text(encoding="utf-8").replace("\r\n", "\n") if f.is_file() else None
    if old is None:
        rep.stale = f"{VIEW} is missing"
    elif old != rep.text:
        rep.stale = (f"{VIEW} is not the render of {FILE}" + ("" if MARKER in old else " (a hand-written README)")
                     + ": a hand edit, or a stale render (a feature, a command's help or the graph changed)")
    return rep


def write(repo_dir: Path, text: str, force: bool = False) -> str:
    """Write README.md; 'written', 'unchanged', or why not: a README that is not generated (no marker) is replaced
    only with ``force`` (the first render of an opted-in repo)."""
    f = Path(repo_dir) / VIEW
    old = f.read_text(encoding="utf-8").replace("\r\n", "\n") if f.is_file() else None
    if old == text:
        return "unchanged"
    if old is not None and MARKER not in old and not force:
        return f"refused: {f} exists and is not generated: brain docs render --write --force replaces it"
    f.write_text(text, encoding="utf-8", newline="\n")
    return "written"
