import pytest
import yaml

from brain import graph


def _nodes(store):
    return {n["id"]: n for n in yaml.safe_load((store / "nodes" / "work.yaml").read_text(encoding="utf-8"))}


def test_render_round_trips_awkward_strings():
    node = {"id": "wi-x", "type": "WorkItem", "status": "todo",
            "title": 'Quotes "x", colons: y, #hash, été, [brackets] {braces}',
            "props": {"priority": "P0", "theme": "3.1", "yes": "no", "date": "2026-10-31", "n": "12",
                      "long": "word " * 40}}
    assert yaml.safe_load(graph.render_node(node)) == [node]
    assert yaml.safe_load(graph.render_edge({"from": "a", "to": "b", "type": "depends_on"})) == \
        [{"from": "a", "to": "b", "type": "depends_on"}]


def test_add_appends_node_and_edges(store):
    before = (store / "nodes" / "work.yaml").read_text(encoding="utf-8")
    graph.add_item(store, "wi-three", "Third: new", props={"priority": "P1"}, spec="spec-x", after=["wi-one"],
                   milestone="ms-x", adr="adr-2026-10-30-x", today="2026-10-31")
    after = (store / "nodes" / "work.yaml").read_text(encoding="utf-8")
    assert after.startswith(before)  # nothing above moved
    assert _nodes(store)["wi-three"] == {"id": "wi-three", "type": "WorkItem", "status": "todo",
                                         "title": "Third: new", "props": {"priority": "P1"}}
    edges = yaml.safe_load((store / "edges" / "work.yaml").read_text(encoding="utf-8"))
    assert edges[-4:] == [{"from": "wi-three", "to": "spec-x", "type": "specified_by"},
                          {"from": "wi-three", "to": "wi-one", "type": "depends_on"},
                          {"from": "wi-three", "to": "ms-x", "type": "part_of"},
                          {"from": "wi-three", "to": "adr-2026-10-30-x", "type": "decided_by"}]
    assert "# 2026-10-31: wi-three (brain item add)" in (store / "edges" / "work.yaml").read_text(encoding="utf-8")


def test_add_refuses_duplicates_unknown_targets_and_bad_status(store):
    with pytest.raises(graph.GraphError, match="already exists"):
        graph.add_item(store, "wi-one", "x")
    with pytest.raises(graph.GraphError, match="unknown node"):
        graph.add_item(store, "wi-new", "x", after=["wi-nope"])
    with pytest.raises(graph.GraphError, match="not allowed"):
        graph.add_item(store, "wi-new", "x", status="reached")


def test_set_and_close_change_only_the_target(store):
    text = (store / "nodes" / "work.yaml").read_text(encoding="utf-8")
    graph.set_item(store, "wi-one", ["status=doing", "priority=P1", "props.owner=ada", "idea="])
    nodes = _nodes(store)
    assert nodes["wi-one"]["status"] == "doing"
    assert nodes["wi-one"]["props"] == {"priority": "P1", "theme": "3.1", "owner": "ada"}
    new = (store / "nodes" / "work.yaml").read_text(encoding="utf-8")
    assert new.split("- {id: wi-one")[0] == text.split("- {id: wi-one")[0]
    assert new.split("- {id: wi-two")[1] == text.split("- {id: wi-two")[1]
    graph.close_item(store, "wi-two", "engine #13", "records and capture", today="2026-10-31")
    assert _nodes(store)["wi-two"] == {"id": "wi-two", "type": "WorkItem", "status": "done", "title": "Second",
                                       "props": {"pr": "engine #13", "done": "2026-10-31 records and capture"}}
    with pytest.raises(graph.GraphError, match="not allowed"):
        graph.set_item(store, "wi-two", ["status=reached"])
    with pytest.raises(graph.GraphError, match="unknown node"):
        graph.set_item(store, "wi-nope", ["status=done"])


def test_link_appends_one_edge_per_pair(store):
    graph.link(store, "wi-two", "depends_on", "wi-one", today="2026-10-31")
    edges = yaml.safe_load((store / "edges" / "work.yaml").read_text(encoding="utf-8"))
    assert edges[-1] == {"from": "wi-two", "to": "wi-one", "type": "depends_on"}
    with pytest.raises(graph.GraphError, match="already linked"):
        graph.link(store, "wi-two", "part_of", "wi-one")
    with pytest.raises(graph.GraphError, match="not an edge type"):
        graph.link(store, "wi-one", "blocks", "wi-two")


# --- the research_graph engine: in this process, else python -m research_graph in another Python ---

def test_engine_runs_in_process(store, monkeypatch, capsys):
    pytest.importorskip("research_graph")
    monkeypatch.delenv("BRAIN_GRAPH_PYTHON", raising=False)
    monkeypatch.setattr(graph.subprocess, "run", lambda *a, **k: pytest.fail("no subprocess when installed"))
    root = store.parents[1]
    (root / "notes" / "decisions.md").write_text("# Decisions\n\n## 2026-10-30 — X\n\nContext: c.\n", encoding="utf-8")
    (root / "docs").mkdir()
    (root / "docs" / "x.md").write_text("# X\n", encoding="utf-8")
    assert graph.research_graph(root, store, "kanban", "--write") == 0
    assert (root / "notes" / "kanban_graph.md").read_text(encoding="utf-8").startswith("<!-- GENERATED by")
    assert graph.research_graph(root, store, "check") == 0
    assert "graph-check OK" in capsys.readouterr().out
    data = graph.research_graph_json(root, store, "items")
    assert [r["id"] for r in data] == ["wi-two", "wi-one"]


def test_engine_failure_is_an_exit_code(store, monkeypatch, capsys):
    class Crash:
        @staticmethod
        def main(argv):
            raise RuntimeError("boom")

    class Usage:
        @staticmethod
        def main(argv):
            raise SystemExit(2)

    root = store.parents[1]
    monkeypatch.setattr(graph, "engine", lambda: Crash)
    assert graph.research_graph(root, store, "check") == 1
    assert "RuntimeError: boom" in capsys.readouterr().err
    assert graph.research_graph_json(root, store, "pending") is None
    assert "failed" in capsys.readouterr().err
    monkeypatch.setattr(graph, "engine", lambda: Usage)
    assert graph.research_graph(root, store, "nope") == 2


def test_engine_runs_in_the_named_python(store, monkeypatch, capsys):
    calls = []

    class Done:
        returncode, stdout, stderr = 0, '{"open_questions": []}', ""

    def run(cmd, **kw):
        calls.append((cmd, kw.get("cwd")))
        return Done

    root = store.parents[1]
    monkeypatch.setenv("BRAIN_GRAPH_PYTHON", "py-with-the-engine")
    assert graph.engine() is None  # an explicit interpreter wins over the installed package
    monkeypatch.setattr(graph.subprocess, "run", run)
    assert graph.research_graph(root, store, "check") == 0
    assert graph.research_graph_json(root, store, "pending") == {"open_questions": []}
    assert [c[0][:3] for c in calls] == [["py-with-the-engine", "-m", "research_graph"]] * 2
    assert calls[1][0][-2:] == ["pending", "--json"] and calls[0][1] == root
    assert "brain update" not in capsys.readouterr().err  # named on purpose: no hint


def test_engine_missing_runs_this_python_once_hinted(store, monkeypatch, capsys):
    """No other copy of the engine is looked for (the legacy package of a registered project is gone): the package
    missing, this Python runs ``-m research_graph`` and the hint names brain update, once."""
    import sys
    calls = []

    class Done:
        returncode, stdout, stderr = 0, "", ""

    monkeypatch.delenv("BRAIN_GRAPH_PYTHON", raising=False)
    monkeypatch.setattr(graph, "engine", lambda: None)
    monkeypatch.setattr(graph, "_hinted", False)
    monkeypatch.setattr(graph.subprocess, "run", lambda cmd, **kw: calls.append(cmd) or Done)
    root = store.parents[1]
    graph.research_graph(root, store, "check")
    graph.research_graph(root, store, "check")
    assert [c[:3] for c in calls] == [[sys.executable, "-m", "research_graph"]] * 2
    assert capsys.readouterr().err.count("brain update (or install.ps1 -Apply) installs it") == 1
    assert not hasattr(graph, "LEGACY") and not hasattr(graph, "graph_python")


def test_adr_ids_match_the_engine(tmp_path):
    """brain writes ADR ids before sync generates them (brain adr new, decision ack): the same slugs and repeats."""
    sync = pytest.importorskip("research_graph.sync")
    import networkx as nx
    from brain import notes

    text = ("# Decisions\n\n## 2026-10-01 — Store format: YAML flow nodes\n\n## 2026-10-02 — Accents é & (x)\n\n"
            "## 2026-10-02 — Accents é & (x)\n\n## 2026-10-03: REVERSAL: Store format: YAML flow nodes\n\n"
            "## 2026-10-04 —\n\n## 2026-10-05 — " + "A very long title " * 6 + "\n")
    (tmp_path / "notes").mkdir()
    (tmp_path / "notes" / "decisions.md").write_text(text, encoding="utf-8")
    seen, ours = [], []
    for day, title in notes.headings(text):
        ours.append(notes.adr_id(day, title, seen))
        seen.append((day, title))
    theirs = yaml.safe_load(sync.render_stubs(sync.decision_stubs(nx.DiGraph(), tmp_path)))
    assert ours == [n["id"] for n in theirs]


def test_unlink_removes_a_curated_edge_and_its_note(store):
    edges = store / "edges" / "work.yaml"
    graph.link(store, "wi-two", "depends_on", "wi-one", today="2026-11-02")
    assert "# 2026-11-02: wi-two (brain item link)" in edges.read_text(encoding="utf-8")
    edge, f = graph.unlink(store, "wi-two", "wi-one")
    assert edge == {"from": "wi-two", "to": "wi-one", "type": "depends_on"} and f == edges
    text = edges.read_text(encoding="utf-8")
    assert "wi-two" not in text and "wi-one, to: spec-x" in text  # the other edge stays
    with pytest.raises(graph.GraphError):
        graph.unlink(store, "wi-two", "wi-one")
