"""The technical reference (wi-brain-technical-reference, brain.reference, brain reference): docs/reference/ per
project from the graph (one page per module, the decisions in force), written by brain sync once it exists; the
neutral render of a public repo, which must not leak the owner's name nor the private brain's records."""

import shutil
from pathlib import Path

from brain import cli, features, reference

FIXTURE = Path(__file__).parent / "fixtures" / "reference"


def _brain(tmp_path, monkeypatch):
    root = tmp_path / "lab"
    shutil.copytree(FIXTURE, root)
    reg = tmp_path / "projects.yaml"
    reg.write_text(f"lab:\n  root: {root.as_posix()}\n", encoding="utf-8")
    monkeypatch.setenv("BRAIN_PROJECTS", str(reg))
    monkeypatch.chdir(root)
    return root, root / "notes" / "graph"


def test_a_module_page_holds_its_features_decisions_in_force_rules_specs_items_and_questions(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    files = reference.render(root, store)
    assert sorted(files) == ["README.md", "modules/K1.md", "modules/K2.md"]
    k1 = files["modules/K1.md"]
    assert k1.startswith("# K1 kettle-core\n\nGENERATED by `brain reference`")
    assert k1.index("`feat-lab-ada-boil` (have)") < k1.index("`feat-lab-pour` (planned)")   # have first
    # on wi-pour the newest answered DDR is in force, the earlier one folded under it; its batch ADR never by title
    pour = k1[k1.index("- **`wi-pour`**"):]
    assert pour.index("`ddr-2026-10-08-pour-cup`: Pour into which cup? → **The blue cup** (Ada Quill, 2026-10-08) "
                      "(in `adr-2026-10-05-answers-of-ada`)") < pour.index("earlier: `ddr-2026-10-04-pour-speed`")
    assert "Ada's answers of 2026-10-05" not in k1
    assert "earlier: `adr-2026-10-02-old-pour`: Pour fast, superseded by `a later decision`" in k1
    # on wi-boil the REVERSAL is in force, the ADR it supersedes folded and marked
    boil = k1[k1.index("- **`wi-boil`**"):k1.index("- **`wi-pour`**")]
    assert "  - `adr-2026-10-09-reversal-boil`: REVERSAL: boil at 95" in boil
    assert "earlier: `adr-2026-10-01-boil-at-100`: Boil at 100 on Ada's stove, superseded by " \
           "`adr-2026-10-09-reversal-boil`" in boil
    assert "- `rule-pour-slow`: Pour slowly, as Ada does" in k1 and "- `spec-kettle`: Ada Quill's kettle spec" in k1
    assert "## Items: 1 done, 1 open" in k1 and "- [ ] `wi-pour`" in k1 and "- [x] `wi-boil`" in k1
    assert "## Open questions\n\nNone." in k1
    assert "## Open questions\n\n- `ddr-2026-10-10-weigh-unit`" in files["modules/K2.md"]
    index = files["README.md"]
    assert "| [K1](modules/K1.md) | kettle-core | K | 2 | 1 | 1 | 5 |" in index
    assert "## Unplaced decisions: 0" in index   # wi-free's ADR went through DDRs about K1's item
    assert reference.render(root, store) == files   # no date of its own


def test_a_decision_about_no_module_is_unplaced_and_counted(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    with (store / "nodes" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write("- {id: adr-2026-10-11-lone, type: ADR, status: active, title: \"A lone call\"}\n")
    with (store / "edges" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write("- {from: wi-free, to: adr-2026-10-11-lone, type: decided_by}\n")
    index = reference.render(root, store)["README.md"]
    assert "## Unplaced decisions: 1" in index and "- `adr-2026-10-11-lone`: A lone call" in index


def test_the_public_render_is_by_domain_and_leaks_nothing_private(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    files = reference.render_public(store, "lab")
    assert sorted(files) == ["README.md", "domains/brewing.md", "domains/measures.md"]
    text = "\n".join(files.values())
    assert "The boiler: boils to the owner's taste** `feat-lab-boil` (have)" in text
    assert "| [brewing](domains/brewing.md) | 2 | 1 | 0 | 1 | `feat-lab-boil`, `feat-lab-pour` |" in files["README.md"]
    for private in ("Ada", "Quill", "feat-lab-ada", "K1", "K2", "kettle-core", "adr-", "ddr-", "wi-", "spec-",
                    "rule-", "notes/graph", "feat-sib"):
        assert private not in text, private
    assert reference.denied(files) == [] and features.denied_lines(text) == []
    full = "\n".join(reference.render(root, store).values())   # the private one names them: the test can fail
    assert "Ada Quill" in full and "adr-" in full and "K1" in full


def test_cli_write_check_and_sync_once_docs_reference_exists(tmp_path, monkeypatch, capsys):
    root, store = _brain(tmp_path, monkeypatch)
    assert cli.main(["reference"]) == 1   # not written yet: the check says so
    assert "docs/reference/README.md: not the render" in capsys.readouterr().out
    assert cli.main(["reference", "--write", "--force"]) == 0
    assert (root / "docs" / "reference" / "modules" / "K1.md").is_file()
    assert cli.main(["reference"]) == 0 and "docs/reference: up to date" in capsys.readouterr().out
    (root / "notes" / "graph" / "modules.yaml").write_text(
        "- {id: K1, name: kettle-core, brick: K, phase: MVP, status: tree}\n", encoding="utf-8")
    assert cli.main(["reference"]) == 1   # K2 gone from the registry: its page is stale
    assert "modules/K2.md: not the render" in capsys.readouterr().out
    from brain.commands._stores import _write_reference
    _write_reference(root, store)   # brain sync's step: written again, the page no longer rendered removed
    assert not (root / "docs" / "reference" / "modules" / "K2.md").exists()
    assert cli.main(["reference"]) == 0


def test_sync_writes_nothing_without_docs_reference(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    from brain.commands._stores import _write_reference
    _write_reference(root, store)   # opt-in: a brain without docs/reference/ gets none
    assert not (root / "docs").exists()


def test_cli_public_needs_out_and_renders_into_a_checkout(tmp_path, monkeypatch, capsys):
    root, store = _brain(tmp_path, monkeypatch)
    assert cli.main(["reference", "--public", "--repo", "lab"]) == 1
    out = tmp_path / "engine" / "docs" / "reference"
    assert cli.main(["reference", "--public", "--repo", "lab", "--out", str(out), "--write", "--force"]) == 0
    assert (out / "domains" / "brewing.md").is_file() and "Ada" not in (out / "README.md").read_text(encoding="utf-8")
    assert cli.main(["reference", "--public", "--repo", "lab", "--out", str(out)]) == 0
