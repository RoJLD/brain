"""The technical reference (wi-brain-technical-reference, brain.reference, brain reference): docs/reference/ per
project from the graph (one page per module, the decisions in force), written by brain sync once the owner opted in;
the neutral render of a public repo, which must not leak the owner's name nor the private brain's records."""

import json
import shutil
from pathlib import Path

from brain import cli, features, graph, projects, reference
from brain.commands._stores import _write_reference
from conftest import git_init, run_git

FIXTURE = Path(__file__).parent / "fixtures" / "reference"


def _brain(tmp_path, monkeypatch, git=False):
    root = tmp_path / "lab"
    if git:
        git_init(root)
    shutil.copytree(FIXTURE, root, dirs_exist_ok=True)
    reg = tmp_path / "projects.yaml"
    reg.write_text(f"lab:\n  root: {root.as_posix()}\n", encoding="utf-8")
    monkeypatch.setenv("BRAIN_PROJECTS", str(reg))
    monkeypatch.chdir(root)
    return root, root / "notes" / "graph"


def _lab():
    return projects.load()["lab"]


def test_a_module_page_holds_its_features_decisions_in_force_rules_specs_items_and_questions(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    files = reference.render(root, store)
    assert sorted(files) == ["README.md", "modules/K1.md", "modules/K2.md"]
    k1 = files["modules/K1.md"]
    assert k1.startswith("# K1 kettle-core\n\nGENERATED by `brain reference`")
    assert k1.index("`feat-lab-ada-boil` (have)") < k1.index("`feat-lab-pour` (planned)")   # have first
    # on wi-pour the newest answered DDR is in force, the earlier one folded under it; its batch ADR never by title
    pour = k1[k1.index("- **`wi-pour`**"):]
    assert pour.index("`ddr-2026-10-08-pour-cup`: Pour into which cup? → **The blue cup** (Ada Quill, 2026-10-08) "
                      "(in `adr-2026-10-05-answers-of-ada`)") < pour.index("earlier: `ddr-2026-10-04-pour-speed`")
    assert "Ada's answers of 2026-10-05" not in k1
    assert "earlier: `adr-2026-10-02-old-pour`: Pour fast, superseded\n" in k1   # no edge says by whom
    # on wi-boil the REVERSAL is in force, the ADR it supersedes folded and marked
    boil = k1[k1.index("- **`wi-boil`**"):k1.index("- **`wi-pour`**")]
    assert "  - `adr-2026-10-09-reversal-boil`: REVERSAL: boil at 95" in boil
    assert "earlier: `adr-2026-10-01-boil-at-100`: Boil at 100 on Ada's stove, superseded by " \
           "`adr-2026-10-09-reversal-boil`" in boil
    assert "- `rule-pour-slow`: Pour slowly, as Ada does" in k1 and "- `spec-kettle`: Ada Quill's kettle spec" in k1
    assert "## Items: 1 done, 1 open" in k1 and "- [ ] `wi-pour`" in k1 and "- [x] `wi-boil`" in k1
    assert "## Open questions\n\nNone." in k1
    assert "## Open questions\n\n- `ddr-2026-10-10-weigh-unit`" in files["modules/K2.md"]
    index = files["README.md"]
    assert "| [K1](modules/K1.md) | kettle-core | K | 2 | 1 | 1 | 5 |" in index
    assert "## Unplaced decisions: 0" in index   # wi-free's ADR went through DDRs about K1's item
    assert reference.render(root, store) == files   # no date of its own


def test_a_pinned_read_project_gets_its_page_and_a_row_in_the_index(tmp_path, monkeypatch):
    """wi-brain-docgraph-read: the Sigma view of the reference reads the projects the brain only reads from their
    pinned docgraph/v1 documents; an unpinned copy gets no page (brain check names it)."""
    root, store = _brain(tmp_path, monkeypatch)
    reg = tmp_path / "projects.yaml"
    reg.write_text(reg.read_text(encoding="utf-8") + "shop: {title: read only, access: read}\n"
                   "mill: {title: read only, access: read}\n", encoding="utf-8")
    src = {"path": "docs/x.md"}
    doc = {"schema": "docgraph/v1", "generated": {"at": "2026-01-01T00:00:00Z", "by": "shop-docs 0.1"},
           "pinned": {"ref": "0123456789abcdef0123", "file": "docs-graph.json", "at": "2026-01-02T00:00:00Z"},
           "nodes": [{"id": "decision:0005", "type": "decision", "title": "Transport", "status": "accepted",
                      "source": {"path": "docs/adr/0005.md"}},
                     {"id": "criterion:S2-1", "type": "criterion", "title": "Paired", "source": src},
                     {"id": "item:25", "type": "item", "title": "Signed orders", "status": "open",
                      "source": {"tracker": "issue", "number": 25}}],
           "edges": []}
    (root / "docgraph").mkdir()
    (root / "docgraph" / "shop.json").write_text(json.dumps(doc), encoding="utf-8")
    (root / "docgraph" / "mill.json").write_text(json.dumps({**doc, "pinned": None}), encoding="utf-8")
    files = reference.render(root, store)
    assert "read/shop.md" in files and "read/mill.md" not in files
    assert "| [shop](read/shop.md) | `0123456789ab` | shop-docs 0.1 | 1 | 1 | 1 |" in files["README.md"]
    page = files["read/shop.md"]
    assert reference.generated(page) and "pinned at `0123456789abcdef0123`" in page
    assert "- `0005` (accepted) Transport — `docs/adr/0005.md`" in page and "- open: 1" in page
    assert "error: `criterion.no-item` [join] no item serves it (`criterion:shop/S2-1`)" in page
    assert reference.render(root, store) == files
    assert reference.stale(root / reference.DIR, files)   # not written yet: every page is late


def test_a_decision_about_no_module_is_unplaced_and_counted(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    with (store / "nodes" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write("- {id: adr-2026-10-11-lone, type: ADR, status: active, title: \"A lone call\"}\n")
    with (store / "edges" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write("- {from: wi-free, to: adr-2026-10-11-lone, type: decided_by}\n")
    index = reference.render(root, store)["README.md"]
    assert "## Unplaced decisions: 1" in index and "- `adr-2026-10-11-lone`: A lone call" in index


def test_a_malformed_ddr_is_read_as_far_as_it_goes_never_a_crash(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    ddr = root / "records" / "ddr"
    (ddr / "ddr-2026-10-12-bad-answer.yaml").write_text(
        "v: 1\nid: ddr-2026-10-12-bad-answer\ntitle: t\nquestion: q?\nstatus: answered\nasked: {at: '2026-10-12'}\n"
        "answer: yes\nlinks: {items: wi-pour}\n", encoding="utf-8")
    (ddr / "ddr-2026-10-13-string-links.yaml").write_text(
        "v: 1\nid: ddr-2026-10-13-string-links\ntitle: t\nquestion: Which kettle?\nstatus: answered\n"
        "asked: {at: '2026-10-13'}\nanswer: {at: '2026-10-13T10:00:00Z', choices: Steel}\n"
        "links: {items: wi-pour, specs: [spec-kettle], adrs: adr-2026-10-05-answers-of-ada}\n", encoding="utf-8")
    (ddr / "ddr-no-id.yaml").write_text("v: 1\ntitle: t\nquestion: q?\nstatus: pending\nasked: {at: '2026-10-14'}\n"
                                        "links: {items: [wi-weigh]}\n", encoding="utf-8")
