    assert sorted(files) == ["README.md", "domains/brewing.md", "domains/measures.md"]
    text = "\n".join(files.values())
    assert "The boiler: boils to the owner's taste** `feat-lab-boil` (have)" in text
    assert "| [brewing](domains/brewing.md) | 2 | 1 | 0 | 1 | `feat-lab-boil`, `feat-lab-pour` |" in files["README.md"]
    assert "  - code: [boil.py](../../../src/lab/boil.py)" in files["domains/brewing.md"]   # from the repo's root
    assert "  - docs: `doc:lab:README.md::boil`" in files["domains/brewing.md"]
    for private in ("Ada", "Quill", "ada", "sib", "feat-lab-ada", "K1", "K2", "kettle-core", "adr-", "ddr-", "wi-",
                    "spec-", "rule-", "notes/graph"):
        assert private not in text, private
    full = "\n".join(reference.render(root, store).values())   # the private one names them: the test can fail
    assert "Ada Quill" in full and "adr-" in full and "K1" in full


