def test_the_public_render_is_by_domain_and_leaks_nothing_private(tmp_path, monkeypatch):
    root, store = _brain(tmp_path, monkeypatch)
    for nid in ("doc:lab:README.md::boil", "doc:sib:ada-notes.md::boil"):
        graph.add_item(store, nid, nid, node_type="WorkItem")   # any node: the Doc nodes are the links layer's
    features.link(store, "feat-lab-ada-boil", code=["code:lab:src/lab/boil.py", "code:sib:sib/ada_private.py"],
                  docs=["doc:lab:README.md::boil", "doc:sib:ada-notes.md::boil"])
