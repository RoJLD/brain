def test_cli_write_check_and_sync_once_opted_in(tmp_path, monkeypatch, capsys):
    root, store = _brain(tmp_path, monkeypatch)
    (root / "docs" / "reference").mkdir(parents=True)   # an empty folder is no opt-in: sync writes nothing
    _write_reference(_lab(), root, store)
    assert list((root / "docs" / "reference").iterdir()) == []
    assert cli.main(["reference"]) == 1   # not written yet: the check says so
    assert "docs/reference/README.md: not the render" in capsys.readouterr().out
    assert cli.main(["reference", "--write"]) == 0
    assert (root / "docs" / "reference" / "modules" / "K1.md").is_file()
    assert cli.main(["reference"]) == 0 and "docs/reference: up to date" in capsys.readouterr().out
    (root / "notes" / "graph" / "modules.yaml").write_text(
        "- {id: K1, name: kettle-core, brick: K, phase: MVP, status: tree}\n", encoding="utf-8")
    assert cli.main(["reference"]) == 1   # K2 gone from the registry: its page is stale
    assert "modules/K2.md: not the render" in capsys.readouterr().out
    hand = root / "docs" / "reference" / "modules" / "notes.md"
    hand.write_text("# Notes\n\nThis folder is GENERATED by `brain reference`, but not this page.\n", encoding="utf-8")
    _write_reference(_lab(), root, store)   # brain sync's step: written again, the page no longer rendered removed
    assert not (root / "docs" / "reference" / "modules" / "K2.md").exists() and hand.is_file()
    assert cli.main(["reference"]) == 0


def test_sync_writes_nothing_without_the_opt_in_and_never_over_a_public_or_hand_written_reference(tmp_path,
                                                                                                  monkeypatch, capsys):
    root, store = _brain(tmp_path, monkeypatch)
    assert cli.main(["sync", "--offline"]) == 0
    assert not (root / "docs").exists()   # no docs/reference/: none
    base = root / "docs" / "reference"
    reference.write(base, reference.render_public(store, "lab"))   # a public render here: never the sync's
    before = (base / "README.md").read_text(encoding="utf-8")
    assert cli.main(["sync", "--offline"]) == 0
    assert (base / "README.md").read_text(encoding="utf-8") == before and not (base / "modules").exists()
    shutil.rmtree(base)
    assert cli.main(["reference", "--write"]) == 0
    (base / "modules" / "K1.md").write_text("# K1, by hand\n", encoding="utf-8")
    capsys.readouterr()
    assert cli.main(["reference", "--write"]) == 1   # a page that is not generated is kept, and said
    assert "is not generated" in capsys.readouterr().err
    assert (base / "modules" / "K1.md").read_text(encoding="utf-8") == "# K1, by hand\n"
    (base / "modules" / "K1.md").unlink()
    (store / "nodes" / "work.yaml").write_text(
        (store / "nodes" / "work.yaml").read_text(encoding="utf-8").replace("Boil water", "Boil the water"),
        encoding="utf-8")
    assert cli.main(["sync", "--offline"]) == 0   # opted in: brain sync writes it again
    assert "Boil the water" in (base / "modules" / "K1.md").read_text(encoding="utf-8")


