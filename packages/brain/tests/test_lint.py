def test_lint_sizes_mapping_and_candidates(brain_repo, claude_home):
    (brain_repo / ".claude").mkdir()
    (brain_repo / ".claude" / "settings.json").write_text(
        json.dumps({"enabledPlugins": {f"extra@{MARKETPLACE}": True, "other@elsewhere": True}}), encoding="utf-8")
    (claude_home / "CLAUDE.md").write_text("- An old global copy.\n", encoding="utf-8")
    assert lint.global_rules() == RULES_FILE  # config.json's first rules
    r = lint.lint([_project(brain_repo)])
    rows = {(s["kind"], s["file"]): s for s in r["sizes"][0]["sources"]}
    hook = rows[("hook", RULES_FILE)]
    assert hook["chars"] == len(GLOBAL) and hook["share"] == round(len(GLOBAL) / lint.HOOK_CAP, 3)
    assert ("claude-md", "~/.claude/CLAUDE.md") in rows and ("claude-md", "CLAUDE.md") in rows
    assert ("skill", "plugins/extra/skills/other/SKILL.md") in rows  # enabled by the project's settings
    assert rows[("skill", f"plugins/{CORE}/skills/close-item/SKILL.md")]["chars"] == len(
        f"- {CORE}:close-item: Close a finished item.")  # the core plugin config.json names, always enabled
    assert r["sizes"][0]["tokens"] == sum(s["tokens"] for s in r["sizes"][0]["sources"])
    dup = [d for d in r["duplicates"] if d["kind"] == "exact"]
    assert len(dup) == 1 and {dup[0]["a"].rel, dup[0]["b"].rel} == {RULES_FILE, "CLAUDE.md"}
    assert [c["unit"].rule for c in r["scripts"]] == ["rule-change"]
    gs = {c["unit"].line: c for c in r["guards"]}
    assert gs[12]["unit"].rule == "rule-backlog" and not gs[12]["enforced"]
    assert gs[8]["enforced"] and gs[8]["covered"] == ["attribution"]  # rule-git-prs has an enforced_by edge
    out = "\n".join(lint.render(r))
    assert "of the 10,000-character hook cap" in out and "demo: rules: 1 of 3 hard" in out
    assert json.loads(json.dumps(lint.to_json(r)))["guards"][0]["unit"]["ref"].startswith("demo:")


