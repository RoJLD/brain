def test_proposals_one_per_rule_most_useful_first(brain_repo):
    (brain_repo / "CLAUDE.md").write_text(CLAUDE + "- Never edit `notes/kanban.md` by hand.\n", encoding="utf-8")
    ps = lint.proposals(lint.lint([_project(brain_repo)]))
    kinds = [p["kind"] for p in ps]
    assert kinds == sorted(kinds, key=lambda k: {"guard": 1, "script": 2, "duplicate": 3}[k])
    guard = [p for p in ps if p["kind"] == "guard"]
    assert [p["title"] for p in guard] == ["Rules lint: a guard for rule-backlog?",
                                           "Rules lint: a guard for demo CLAUDE.md §Other rules?"]
    for p in ps:
        assert 2 <= len(p["options"]) <= 4 and p["why"] and len(p["title"]) <= 100
    assert len({p["key"] for p in ps}) == len(ps)


def test_propose_files_a_batch_never_twice(brain_repo, capsys):
    root = brain_repo
    at = "2026-11-02T10:00:00Z"
    report = lint.lint([_project(root)])
    n = len(lint.proposals(report))
    assert n >= 3
    dry = lint.propose(root, report, at=at, limit=2, dry_run=True)
    assert len(dry["filed"]) == 2 and not (root / "records").exists()
    first = lint.propose(root, report, at=at, limit=2)
    assert [f["id"].startswith("ddr-2026-11-02-rules-lint-") for f in first["filed"]] == [True, True]
    ddr = yaml.safe_load((root / first["filed"][0]["file"]).read_text(encoding="utf-8"))
    assert ddr["links"] == {"items": ["wi-brain-rules-linter"], "specs": ["spec-brain-governance"],
                            "project": "demo"}
    assert ddr["context"].startswith("Rules lint batch of 2026-11-02, 1 of 2")
    again = lint.propose(root, report, at=at, limit=2)  # two pending already: nothing more
    assert again["filed"] == [] and again["pending_before"] == 2 and again["left"] == n - 2
    decisions.answer(root, first["filed"][0]["id"], ["1"], at=at)
    third = lint.propose(root, report, at="2026-11-03T10:00:00Z", limit=2)
    assert len(third["filed"]) == 1 and third["filed"][0]["id"] not in {f["id"] for f in first["filed"]}
    lint.mark_asked(report, root)
    assert report["undecided"] == n - 1 and n == 3
    (root / "CLAUDE.md").write_text(CLAUDE + "- Never edit `notes/kanban.md` by hand.\n", encoding="utf-8")
    assert cli.main(["--root", str(root), "lint", "rules", "--propose", "--max", "3", "--at", at]) == 0
    out = capsys.readouterr().out  # a new guard candidate in a section: a new key, a new DDR
    assert "propose: filed 1 DDR(s) (2 rules-lint DDR(s) already pending, at most 3 at once" in out
    assert f"[{first['filed'][0]['id']}: answered]" in out and (root / decisions.VIEW).is_file()
