GLOBAL = """# Ada's rules

Source: the private repo, injected into every session.

## Git and PRs

- Work in a git worktree, merge by PR, then pull where a service or a scheduled task runs.
- No AI attribution line in a commit message or a PR body.

## Backlog

- Generated views (kanban, roadmap) are regenerated by their command, never edited by hand.
- Each working day gets a dated entry in the project's journal.
"""

CLAUDE = """# demo — rules for working in this repo

## Changing the rules

A change of a plugin is done only when, in the same PR:
1. an ADR is appended to `notes/decisions.md`;
2. the graph nodes follow;
3. the graph is checked: `python -m research_graph sync --write`, then `check`;
4. the README is updated.

## Other rules

- Work in a git worktree, merge by PR, then pull where a service or a scheduled task runs.
- Testing with the venv: set `PYTHONPATH` (the venv has the package installed, not editable, so tests import it).
- A brief asks for a report with branch names and what remains (no push unless told).
"""

