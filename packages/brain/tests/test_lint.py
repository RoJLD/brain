def test_anchor_is_githubs():
    assert lint.anchor("Backlog, milestones, roadmap, history") == "backlog-milestones-roadmap-history"
    assert lint.anchor("Git and PRs") == "git-and-prs"
    assert lint.anchor("`brain` and its records") == "brain-and-its-records"
    assert lint.anchor("6. Backlog — Ada, 2026-10-30") == "6-backlog--ada-2026-10-30"


def test_units_cut_bullets_steps_and_paragraphs():
    text = ("# Title\n\nIntro paragraph\nover two lines.\n\n## One\n\n- first bullet\n  continued\n  - a sub-bullet\n"
            "- second bullet\n\nLead of the steps:\n\n1. step one\n2. step two\n   more of step two\n3. step three\n\n"
            "### Sub\n\nA paragraph with code:\n```\ngit status\n\ngit diff\n```\n")
    us = lint.units(text, "p", "f.md")
    assert [u.line for u in us] == [3, 8, 11, 13, 22]
    assert us[0].section == "" and us[0].text == "Intro paragraph\nover two lines."
    assert us[1].text.endswith("- a sub-bullet") and us[1].anchor == us[1].top == "one"
    assert us[3].steps == 3 and us[3].text.startswith("Lead of the steps:") and "more of step two" in us[3].text
    assert us[4].anchor == "sub" and us[4].top == "one" and "git diff" in us[4].text  # a blank line inside a fence


def test_words_drop_stop_words_and_stem():
    assert lint.words("The commits are merged by PRs") == {"commit", "merg", "prs"}


