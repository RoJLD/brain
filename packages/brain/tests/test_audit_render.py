"""brain.audit_render: brain audit's outputs, the text, the JSON and the view notes/audit.md, from a measured project
(test_audit runs them through the command; these read the module directly)."""

import json

from brain import audit_checks, audit_render


def _finding(check, sev, unit, cls="", chain="", fix="fix it"):
    return {"key": f"lab:{check}:{unit}", "check": check, "severity": sev, "unit": unit, "class": cls,
            "chain": chain, "via": "", "why": f"why {unit}", "fix": fix}


def _project():
    p2 = [_finding("doc.links", "P2", f"docs/d{i}.md") for i in range(4)]
    repo = {"name": "lab", "path": "/m/lab", "production": True, "commit": "main@abc1234", "date": "2026-11-02",
            "counts": {"P0": 0, "P1": 1, "P2": 4, "info": 0}, "classes": {}, "no_entry": False,
            "missing_entries": [], "not_measured": [{"check": "cmd.leaves", "owner": "a generator"}],
            "findings": [_finding("test.module", "P1", "src/lab/a.py", "prod", "cli > a", "add tests/test_a.py"),
                         *p2],
            "waived": [{"unit": "tests/test_ci.py", "reason": "checks the CI files, no module"}],
            "exempt": ["src/lab/__main__.py"]}
    return {"name": "demo", "root": "/m/demo", "counts": {"P0": 0, "P1": 1, "P2": 4}, "repos": [repo],
            "facts": object(), "cfgs": [], "layered": set(), "coverage": {}}


def test_the_text_lists_p0_p1_and_counts_each_p2_check_with_three_examples():
    data = {"ruleset": audit_checks.RULESET, "projects": [audit_render._public(_project())]}
    out = audit_render.render_text(data)
    assert out[0] == f"== demo: /m/demo  (rules {audit_checks.RULESET})"
    assert "  P1 test.module      src/lab/a.py  prod (cli > a): why src/lab/a.py -> add tests/test_a.py" in out
    assert ("  P2 doc.links        4 unit(s), e.g. docs/d0.md, docs/d1.md, docs/d2.md (-v: all)") in out
    assert "  not measured: cmd.leaves (a generator)" in out
    assert out[-1] == f"demo: P0 0  P1 1  P2 4 in 1 repo(s) (calibrated {audit_checks.CALIBRATED.split(' ', 1)[0]})"
    verbose = audit_render.render_text(data, verbose=True)
    assert sum(1 for x in verbose if " doc.links " in x) == 4   # -v: every finding


def test_the_view_has_no_run_date_and_says_what_was_waived_exempt_and_not_measured():
    view = audit_render.render_view(_project())
    assert view == audit_render.render_view(_project())   # no run date: it changes only when the measure does
    assert view.startswith("# Conformance audit — demo\n\nGENERATED by `brain audit --write`. Do not edit")
    assert "| [lab](#lab) | main@abc1234 (2026-11-02) | production | 0 | 1 | 4 | 0 | 1 | 1 | 1 |" in view
    assert "- P1 lab test.module `src/lab/a.py` (prod, cli > a): why src/lab/a.py → add tests/test_a.py" in view
    assert f"### P2 doc.links (4)\n\n_{audit_checks.CHECKS['doc.links'].what}._" in view
    assert "Waived: `tests/test_ci.py` (checks the CI files, no module)" in view
    assert "Exempt (trivial modules): `src/lab/__main__.py`" in view and "Not measured: cmd.leaves" in view


def test_uncalibrated_counts_say_so_in_the_text_and_the_view(monkeypatch):
    monkeypatch.setattr(audit_checks, "CALIBRATED", "")
    data = {"ruleset": audit_checks.RULESET, "projects": [audit_render._public(_project())]}
    assert audit_render.render_text(data)[-1].endswith("(uncalibrated: wi-brain-scout-rule measures each check's "
                                                       "error rate)")
    assert "Uncalibrated: the counts are measured" in audit_render.render_view(_project())


def test_the_json_drops_the_measure_s_internals_and_sorts_its_keys():
    pub = audit_render._public(_project())
    assert not {"facts", "cfgs", "layered", "coverage"} & set(pub) and pub["repos"][0]["name"] == "lab"
    text = audit_render.render_json({"projects": [pub], "audit": 1})
    assert json.loads(text)["projects"][0]["name"] == "demo" and text.index('"audit"') < text.index('"projects"')


def test_the_view_is_written_once_then_left_as_it_is(tmp_path):
    f, wrote = audit_render.write_view(tmp_path, "# view\n")
    assert wrote and f == tmp_path / audit_render.VIEW and f.read_text(encoding="utf-8") == "# view\n"
    assert audit_render.write_view(tmp_path, "# view\n") == (f, False)   # unchanged: not rewritten
    assert audit_render.write_view(tmp_path, "# view 2\n") == (f, True)
