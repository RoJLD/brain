def test_the_view_goes_to_the_merge_driver():
    from brain import mergedriver
    line = "notes/modules_graph.md merge=brain"
    assert line in mergedriver.ATTRIBUTES
    tmpl = Path(modules.__file__).parent / "templates" / "generic"
    assert line in (tmpl / "gitattributes").read_text(encoding="utf-8")
    assert "notes/modules_graph.md" in (tmpl / "boundary.yaml").read_text(encoding="utf-8")


def test_json_write_check_an_item_without_id_and_a_repeated_secondary(tmp_path, monkeypatch, capsys):
    nodes = NODES + ('- {type: WorkItem, status: todo, title: "No id", props: {module: P2}}\n'
                     '- {id: wi-twice, type: WorkItem, status: todo, title: "Twice",'
                     ' props: {module: K1, modules_secondary: "M4, M4"}}\n')
    store = _brain(tmp_path, nodes=nodes)
    monkeypatch.setenv("BRAIN_ROOT", str(tmp_path))
    assert not [p for p in modules.problems(store) if "No id" in p]   # research_graph reports it, not a KeyError
    got = modules.data(store)
    m4 = next(m for m in got["modules"] if m["id"] == "M4")
    assert m4["secondary"] == 1 and got["open_items"] == 8   # M4 given twice counts once
    assert cli.main(["modules", "--json"]) == 0
    assert json.loads(capsys.readouterr().out)["modules"][0]["id"] == "K1"
    assert cli.main(["modules", "--write", "--check"]) == 1   # writes the view, then checks the map
    out = capsys.readouterr().out
    assert "view: notes/modules_graph.md written" in out and "wi-bare: no props.module" in out
