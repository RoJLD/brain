"""The module map (wi-brain-module-map, brain.modules): each open item's module against the store's registry, the
generated view notes/modules_graph.md, brain check's warnings and brain modules."""

import json
from pathlib import Path

import pytest

from brain import cli, modules

REGISTRY = """\
- {id: P2, name: kettle-core, brick: P, phase: MVP, status: tree}
- {id: P12, name: kettle-meter, brick: P, phase: V1.5, status: proposed, lab: now, since: 2026-08-01,
   note: "Weigh and time, split from P2."}
- {id: K1, name: tea-room, brick: K, phase: MVP, status: tree}
- {id: M4, name: lamp-post, brick: M, phase: V1, status: proposed, since: 2026-08-01}
"""
NODES = """\
- {id: wi-guard, type: WorkItem, status: todo, title: "A guard", props: {priority: P1, module: P2}}
- {id: wi-eval, type: WorkItem, status: doing, title: "An eval", props: {module: P12, modules_secondary: "P2"}}
- {id: wi-old, type: WorkItem, status: done, title: "An old guard", props: {module: P2}}
- {id: wi-meta, type: WorkItem, status: todo, title: "The map itself",
   props: {module: none, module_reason: "the brain's own process"}}
- {id: wi-bare, type: WorkItem, status: todo, title: "No module yet"}
- {id: wi-odd, type: WorkItem, status: todo, title: "Odd", props: {module: Z9, modules_secondary: "Q1, Z9"}}
- {id: wi-list, type: WorkItem, status: todo, title: "A list", props: {module: K1, modules_secondary: [P2, P12]}}
- {id: wi-why, type: WorkItem, status: todo, title: "None, no reason", props: {module: none}}
- {id: wi-gone, type: WorkItem, status: dropped, title: "Dropped, no module"}
- {id: ms-a, type: Milestone, status: todo, title: "A milestone"}
"""


def _brain(tmp_path, registry=REGISTRY, nodes=NODES):
    store = tmp_path / "notes" / "graph"
    (store / "nodes").mkdir(parents=True)
    (store / "schema.yaml").write_text("node_types: [WorkItem, Milestone]\nedge_types: []\n", encoding="utf-8")
    (store / "nodes" / "work.yaml").write_text(nodes, encoding="utf-8")
    if registry is not None:
        (store / "modules.yaml").write_text(registry, encoding="utf-8")
    return store


def test_problems_name_every_open_item_without_a_known_module(tmp_path):
    store = _brain(tmp_path)
    assert modules.problems(store) == [
        "wi-bare: no props.module (a module of modules.yaml, or none with props.module_reason)",
        "wi-odd: props.module Z9 is not in modules.yaml",
        "wi-odd: props.modules_secondary Q1 is not in modules.yaml",
        "wi-odd: props.modules_secondary Z9 is not in modules.yaml",
        "wi-why: props.module is none without props.module_reason",
    ]   # done, dropped and non-items are not counted
    assert modules.problems(_brain(tmp_path / "bare", registry=None)) == []   # no registry: not concerned
    assert not modules.applies(tmp_path / "bare" / "notes" / "graph")


def test_the_view_counts_lists_and_shows_the_gaps(tmp_path):
    text = modules.render(_brain(tmp_path))
    assert text.startswith("# Modules\n\nGENERATED by `brain sync` (brain.modules)")
    assert "**4 modules (2 proposed); 6 of 7 open items placed, 2 outside the tree.**" in text
    assert "| [P2](#p2) | kettle-core | P | MVP | tree | 1 | 1 | 2 |" in text   # done, open, open as secondary
    assert "| [P12](#p12) | kettle-meter | P | V1.5 | proposed | 0 | 1 | 1 |" in text
    assert text.index("| [K1]") < text.index("| [M4]") < text.index("| [P2]") < text.index("| [P12]")
    assert "- K1" not in text   # wi-list places it
    assert "- M4 (lamp-post): proposed 2026-08-01, no item done or open: back to sleep from 2026-10-30" \
        in text
    assert "- Z9: 1 item(s) name it, the registry does not know it" in text
    assert "- `wi-guard` [P1] A guard" in text and "Secondary: `wi-eval`, `wi-list`" in text
    assert "Weigh and time, split from P2." in text and ", in the lab now." in text
    assert "- `wi-meta`: the brain's own process" in text
    assert modules.render(_brain(tmp_path / "again")) == text   # no date of its own: the same input, the same view


def test_sync_writes_the_view_and_check_warns(tmp_path, monkeypatch, capsys):
    store = _brain(tmp_path)
    monkeypatch.setenv("BRAIN_ROOT", str(tmp_path))
    assert modules.stale(tmp_path, store)
    assert modules.write(tmp_path, store) and not modules.write(tmp_path, store)
    assert not modules.stale(tmp_path, store)
    assert (tmp_path / modules.VIEW).read_text(encoding="utf-8") == modules.render(store)
    assert cli.main(["modules", "--check"]) == 1
    assert "wi-bare: no props.module" in capsys.readouterr().out
    (store / "nodes" / "work.yaml").write_text(NODES.replace('title: "No module yet"}',
                                                             'title: "No module yet", props: {module: K1}}'),
                                               encoding="utf-8")
    assert modules.stale(tmp_path, store)
    assert cli.main(["modules", "--write"]) == 0
    assert "view: notes/modules_graph.md written" in capsys.readouterr().out
    assert cli.main(["modules"]) == 0
    assert "| [K1](#k1) | tea-room | K | MVP | tree | 0 | 2 | 0 |" in capsys.readouterr().out
    (store / "modules.yaml").unlink()
    with pytest.raises(SystemExit, match="no modules.yaml"):
        cli.main(["modules"])


