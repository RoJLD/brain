def test_yaml_by_id_one_change_each_side_and_both_append():
    ours = NODES.replace("id: wi-a, type: WorkItem, status: todo", "id: wi-a, type: WorkItem, status: done") + \
        '- {id: wi-o, type: WorkItem, status: todo, title: "Ours"}\n'
    theirs = NODES.replace('title: "B"', 'title: "B, renamed"') + \
        '\n# --- theirs ---\n- {id: wi-t, type: WorkItem, status: todo, title: "Theirs"}\n'
    text, res, kind = merge("notes/graph/nodes/work.yaml", NODES, ours, theirs)
    assert (kind, res.conflicts) == ("yaml", 0), text
    assert "id: wi-a, type: WorkItem, status: done" in text and 'title: "B, renamed"' in text
    assert text.index("wi-o") < text.index("# --- theirs ---") < text.index("wi-t")
    import yaml
    assert [n["id"] for n in yaml.safe_load(text)] == ["wi-a", "wi-b", "wi-c", "wi-o", "wi-t"]


def test_yaml_by_id_a_deletion_and_a_new_entry_in_the_middle():
    ours = NODES.replace('- {id: wi-c, type: WorkItem, status: todo, title: "C"}\n', "")
    theirs = NODES.replace('title: "B"}\n', 'title: "B"}\n- {id: wi-n, type: WorkItem, status: todo, title: "N"}\n')
    text, res, _ = merge("notes/graph/nodes/work.yaml", NODES, ours, theirs)
    assert res.conflicts == 0 and "wi-c" not in text
    assert text.index("wi-b") < text.index("wi-n")


def test_yaml_by_id_the_same_entry_changed_both_ways_stays_a_conflict():
    ours = NODES.replace('title: "B"', 'title: "B ours"')
    theirs = NODES.replace('title: "B"', 'title: "B theirs"')
    text, res, _ = merge("notes/graph/nodes/work.yaml", NODES, ours, theirs)
    assert res.conflicts == 1 and "wi-a" in text and "wi-c" in text


def test_yaml_that_is_not_a_list_of_ids_is_merged_as_text():
    base = "owner: ada\nkind: person\nnodes: []\n"
    text, res, _ = merge("notes/graph/schema.yaml", base, base.replace("[]", "[a]"), base.replace("ada", "bob"))
    assert res.conflicts == 0 and text == "owner: bob\nkind: person\nnodes: [a]\n"


