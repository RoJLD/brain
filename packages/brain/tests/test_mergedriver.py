def change(r, branch, who, *, new=False):
    run_git(r, "checkout", "-q", *(["-b"] if new else []), branch)
    with (r / "notes" / "journal.md").open("a", encoding="utf-8") as f:
        f.write(f"\n## 2026-10-02 — {who}\n- {who}'s day\n")
    (r / "notes" / "kanban_graph.md").write_text(KANBAN.format(who), encoding="utf-8")
    with (r / "notes" / "graph" / "nodes" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write(f'- {{id: wi-{who}, type: WorkItem, status: todo, title: "{who}"}}\n')
    with (r / "notes" / "graph" / "edges" / "work.yaml").open("a", encoding="utf-8") as f:
        f.write(f"- {{from: wi-{who}, to: wi-a, type: depends_on}}\n")
    run_git(r, "commit", "-q", "-am", who)


def test_git_merge_of_main_into_a_branch_needs_no_hand(repo):
    change(repo, "feature", "ada", new=True)
    change(repo, "main", "bob")
    run_git(repo, "checkout", "-q", "feature")
    run_git(repo, "merge", "-q", "--no-edit", "main")   # check=True: a conflict would fail here
    journal = (repo / "notes" / "journal.md").read_text(encoding="utf-8")
    assert "ada's day" in journal and "bob's day" in journal
    assert (repo / "notes" / "kanban_graph.md").read_text(encoding="utf-8") == KANBAN.format("bob")  # main's side
    nodes = (repo / "notes" / "graph" / "nodes" / "work.yaml").read_text(encoding="utf-8")
    assert nodes.index("wi-ada") < nodes.index("wi-bob")
    assert md.marked(repo) == ["notes/kanban_graph.md"]
    cli._merge_marks(repo, "regenerated", clear=True)   # what brain refresh does once it passes
    assert md.marked(repo) == []


def test_without_the_driver_the_same_merge_conflicts(repo):
    run_git(repo, "config", "--unset", "merge.brain.driver")
    change(repo, "feature", "ada", new=True)
    change(repo, "main", "bob")
    run_git(repo, "checkout", "-q", "feature")
