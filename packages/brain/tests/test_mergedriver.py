- {id: wi-a, type: WorkItem, status: todo,
   title: "A",
   props: {priority: P1}}
- {id: wi-b, type: WorkItem, status: todo, title: "B"}
- {id: wi-c, type: WorkItem, status: todo, title: "C"}
