INSTALLER = Path(cli.__file__).parents[2] / "installer" / "install.ps1"


def _merge_block() -> str:
    text = INSTALLER.read_text(encoding="utf-8")
    return text[text.index("# --- the merge driver step"):text.index("# --- end of the merge driver step")] + \
        "Set-MergeDriver\n"


@pytest.mark.skipif(sys.platform != "win32" or not shutil.which("powershell.exe"), reason="Windows PowerShell")
@pytest.mark.parametrize("python, apply", [("venv", False), ("venv", True), ("none", True), ("old", True)])
def test_installer_step(repo, tmp_path, python, apply):
    run_git(repo, "config", "--unset", "merge.brain.driver")
    bin_ = tmp_path / "bin"
    old = tmp_path / "old.cmd"
    old.write_text("@echo off\r\nexit /b 2\r\n", encoding="utf-8")
    exe = {"venv": Path(sys.executable), "none": tmp_path / "absent.exe", "old": old}[python]
    script = tmp_path / "install.ps1"
    script.write_text("$ErrorActionPreference = 'Stop'\n$windows = $true\n"
                      f"$repo = '{repo}'\n$bin = '{bin_}'\n$venv_python = '{exe}'\n$Apply = ${str(apply).lower()}\n"
                      + _merge_block(), encoding="utf-8")
    res = subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(script)],
                         capture_output=True, text=True, timeout=120)
    assert res.returncode == 0, res.stdout + res.stderr
    driver = subprocess.run(["git", "-C", str(repo), "config", "merge.brain.driver"], capture_output=True, text=True)
    if python == "none":
        assert "once the command is installed" in res.stdout and driver.returncode == 1
    elif python == "old":
        assert "no merge-driver subcommand yet" in res.stdout and driver.returncode == 1
    elif not apply:
        assert "(to set (--apply))" in res.stdout and driver.returncode == 1
    else:
        assert "(set)" in res.stdout
        assert driver.stdout.strip() == md.command(str(bin_ / "brain.exe"))   # with its git merge-file fallback


def test_yaml_by_id_both_add_props_to_one_entry():
    ours = NODES.replace("props: {priority: P1}}", 'props: {priority: P1, pr: "demo #4",\n           done: "2026-10-02"}}')
    ours = ours.replace("id: wi-a, type: WorkItem, status: todo", "id: wi-a, type: WorkItem, status: done")
    theirs = NODES.replace("props: {priority: P1}}", 'props: {priority: P1, extended: "more"}}')
    text, res, _ = merge("notes/graph/nodes/work.yaml", NODES, ours, theirs)
    assert res.conflicts == 0, text
    import yaml
    a = yaml.safe_load(text)[0]
    assert a["status"] == "done" and a["props"] == {"priority": "P1", "pr": "demo #4", "done": "2026-10-02",
                                                    "extended": "more"}
    assert text.startswith("# Work layer\n# --- items ---\n- {id: wi-a")   # the comments above it kept


