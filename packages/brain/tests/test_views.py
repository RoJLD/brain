def test_the_records_graph_is_stale_when_its_files_differ(tmp_path):
    root = tmp_path / "r"
    store = root / "notes" / "graph"
    (store / "nodes").mkdir(parents=True)
    (store / "schema.yaml").write_text("node_types: [DDR, WorkItem]\nedge_types: []\n", encoding="utf-8")
    (root / records.RECORDS_DIR).mkdir()
    assert records.graph_stale(root, store) == []   # not written yet: nothing to call stale
    records.write_graph(root, store)
    assert records.graph_stale(root, store) == []
    (store / "nodes" / "_generated_records.yaml").write_text("# edited by hand\n[]\n", encoding="utf-8")
    assert records.graph_stale(root, store) == ["nodes/_generated_records.yaml"]
