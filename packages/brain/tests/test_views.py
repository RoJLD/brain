"""One writer of the generated views (wi-brain-views-one-writer, brain.views, docs/views.md): a branch need not commit
them, brain check fails on a stale one on the default branch only, brain views --unstage and --reset keep a branch's
commits and merges clear of them, brain views --write regenerates and commits them at the default branch's tip, and
committed views are written by the pinned engine only (COMPAT-1)."""

import json
import shutil
import subprocess

import pytest

from brain import audit, cli, mergedriver, records, skew, views
from conftest import run_git

SCHEMA = ("node_types: [WorkItem, Milestone]\nedge_types: [depends_on]\nstatuses: [todo, doing, done, pending]\n"
          "status_by_type:\n  WorkItem: [todo, doing, done]\n")
NODES = '- {id: wi-a, type: WorkItem, status: todo, title: "A"}\n'
KANBAN = "notes/kanban_graph.md"
ROADMAP = "notes/roadmap_graph.md"


@pytest.fixture
def brainrepo(make_repo):
    """A brain on main with its views synced and committed."""
    repo = make_repo("b", {"notes/graph/schema.yaml": SCHEMA, "notes/graph/nodes/work.yaml": NODES,
                           "notes/graph/edges.yaml": "[]\n", "README.md": "# b\n"})
    assert cli.main(["--root", str(repo), "sync", "--offline"]) == 0
    make_repo.commit(repo, msg="views")
    return repo


def _add_node(repo, nid: str) -> None:
    f = repo / "notes" / "graph" / "nodes" / "work.yaml"
    f.write_text(f.read_text(encoding="utf-8") + f'- {{id: {nid}, type: WorkItem, status: todo, title: "{nid}"}}\n',
                 encoding="utf-8")


def _git(repo, *args) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, encoding="utf-8")


# --- what a view is, where a checkout stands ---

def test_a_view_is_what_the_merge_driver_calls_one():
    marked = "<!-- GENERATED by `brain sync` -->\n# Board\n"
    for path, head in (("notes/kanban_graph.md", marked), ("notes/graph/nodes/_generated_links.yaml", ""),
                       ("FEATURES.md", "# Features\n" + marked), ("notes/journal.md", "# Journal\n"),
                       ("notes/graph/nodes/work.yaml", "- {id: wi-a}\n")):
        assert views.is_view(path, head) == (mergedriver.kind_of(path, head, head) == "view"), path
    assert views.is_view("notes/kanban_graph.md", marked) and not views.is_view("notes/journal.md", "# Journal\n")


def test_tracked_views_and_where_a_checkout_stands(brainrepo, tmp_path):
    assert {KANBAN, ROADMAP} <= set(views.tracked(brainrepo)) and "README.md" not in views.tracked(brainrepo)
    assert views.place(brainrepo) == views.Place("default", "main", "main")
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    assert views.place(brainrepo) == views.Place("branch", "feat", "main")
    run_git(brainrepo, "checkout", "-q", "--detach")
    assert views.place(brainrepo).where == "branch" and views.place(brainrepo).branch == "HEAD"
    plain = tmp_path / "plain"
    plain.mkdir()
    assert views.place(plain).where == ""


def test_the_verdict_by_place():
    stale = views.Stale()
    stale.add("notes/graph/nodes/_generated_links.yaml")
    stale.add("notes/decision_queue.md", "brain sync (or brain decision view --write)")
    stale.add("notes/decision_queue.md")   # once
    rc, lines = views.verdict(stale, views.Place("default", "main", "main"))
    assert rc == 1 and len(lines) == 2
    assert lines[1].startswith("error: notes/decision_queue.md is stale on main, the default branch: brain views "
                               "--write") and lines[1].endswith("or brain sync (or brain decision view --write)")
    rc, lines = views.verdict(stale, views.Place("branch", "feat", "main"))
    assert rc == 0 and lines == ["views: 2 stale here (notes/graph/nodes/_generated_links.yaml, "
                                 "notes/decision_queue.md), not required on a branch: brain sync refreshes them for "
                                 "this branch's checks; brain views --write writes them on main after the merge"]
    rc, lines = views.verdict(stale, views.Place(""), {"notes/graph/nodes/_generated_links.yaml":
                                                       "nodes/_generated_links.yaml"})
    assert rc == 0 and lines[0] == "warning: nodes/_generated_links.yaml is stale: brain sync"
    assert views.verdict(views.Stale(), views.Place("default", "main", "main")) == (0, [])


# --- brain check: fresh on the default branch, not required on a branch ---

def test_check_fails_on_a_stale_board_on_the_default_branch_only(brainrepo, tmp_path, capsys):
    assert cli.main(["--root", str(brainrepo), "check"]) == 0
    capsys.readouterr()
    _add_node(brainrepo, "wi-b")   # a merged PR that left the views to the one writer
    f = brainrepo / "notes" / "graph" / "nodes" / "work.yaml"
    f.write_text(f.read_text(encoding="utf-8") + '- {id: ms-x, type: Milestone, status: pending, title: "X"}\n',
                 encoding="utf-8")
    assert cli.main(["--root", str(brainrepo), "check"]) == 1
    out = capsys.readouterr().out
    assert f"error: {KANBAN} is stale on main, the default branch: brain views --write" in out
    assert f"error: {ROADMAP} is stale on main" in out
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    assert cli.main(["--root", str(brainrepo), "check"]) == 0
    out = capsys.readouterr().out
    assert "error:" not in out and "views:" not in out   # the board is measured on the default branch only
    copy = shutil.copytree(brainrepo, tmp_path / "copy", ignore=shutil.ignore_patterns(".git"))
    assert cli.main(["--root", str(copy), "check"]) == 0   # outside git: as before, an advisory


def test_a_branch_that_commits_its_views_keeps_working(brainrepo, capsys):
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    _add_node(brainrepo, "wi-b")
    assert cli.main(["--root", str(brainrepo), "sync", "--offline"]) == 0
    run_git(brainrepo, "add", "-A")
    run_git(brainrepo, "commit", "-q", "-m", "wi-b, views included")   # nothing refuses it
    capsys.readouterr()
    assert cli.main(["--root", str(brainrepo), "check"]) == 0
    assert views.changed(brainrepo) == [] and "wi-b" in (brainrepo / KANBAN).read_text(encoding="utf-8")


def test_a_branch_that_leaves_its_views_out_merges_the_default_branch_cleanly(brainrepo, capsys):
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    run_git(brainrepo, "checkout", "-q", "main")
    (brainrepo / "notes" / "graph" / "nodes" / "more.yaml").write_text(   # main moves, its views with it (no merge
        '- {id: wi-c, type: WorkItem, status: todo, title: "wi-c"}\n', encoding="utf-8")   # driver in this repo)
    assert cli.main(["--root", str(brainrepo), "sync", "--offline"]) == 0
    run_git(brainrepo, "add", "-A")
    run_git(brainrepo, "commit", "-q", "-m", "wi-c")
    run_git(brainrepo, "checkout", "-q", "feat")
    _add_node(brainrepo, "wi-b")
    assert cli.main(["--root", str(brainrepo), "sync", "--offline"]) == 0
    run_git(brainrepo, "add", "-A")
    assert views.staged(brainrepo) == [KANBAN]
    assert cli.main(["--root", str(brainrepo), "views", "--unstage"]) == 0
    assert "unstaged" in capsys.readouterr().out and views.staged(brainrepo) == []
    run_git(brainrepo, "commit", "-q", "-m", "wi-b, views left to the writer")
    assert "wi-b" in (brainrepo / KANBAN).read_text(encoding="utf-8")   # the working tree keeps them
    assert "wi-b" not in _git(brainrepo, "show", f"HEAD:{KANBAN}").stdout   # the commit leaves them as they were
    assert _git(brainrepo, "merge", "--no-edit", "main").returncode != 0   # a local change to a file main brings
    assert cli.main(["--root", str(brainrepo), "views", "--reset"]) == 0
    assert "put back at HEAD" in capsys.readouterr().out and views.changed(brainrepo) == []
    merge = _git(brainrepo, "merge", "--no-edit", "main")
    assert merge.returncode == 0 and "CONFLICT" not in merge.stdout   # the branch never touched them
    assert cli.main(["--root", str(brainrepo), "refresh", "--offline"]) == 0
    board = (brainrepo / KANBAN).read_text(encoding="utf-8")
    assert "wi-b" in board and "wi-c" in board


def test_unstage_and_reset_leave_a_new_view_untracked(brainrepo):
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    new = brainrepo / "notes" / "graph" / "nodes" / "_generated_more.yaml"
    new.write_text("[]\n", encoding="utf-8")
    run_git(brainrepo, "add", "-A")
    assert views.unstage(brainrepo) == ["notes/graph/nodes/_generated_more.yaml"] and new.is_file()
    assert "?? notes/graph/nodes/_generated_more.yaml" in run_git(brainrepo, "status", "--porcelain")
    run_git(brainrepo, "add", "-A")
    assert views.reset(brainrepo) == ["notes/graph/nodes/_generated_more.yaml"] and views.staged(brainrepo) == []


def test_views_lists_what_a_branch_changed_and_staged(brainrepo, capsys):
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    _add_node(brainrepo, "wi-b")
    assert cli.main(["--root", str(brainrepo), "sync", "--offline"]) == 0
    run_git(brainrepo, "add", KANBAN)
    capsys.readouterr()
    assert cli.main(["--root", str(brainrepo), "views", "--json"]) == 0
    data = json.loads(capsys.readouterr().out)
    assert data["place"] == "branch" and data["branch"] == "feat" and data["default"] == "main"
    assert data["staged"] == [KANBAN] and data["changed"] == [KANBAN]
    assert {KANBAN, ROADMAP} <= set(data["tracked"])
    assert cli.main(["--root", str(brainrepo), "views"]) == 0
    out = capsys.readouterr().out
    assert "place: on branch feat: its views need not be fresh nor committed" in out
    assert f"  {KANBAN}  (changed here, staged)" in out and "brain views --unstage keeps them out" in out


# --- the one writer ---

def test_views_write_regenerates_and_commits_at_the_default_branch_tip(brainrepo, make_repo, capsys):
    _add_node(brainrepo, "wi-b")
    make_repo.commit(brainrepo, msg="a merged PR, its views left to the writer")
    with pytest.raises(SystemExit, match="is a main checkout on main: write the views from a worktree"):
        cli.main(["--root", str(brainrepo), "views", "--write"])
    run_git(brainrepo, "checkout", "-q", "-b", "chore/views")
    capsys.readouterr()
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--commit", "--offline"]) == 0
    out = capsys.readouterr().out
    assert "HEAD is not" not in out and f"\n  {KANBAN}" in out and "views --write: committed " in out
    assert "Views regenerated at main" in run_git(brainrepo, "log", "-1", "--format=%s")
    assert run_git(brainrepo, "show", "--name-only", "--format=", "HEAD").split() == [KANBAN]
    assert views.changed(brainrepo) == []
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--commit", "--offline"]) == 0   # nothing new
    assert "views --write: 0 file(s) changed" in capsys.readouterr().out
    run_git(brainrepo, "checkout", "-q", "main")
    run_git(brainrepo, "merge", "-q", "--ff-only", "chore/views")
    assert cli.main(["--root", str(brainrepo), "check"]) == 0   # fresh again on the default branch


def test_views_write_leaves_what_was_dirty_before_out_of_its_commit(brainrepo):
    run_git(brainrepo, "checkout", "-q", "-b", "chore/views")
    (brainrepo / "README.md").write_text("# b, edited by hand\n", encoding="utf-8")
    _add_node(brainrepo, "wi-b")
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--commit", "--offline"]) == 0
    committed = run_git(brainrepo, "show", "--name-only", "--format=", "HEAD").split()
    assert KANBAN in committed and "README.md" not in committed and "notes/graph/nodes/work.yaml" not in committed
    assert " M README.md" in run_git(brainrepo, "status", "--porcelain")


def test_views_write_off_the_tip_says_so(brainrepo, capsys):
    run_git(brainrepo, "checkout", "-q", "-b", "feat")
    _add_node(brainrepo, "wi-b")
    run_git(brainrepo, "commit", "-q", "-am", "feat")
    capsys.readouterr()
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--offline"]) == 0
    assert "views: HEAD is not main's tip: these views are this branch's" in capsys.readouterr().out


def test_views_write_writes_the_audit_view_where_the_root_keeps_one(brainrepo, make_repo, capsys):
    (brainrepo / audit.VIEW).write_text("<!-- GENERATED by `brain audit --write` -->\n# Audit\n", encoding="utf-8")
    make_repo.commit(brainrepo, msg="an audit view")
    run_git(brainrepo, "checkout", "-q", "-b", "chore/views")
    capsys.readouterr()
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--no-audit", "--offline"]) == 0
    assert audit.VIEW not in capsys.readouterr().out   # --no-audit: left as it is
    assert cli.main(["--root", str(brainrepo), "views", "--write", "--commit", "--offline"]) == 0
    out = capsys.readouterr().out
    assert f"view: {audit.VIEW} written" in out and f"\n  {audit.VIEW}" in out
    assert audit.VIEW in run_git(brainrepo, "show", "--name-only", "--format=", "HEAD").split()


# --- committed views written by the pinned engine only (COMPAT-1) ---

PIN = "v0.2.3"
AHEAD = [skew.Engine("brain", "0.2.4", "v0.2.4", "abc1234"), skew.Engine("research-graph", "0.2.4", "v0.2.4", "abc")]


@pytest.fixture
def pinned(tmp_path, monkeypatch):
    cfg = tmp_path / "pinned-config.json"
    cfg.write_text(json.dumps({"v": 1, "identity": {"owner": "Ada", "kind": "person"},
                               "engine": {"repo": "someone/brain", "pin": PIN}}), encoding="utf-8")
    monkeypatch.setenv("BRAIN_CONFIG", str(cfg))
    monkeypatch.setattr(skew, "running", lambda: AHEAD)


@pytest.mark.parametrize("argv,what", [
    (["views", "--write"], "views --write"),
    (["decision", "view", "--write"], "decision view --write"),
    (["features", "render", "--write"], "features render --write"),
    (["modules", "--write"], "modules --write"),
    (["coverage", "--write"], "coverage --write"),
    (["audit", "--write"], "audit --write"),
])
def test_every_writer_of_a_committed_view_refuses_another_engine(brainrepo, pinned, capsys, argv, what):
    run_git(brainrepo, "checkout", "-q", "-b", "chore/views")
    (brainrepo / "notes" / "graph" / "modules.yaml").write_text("- {id: P1, name: core, phase: MVP, status: tree}\n",
                                                                encoding="utf-8")
    _add_node(brainrepo, "wi-b")
    before = (brainrepo / KANBAN).read_text(encoding="utf-8")
    assert cli.main(["--root", str(brainrepo), *argv]) == 1
    err = capsys.readouterr().err
    assert f"brain {what}: the running engine is not config.json engine.pin {PIN}" in err and "--force" in err
    assert (brainrepo / KANBAN).read_text(encoding="utf-8") == before
    assert not (brainrepo / "notes" / "modules_graph.md").exists() and not (brainrepo / audit.VIEW).exists()


