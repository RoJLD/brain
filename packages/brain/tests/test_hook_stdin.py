"""The hooks read their JSON as UTF-8 bytes, whatever the console's codepage (wi-brain-hook-stdin-utf8). On Windows,
``python -I`` decodes a pipe with the ANSI codepage (cp1252): an emoji came out as letters and an AI attribution line
went through the attribution guard, and every guard read non-ASCII text as mojibake. A PowerShell pipe's BOM is
dropped by the same reader (wi-brain-hook-stdin-bom)."""

import io
import json
import os
import subprocess
import sys

import pytest
from test_capture import PLUGIN, _bash, _ledger
from test_guards import GENERATED, payload
from test_guards_owner_power import owner  # noqa: F401 - a fixture

from brain import capture, guards

BOM = b"\xef\xbb\xbf"


def _stdin(monkeypatch, data: dict, bom: bool = False) -> None:
    """The hook's stdin as Claude Code writes it (raw UTF-8 JSON), opened the way Windows opens a pipe (cp1252)."""
    raw = (BOM if bom else b"") + json.dumps(data, ensure_ascii=False).encode("utf-8")
    monkeypatch.setattr(sys, "stdin", io.TextIOWrapper(io.BytesIO(raw), encoding="cp1252"))


def _decide(monkeypatch, p: dict, bom: bool = False) -> str | None:
    _stdin(monkeypatch, p, bom)
    out = io.StringIO()
    assert guards.main(stdout=out) == 0
    return json.loads(out.getvalue())["hookSpecificOutput"]["permissionDecisionReason"] if out.getvalue() else None


def test_an_emoji_before_generated_with_is_refused_from_a_codepage_stdin(monkeypatch, tmp_path):
    body = f"gh pr create --title t --body-file - <<'EOF'\nDes « guillemets », été.\n\n{GENERATED}\nEOF"
    assert "AI attribution" in _decide(monkeypatch, payload("Bash", tmp_path, command=body))
    assert "AI attribution" in _decide(monkeypatch, payload("Bash", tmp_path, command=body), bom=True)
    clean = "gh pr create --title t --body 'Des « guillemets », été, et un robot \N{ROBOT FACE}.'"
    assert _decide(monkeypatch, payload("Bash", tmp_path, command=clean)) is None


def test_the_generated_pattern_takes_any_prefix_but_letters():
    def hit(text):
        return any(rx.search(text) for rx in guards.ATTRIBUTION)
    assert hit(GENERATED) and hit("- Generated by Claude") and hit("**Generated with [Claude Code](x)**")
    assert hit("\u00f0\u0178\u00a4\u2013 Generated with [Claude Code](x)")   # the emoji read as cp1252: still refused
    assert not hit("This text was generated with Claude's help") and not hit("Regenerated with Claude")


def test_accents_and_guillemets_survive_in_a_queued_command(owner, monkeypatch, brain_home):  # noqa: F811
    command = 'schtasks /Create /SC DAILY /TN "Tâche « nuit »" /TR "brain digest --write"'
    reason = _decide(monkeypatch, payload("PowerShell", owner, command=command, description="x"))
    assert reason and "--guard " in reason, reason
    ref = reason.split("--guard ")[1].split()[0]
    rows = _ledger(brain_home, "guards")
    queued = next(r["request"] for r in rows if (r.get("request") or {}).get("ref") == ref)["command"]
    assert "Tâche « nuit »" in queued and "Ã" not in queued


def test_capture_keeps_the_accents_of_its_payload(monkeypatch, brain_home):
    _stdin(monkeypatch, {"session_id": "s-é", "source": "startup", "cwd": "D:/travail/équipe « x »"})
    assert capture.main(["session-start"]) == 0
    event = _ledger(brain_home, "events")[0]
    assert event["session_id"] == "s-é" and event["cwd"] == "D:/travail/équipe « x »"


def test_every_launcher_runs_python_in_utf8_mode():
    launchers = [p for p in sorted((PLUGIN / "hooks").glob("*.sh")) if '"$path"' in p.read_text(encoding="utf-8")]
    assert len(launchers) >= 9
    for sh in launchers:
        text = sh.read_text(encoding="utf-8")
        assert '"$path" -X utf8 -I ' in text and '"$path" -I ' not in text, sh.name


def test_guard_sh_refuses_raw_utf8_with_an_emoji(tmp_path):
    """The replay that found it: the same command, through the launcher, as Claude Code sends it."""
    sh = _bash()
    if not sh:
        pytest.skip("no bash")
    env = dict(os.environ, BRAIN_PYTHON=sys.executable)
    command = f"gh pr create --title t --body-file - <<'EOF'\nUn corps, « cité ».\n\n{GENERATED}\nEOF"
    raw = json.dumps(payload("Bash", tmp_path, command=command), ensure_ascii=False).encode("utf-8")
    for data in (raw, BOM + raw):
        out = subprocess.run([sh, str(PLUGIN / "hooks" / "guard.sh"), "shell"], input=data, capture_output=True,
                             env=env, timeout=60)
        assert out.returncode == 0
        hso = json.loads(out.stdout.decode("utf-8"))["hookSpecificOutput"]
        assert hso["permissionDecision"] == "deny" and "AI attribution" in hso["permissionDecisionReason"]
