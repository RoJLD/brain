"""brain merge-ready PR --with PR... (wi-brain-merge-ready-together, brain.mergetogether): PRs green alone checked
merged together on the base: the repo's merge driver by git merge-tree (nothing checked out, no view marked), the
order said, the PR GitHub will see conflicting once those before it merge (a new head: no stamp), a head that
conflicts left out, the tests impact chooses run in a scratch worktree, a stamp per head ready as it is."""

import json
import sys
from pathlib import Path

import pytest
from brain import cli, config, mergeready, mergetogether, review
from conftest import git_init, run_git

GREEN = [{"__typename": "CheckRun", "name": "tests", "status": "COMPLETED", "conclusion": "SUCCESS"}]
CFG = config.Config(None, Path("."), {})
CHANGELOG = "# Changelog\n\n## Unreleased\n\n### Added\n\n- base\n"
VIEW = "<!-- GENERATED by `research_graph kanban --write` -->\n# Board\n{}\n"


@pytest.fixture
def prs(make_repo, tmp_path):
    """A clone of an origin with five PR branches: 1 and 2 each add a CHANGELOG bullet and rewrite a generated view
    (the driver merges them, plain text conflicts), 3 and 4 change one line of a.txt each way (a conflict either
    way), 5 adds a failing test."""
    origin = git_init(tmp_path / "origin.git", bare=True)
    work = make_repo("work", {"a.txt": "a\n", "CHANGELOG.md": CHANGELOG, "notes/kanban_graph.md": VIEW.format("base"),
                              ".gitattributes": "CHANGELOG.md merge=brain\nnotes/kanban_graph.md merge=brain\n"})
    run_git(work, "config", "merge.brain.driver",
            f'"{Path(sys.executable).as_posix()}" -m brain merge-driver run %O %A %B %P %L')
    run_git(work, "remote", "add", "origin", str(origin))
    run_git(work, "push", "-q", "origin", "main")
    heads = {}
    changes = {1: {"CHANGELOG.md": CHANGELOG + "- one\n", "notes/kanban_graph.md": VIEW.format("one"),
                   "tests/test_one.py": "def test_one():\n    assert True\n"},
               2: {"CHANGELOG.md": CHANGELOG + "- two\n", "notes/kanban_graph.md": VIEW.format("two")},
               3: {"a.txt": "a, three\n"}, 4: {"a.txt": "a, four\n"},
               5: {"tests/test_five.py": "def test_five():\n    assert False\n"}}
    for n, files in changes.items():
        run_git(work, "switch", "-q", "-c", f"pr{n}", "main")
        heads[n] = make_repo.commit(work, files, msg=f"PR {n}")
        run_git(work, "push", "-q", "origin", f"pr{n}")
    run_git(work, "switch", "-q", "main")
    run_git(work, "fetch", "-q", "origin")

    def view(number, slug, cwd=None):
        n = int(str(number).lstrip("#"))
        return {"number": n, "state": "OPEN", "isDraft": False, "mergeable": "MERGEABLE", "headRefName": f"pr{n}",
                "headRefOid": heads[n], "baseRefName": "main", "title": f"PR {n}", "body": "A change.",
                "statusCheckRollup": GREEN}

    for h in heads.values():
        review.stamp(h, 0, 0)

    class P:
        pass
    P.repo, P.heads, P.view = work, heads, staticmethod(view)
    return P


def _check(p, numbers, **kw):
    return mergetogether.check(p.repo, [str(n) for n in numbers], "owner/lab", view=p.view, cfg=CFG, fetch=False,
                               **kw)


def _none(*a):
    return [], "none here", ""


def test_prs_on_other_files_are_ready_together_and_each_head_stamped(prs, monkeypatch):
    monkeypatch.setattr(mergetogether, "chosen_tests", _none)
    t = _check(prs, [1, 3])
    assert t.ready, mergetogether.lines(t)
    assert t.order == [1, 3] and "ok    #3 merges clean" in "\n".join(mergetogether.lines(t))
    files = mergetogether.stamps(t)
    rec = json.loads(files[1].read_text(encoding="utf-8"))
    assert rec["head"] == prs.heads[3] and rec["together"]["with"] == [1] and rec["together"]["order"] == [1, 3]


def test_a_pr_github_will_see_conflicting_after_another_needs_a_new_head(prs, monkeypatch):
    monkeypatch.setattr(mergetogether, "chosen_tests", _none)
    t = _check(prs, [1, 2])
    assert t.order == [1, 2] and not t.ready   # the driver merges both: GitHub would not merge #2 as it is
    assert t.steps[0].as_text == [] and t.steps[1].needs_new_head
    assert sorted(t.steps[1].as_text) == ["CHANGELOG.md", "notes/kanban_graph.md"]
    text = "\n".join(mergetogether.lines(t))
    assert "then  #2: once #1 merged, GitHub sees a conflict on" in text and "no stamp for this head" in text
    merged = run_git(prs.repo, "show", f"{t.result}:CHANGELOG.md")
    assert "- one" in merged and "- two" in merged and "<<<<<<<" not in merged
    assert not (prs.repo / ".git" / "brain-refresh").exists()   # the view kept from one side: no mark (a check)
    assert run_git(prs.repo, "rev-parse", "HEAD").strip() == run_git(prs.repo, "rev-parse", "main").strip()
    assert [json.loads(f.read_text(encoding="utf-8"))["pr"] for f in mergetogether.stamps(t)] == [1]   # #1 may go


def test_a_head_that_conflicts_with_one_before_it_is_left_out(prs):
    t = _check(prs, [3, 4, 1])
    assert not t.ready and t.order == [3, 1]
    assert [(s.pr, s.conflicts) for s in t.left] == [(4, ["a.txt"])]
    assert "BLOCK #4 conflicts after #3: a.txt" in "\n".join(mergetogether.lines(t))
    assert t.tests == [] and t.tests_rc is None   # no test chosen for a set that does not merge


def test_a_pr_not_ready_alone_is_not_ready_together(prs, monkeypatch):
    monkeypatch.setattr(mergetogether, "chosen_tests", _none)
    review.stamp(prs.heads[3], 1, 0)   # a finding left open on the second head
    t = _check(prs, [1, 3])
    assert not t.ready and t.order == [1, 3]
    assert {c["check"] for g in t.gates for c in g.blocks} == {"review"}
    assert [g.pr for g in t.stampable()] == [1]


def test_the_chosen_tests_run_in_a_scratch_worktree_and_a_failure_stamps_nothing(prs, monkeypatch):
    before = run_git(prs.repo, "worktree", "list")
    monkeypatch.setattr(mergetogether, "chosen_tests", lambda *a: (["tests/test_one.py"], "chosen here", ""))
    t = _check(prs, [1, 3], test=True)
    assert t.tests_rc == 0 and t.ready, t.tests_note
    assert run_git(prs.repo, "worktree", "list") == before   # the scratch worktree is removed
    monkeypatch.setattr(mergetogether, "chosen_tests", lambda *a: (["tests/test_five.py"], "chosen here", ""))
    t = _check(prs, [3, 5], test=True)
    assert t.tests_rc not in (None, 0) and not t.ready and t.stampable() == []
    t = _check(prs, [1, 3], test=True, python=str(prs.repo / "no-python.exe"))
    assert t.tests_rc == 127 and not t.ready
    monkeypatch.setattr(mergetogether, "chosen_tests", lambda *a: ([], "failed", "brain impact failed: boom"))
    t = _check(prs, [1, 3], test=True)
    assert t.tests_error and not t.ready and t.stampable() == []
    assert "BLOCK tests: brain impact failed: boom" in "\n".join(mergetogether.lines(t))
    assert run_git(prs.repo, "worktree", "list") == before


def test_a_set_needs_two_prs_on_one_base(prs):
    t = _check(prs, [1, "#1"])   # one PR given twice
    assert not t.ready and "a set of one PR" in t.error and len(t.gates) == 1
    run_git(prs.repo, "push", "-q", "origin", "main:release")
    run_git(prs.repo, "fetch", "-q", "origin")
    other = prs.view

    def view(number, slug, cwd=None):
        d = other(number, slug, cwd)
        return {**d, "baseRefName": "release"} if int(number) == 2 else d
    prs.view = staticmethod(view)
    t = _check(prs, [1, 2])
    assert not t.ready and "different bases: main, release" in t.error


def test_brain_merge_ready_with_exits_by_the_answer(prs, monkeypatch, capsys):
    monkeypatch.setattr(mergeready, "gh_view", prs.view)
    monkeypatch.setattr(mergetogether, "chosen_tests", _none)
    base = ["merge-ready", "1", "--repo-dir", str(prs.repo), "--slug", "owner/lab", "--no-fetch"]
    assert cli.main([*base, "--with", "3", "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["ready"] and out["order"] == [1, 3] and len(out["stamps"]) == 2
    assert cli.main([*base, "--with", "2,3"]) == 1
    text = capsys.readouterr().out
    assert "not ready; merge order: #1, #2, #3" in text and "then  #2" in text and text.count("stamp: ") == 2
    assert cli.main([*base, "--test"]) == 2
    assert "--test and --python go with --with" in capsys.readouterr().err
